import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { check } from "prettier";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { formatAssetJson } from "./build.ts";
import { declaredVariants, ROOT } from "./catalog.ts";
import {
  buildPrompt,
  checkNewId,
  claudeArgs,
  DEFAULT_ROUNDS,
  describeEvent,
  draftAsset,
  draftPy,
  formatDryRun,
  parseArgs,
  plan,
  scaffold,
  shellQuote,
  SKILL_FILE,
  skillBody,
} from "./new.ts";
import { parseAsset, parseTags } from "./schema.ts";

let root: string;

function write(path: string, content: string): void {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), content);
}

const tags = () =>
  parseTags(JSON.parse(readFileSync(join(ROOT, "catalog/tags.json"), "utf8")));

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "propsmith-new-"));
  for (const file of [
    "catalog/tags.json",
    "catalog/textures.json",
    SKILL_FILE,
  ]) {
    mkdirSync(dirname(join(root, file)), { recursive: true });
    copyFileSync(join(ROOT, file), join(root, file));
  }
  write(
    "catalog/well_stone/asset.json",
    JSON.stringify({
      id: "well_stone",
      variants: ["well_stone", "well_stone_dry"],
    }),
  );
  write("catalog/well_stone/asset.py", "");
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

const BARREL = "A short oak barrel with three iron hoops.";

describe("parseArgs", () => {
  it("takes an id, a description, --rounds and --dry-run", () => {
    expect(parseArgs(["barrel_wood", BARREL])).toEqual({
      id: "barrel_wood",
      description: BARREL,
      rounds: DEFAULT_ROUNDS,
      dryRun: false,
    });
    expect(
      parseArgs(["--dry-run", "barrel_wood", `  ${BARREL} `, "--rounds", "2"]),
    ).toEqual({
      id: "barrel_wood",
      description: BARREL,
      rounds: 2,
      dryRun: true,
    });
  });

  it("refuses a bad id, a missing description and bad options", () => {
    expect(() => parseArgs(["BarrelWood", BARREL])).toThrow("snake_case");
    expect(() => parseArgs(["barrel_wood"])).toThrow("usage");
    expect(() => parseArgs(["barrel_wood", "  "])).toThrow("empty");
    expect(() => parseArgs(["barrel_wood", BARREL, "extra"])).toThrow("usage");
    for (const n of ["0", "11", "two", "1.5"])
      expect(() => parseArgs(["barrel_wood", BARREL, "--rounds", n])).toThrow(
        "--rounds",
      );
    expect(() => parseArgs(["barrel_wood", BARREL, "--rounds"])).toThrow(
      "--rounds",
    );
    expect(() => parseArgs(["barrel_wood", BARREL, "--fast"])).toThrow(
      "unknown option --fast",
    );
  });
});

describe("scaffold", () => {
  it("writes a draft asset.json that validates and a stub asset.py with the one variant", () => {
    expect(scaffold(root, "barrel_wood", BARREL)).toEqual([
      "catalog/barrel_wood/asset.json",
      "catalog/barrel_wood/asset.py",
    ]);
    const json = JSON.parse(
      readFileSync(join(root, "catalog/barrel_wood/asset.json"), "utf8"),
    ) as unknown;
    const prop = parseAsset(json, tags());
    expect(prop).toEqual(draftAsset("barrel_wood", BARREL));
    expect(prop).toMatchObject({
      id: "barrel_wood",
      name: "Barrel wood",
      description: BARREL,
      family: "barrel",
      variants: ["barrel_wood"],
      provenance: { source: "generated", prompt: BARREL },
    });
    const py = readFileSync(join(root, "catalog/barrel_wood/asset.py"), "utf8");
    expect(declaredVariants(py)).toEqual(["barrel_wood"]);
    expect(py).toContain(`"""${BARREL} (generated by npm run new)."""`);
    expect(py).toContain("raise NotImplementedError");
  });

  it("leaves a asset.json that the first npm run build turns Prettier-clean", async () => {
    scaffold(root, "barrel_wood", BARREL);
    const path = join(root, "catalog/barrel_wood/asset.json");
    const draft = readFileSync(path, "utf8");
    await formatAssetJson(root, "barrel_wood");
    const formatted = readFileSync(path, "utf8");
    expect(await check(formatted, { filepath: path })).toBe(true);
    expect(JSON.parse(formatted)).toEqual(JSON.parse(draft));
  });

  it("escapes a description that would end the docstring", () => {
    expect(draftPy("sign_wood", 'Says """hi""" \\ there')).toContain(
      '"""Says \\"\\"\\"hi\\"\\"\\" \\\\ there (generated',
    );
  });

  it("refuses an existing id and another prop's variant, writing nothing", () => {
    expect(() => scaffold(root, "well_stone", BARREL)).toThrow(
      'asset "well_stone" exists in catalog/well_stone',
    );
    expect(() => checkNewId(root, "well_stone_dry")).toThrow(
      '"well_stone_dry" is a variant of asset "well_stone"',
    );
    expect(readdirSync(join(root, "catalog")).sort()).toEqual([
      "tags.json",
      "textures.json",
      "well_stone",
    ]);
  });
});

describe("prompt and command", () => {
  it("strips the skill's front matter", () => {
    const skill = readFileSync(join(ROOT, SKILL_FILE), "utf8");
    expect(skill).toMatch(/^---\nname: prop\ndescription: .+\n---\n/);
    const body = skillBody(skill);
    expect(body.startsWith("# Props: write, build, check, look, fix")).toBe(
      true,
    );
    expect(body).not.toContain("name: prop");
    expect(skillBody("no front matter")).toBe("no front matter");
  });

  it("assembles the task from the id, description, rounds, textures and examples", () => {
    const prompt = buildPrompt({
      id: "barrel_wood",
      description: `${BARREL}\nIts lid is nailed shut.`,
      rounds: 3,
      textures: ["ambientcg:Wood049"],
      examples: ["cart_hand", "well_stone"],
    });
    expect(prompt).toContain(`> ${BARREL}\n> Its lid is nailed shut.`);
    expect(prompt).toContain("Write only in `catalog/barrel_wood/`");
    expect(prompt).toContain("`ambientcg:Wood049`");
    expect(prompt).toContain("`cart_hand`, `well_stone`");
    expect(prompt).toContain("`npm run build -- barrel_wood`");
    expect(prompt).toContain(".cache/assets/barrel_wood/review/");
    expect(prompt).toContain("At most 3 build rounds.");
    expect(
      buildPrompt({
        id: "x",
        description: "d",
        rounds: 1,
        textures: [],
        examples: [],
      }),
    ).toContain("At most 1 build round.");
  });

  it("limits claude to reading the repo, writing the prop folder and building the prop", () => {
    const args = claudeArgs("/repo", "barrel_wood", "PROMPT", "SKILL");
    expect(args.slice(0, 4)).toEqual([
      "-p",
      "PROMPT",
      "--append-system-prompt",
      "SKILL",
    ]);
    expect(args).toContain("--restricted");
    expect(args).toContain("--strict-mcp-config");
    const after = (flag: string) => args[args.indexOf(flag) + 1];
    expect(after("--tools")).toBe("Read,Edit,Write,Bash");
    expect(after("--permission-mode")).toBe("dontAsk");
    expect(after("--output-format")).toBe("stream-json");
    const start = args.indexOf("--allowedTools") + 1;
    expect(args.slice(start, args.indexOf("--permission-mode"))).toEqual([
      "Read(//repo/**)",
      "Edit(//repo/catalog/barrel_wood/**)",
      "Write(//repo/catalog/barrel_wood/**)",
      "Bash(npm run build -- barrel_wood)",
      "Bash(npm run build -- barrel_wood --*)",
    ]);
  });

  it("quotes for a shell", () => {
    expect(shellQuote(["claude", "-p", "it's a barrel", "Bash(npm *)"])).toBe(
      `claude -p 'it'\\''s a barrel' 'Bash(npm *)'`,
    );
  });
});

describe("--dry-run", () => {
  it("prints the scaffold, the command and the prompt, and writes nothing", () => {
    const args = parseArgs([
      "barrel_wood",
      BARREL,
      "--dry-run",
      "--rounds",
      "2",
    ]);
    const out = formatDryRun(plan(root, args));
    expect(out).toContain("dry run: nothing written, claude not started");
    expect(out).toContain("  catalog/barrel_wood/asset.json\n");
    expect(out).toContain("  catalog/barrel_wood/asset.py\n");
    expect(out).toContain("  claude -p '<the prompt below>' --append");
    expect(out).toContain(
      `--append-system-prompt '<${SKILL_FILE} without front matter>'`,
    );
    expect(out).not.toContain("# Props: write, build");
    expect(out).toContain("'Bash(npm run build -- barrel_wood)'");
    expect(out).toContain(`prompt:\nMake the catalogue asset \`barrel_wood\``);
    expect(out).toContain("At most 2 build rounds.");
    expect(out).toContain(
      "`ambientcg:PavingStones046`, `ambientcg:PavingStones128`, `ambientcg:Wood049`",
    );
    expect(out).toContain("existing assets as examples: `well_stone`");
    expect(existsSync(join(root, "catalog/barrel_wood"))).toBe(false);
  });

  it("refuses an existing id too", () => {
    expect(() =>
      plan(root, parseArgs(["well_stone", BARREL, "--dry-run"])),
    ).toThrow("exists");
  });
});

describe("describeEvent", () => {
  const line = (event: unknown) =>
    describeEvent("/repo", JSON.stringify(event));

  it("prints Claude's text and one line per tool call", () => {
    expect(
      line({
        type: "assistant",
        message: {
          content: [
            { type: "text", text: "  Writing the barrel.\n" },
            {
              type: "tool_use",
              name: "Write",
              input: { file_path: "/repo/catalog/barrel_wood/asset.py" },
            },
            {
              type: "tool_use",
              name: "Bash",
              input: { command: "npm run build -- barrel_wood\necho" },
            },
            {
              type: "tool_use",
              name: "Read",
              input: { file_path: "/tmp/x.png" },
            },
            { type: "thinking", thinking: "…" },
          ],
        },
      }),
    ).toEqual([
      "Writing the barrel.",
      "→ Write: catalog/barrel_wood/asset.py",
      "→ Bash: npm run build -- barrel_wood",
      "→ Read: /tmp/x.png",
    ]);
  });

  it("prints failed and denied tool calls, not successful ones", () => {
    expect(
      line({
        type: "user",
        message: {
          content: [
            { type: "tool_result", content: "fine" },
            {
              type: "tool_result",
              is_error: true,
              content: [{ type: "text", text: "Permission denied\nmore" }],
            },
            { type: "tool_result", is_error: true, content: "exit 1" },
          ],
        },
      }),
    ).toEqual(["  ✗ Permission denied", "  ✗ exit 1"]);
  });

  it("closes with turns, time and cost, and skips other events", () => {
    expect(
      line({
        type: "result",
        subtype: "success",
        is_error: false,
        num_turns: 14,
        duration_ms: 312_400,
        total_cost_usd: 1.234,
      }),
    ).toEqual(["claude done, 14 turns, 312 s, $1.23"]);
    expect(
      line({ type: "result", subtype: "error_max_turns", is_error: true }),
    ).toEqual(["claude stopped (error_max_turns)"]);
    expect(line({ type: "system", subtype: "init" })).toEqual([]);
    expect(describeEvent("/repo", "")).toEqual([]);
    expect(describeEvent("/repo", "not json")).toEqual(["not json"]);
  });
});
