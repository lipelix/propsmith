import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { format, resolveConfig } from "prettier";
import { z } from "zod";

/**
 * `catalog/measurements.json`: what Blender measured for every built asset, so `npm run check` can run the build checks
 * (bounds, ground, triangles, manifold, materials, anchors) in CI, which has no Blender. `npm run build` writes it from
 * each full build's `result.json`; only facts the checks read are kept (no file names, no timings), so a rebuild of the
 * same inputs writes the same bytes. `inputHash` ties an entry to the inputs it was measured from: an entry whose hash
 * no longer matches is stale. All lengths are metres in the asset's own space.
 */
export const MEASUREMENTS_FILE = "catalog/measurements.json";

const vec3 = z.tuple([z.number(), z.number(), z.number()]);

export const measuredVariantSchema = z
  .object({
    id: z.string().min(1),
    tris: z.number().int().min(0),
    bbox: z.object({ min: vec3, max: vec3 }).strict(),
    origin: vec3,
    nonManifoldEdges: z.number().int().min(0),
    /** `source`: `palette`, `ledger:<texture id>`, or null for a material not made by `propsmith.materials`. */
    materials: z.array(
      z.object({ name: z.string(), source: z.string().nullable() }).strict(),
    ),
    /** `size`: the extent of a sized anchor (fire, water spout or basin), from its empty's scale. */
    anchors: z.array(
      z.object({ name: z.string(), at: vec3, size: vec3.optional() }).strict(),
    ),
    textures: z.array(z.string()),
  })
  .strict();
export type MeasuredVariant = z.infer<typeof measuredVariantSchema>;

const measuredAssetSchema = z
  .object({
    inputHash: z.string().regex(/^[0-9a-f]{64}$/),
    libVersion: z.number().int(),
    blender: z.string(),
    variants: z.array(measuredVariantSchema).min(1),
  })
  .strict();
export type MeasuredAsset = z.infer<typeof measuredAssetSchema>;

export const measurementsSchema = z
  .object({
    schema: z.literal(1),
    note: z.string(),
    assets: z.record(z.string(), measuredAssetSchema),
  })
  .strict();
export type Measurements = z.infer<typeof measurementsSchema>;

/** What the checks read of a build: a build result or a committed measurement both fit. */
export interface Measured {
  /** The one variant built, or null for a full build (a committed measurement is always full). */
  only: string | null;
  variants: readonly MeasuredVariant[];
}

const NOTE =
  "Generated by npm run build from each full build's result.json; npm run check reads it. Do not edit.";

/** A full build result, as far as the measurements need it. */
export interface FullResult {
  id: string;
  inputHash: string;
  only: string | null;
  libVersion: number;
  blender: string;
  variants: readonly MeasuredVariant[];
}

/** The measurement of a full build: the facts the checks read, nothing run-specific but the Blender version. */
export function measuredOf(result: FullResult): MeasuredAsset {
  if (result.only !== null)
    throw new Error(`${result.id}: only ${result.only} was built`);
  return {
    inputHash: result.inputHash,
    libVersion: result.libVersion,
    blender: result.blender,
    variants: result.variants.map((v) => ({
      id: v.id,
      tris: v.tris,
      bbox: v.bbox,
      origin: v.origin,
      nonManifoldEdges: v.nonManifoldEdges,
      materials: v.materials,
      anchors: v.anchors,
      textures: v.textures,
    })),
  };
}

/** A committed measurement as the checks read it. */
export const asMeasured = (m: MeasuredAsset): Measured => ({
  only: null,
  variants: m.variants,
});

/** The committed measurements under `root`, or none. */
export function readMeasurements(root: string): Measurements {
  const path = join(root, MEASUREMENTS_FILE);
  if (!existsSync(path)) return { schema: 1, note: NOTE, assets: {} };
  const parsed = measurementsSchema.safeParse(
    JSON.parse(readFileSync(path, "utf8")),
  );
  if (!parsed.success)
    throw new Error(`${MEASUREMENTS_FILE}: ${z.prettifyError(parsed.error)}`);
  return parsed.data;
}

/** `entries` replace their assets' measurements, sorted by id; only assets in `keep` are left. */
export function mergeMeasurements(
  current: Measurements,
  entries: readonly { id: string; measured: MeasuredAsset }[],
  keep: ReadonlySet<string>,
): Measurements {
  const all: Record<string, MeasuredAsset> = { ...current.assets };
  for (const { id, measured } of entries) all[id] = measured;
  const assets: Record<string, MeasuredAsset> = {};
  for (const id of Object.keys(all).sort())
    if (keep.has(id)) assets[id] = all[id] as MeasuredAsset;
  return { schema: 1, note: NOTE, assets };
}

/** Writes the merged measurements under `root`, formatted by the repository's Prettier config. */
export async function writeMeasurements(
  root: string,
  entries: readonly { id: string; measured: MeasuredAsset }[],
  keep: ReadonlySet<string>,
): Promise<void> {
  const path = join(root, MEASUREMENTS_FILE);
  const next = mergeMeasurements(readMeasurements(root), entries, keep);
  const options = await resolveConfig(path);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(
    path,
    await format(JSON.stringify(next), { ...options, parser: "json" }),
  );
}
