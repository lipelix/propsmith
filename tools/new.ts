import { spawn, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createInterface } from "node:readline";
import { assetIds } from "./build.ts";
import { CATALOG_DIR, ROOT } from "./catalog.ts";
import { SNAKE } from "./ids.ts";
import { type Asset, LICENCE, parseAsset, parseTags } from "./schema.ts";
import { ensureTextures, readLedger } from "./textures.ts";

/**
 * `npm run new -- <id> "<description>" [--rounds n] [--dry-run]` (needs Blender and the Claude Code CLI logged in; CI
 * never generates).
 *
 * Scaffolds `catalog/<id>/` with a draft `asset.json` (valid, with the description as the generation prompt) and a
 * stub `asset.py`, fetches the ledger textures, then runs `claude -p` headless in restricted mode with the `prop` skill
 * (`skills/prop/SKILL.md`) appended to its system prompt. Claude may read the repository, write only in the
 * asset's folder and run only `npm run build -- <id>`; it loops write → build → checks → snapshots → fix for at
 * most `--rounds` rounds (5). Its tool calls print as they happen. Finally `npm run build` prints the check report and
 * sets the exit code. `--dry-run` writes nothing and prints the scaffold, the command and the prompt.
 */
export const SKILL_FILE = "skills/prop/SKILL.md";
const TAGS_FILE = "catalog/tags.json";
export const DEFAULT_ROUNDS = 5;
const MAX_ROUNDS = 10;
/** The tools Claude gets at all; the allow rules below narrow what it may do with them. */
const TOOLS = ["Read", "Edit", "Write", "Bash"];

export interface Args {
  id: string;
  description: string;
  rounds: number;
  dryRun: boolean;
}

export function parseArgs(argv: readonly string[]): Args {
  const positional: string[] = [];
  let rounds = DEFAULT_ROUNDS;
  let dryRun = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i] ?? "";
    if (a === "--dry-run") dryRun = true;
    else if (a === "--rounds") {
      const v = argv[++i] ?? "";
      const n = Number(v);
      if (!/^\d+$/.test(v) || n < 1 || n > MAX_ROUNDS)
        throw new Error(
          `--rounds needs a whole number from 1 to ${MAX_ROUNDS}`,
        );
      rounds = n;
    } else if (a.startsWith("--")) throw new Error(`unknown option ${a}`);
    else positional.push(a);
  }
  const usage =
    'usage: npm run new -- <id> "<description>" [--rounds n] [--dry-run]';
  if (positional.length !== 2) throw new Error(usage);
  const [id = "", description = ""] = positional;
  if (!SNAKE.test(id))
    throw new Error(`id "${id}" must be snake_case (barrel_wood)`);
  if (description.trim() === "")
    throw new Error(`the description is empty\n${usage}`);
  return { id, description: description.trim(), rounds, dryRun };
}

/** `barrel_wood` → `Barrel wood`: a placeholder Claude replaces. */
const title = (id: string): string => {
  const words = id.split("_").join(" ");
  return words.charAt(0).toUpperCase() + words.slice(1);
};

/**
 * The draft `asset.json`: valid against the schema so the first build runs, with neutral guesses (a 1 m box, decor,
 * family from the id's first word) the skill tells Claude to replace. Provenance records the description as the prompt.
 */
export function draftAsset(id: string, description: string): Asset {
  return {
    schema: 1,
    id,
    name: title(id),
    description,
    category: "decor",
    family: id.split("_")[0] ?? id,
    tags: [],
    aliases: [],
    variants: [id],
    size: { x: 1, y: 1, z: 1 },
    anchors: [],
    closed: false,
    provenance: { source: "generated", prompt: description },
    licence: LICENCE,
  };
}

/** The stub `asset.py`: one variant that fails the build until Claude writes it. */
export function draftPy(id: string, description: string): string {
  const doc = description
    .replaceAll("\\", "\\\\")
    .replaceAll('"""', '\\"\\"\\"');
  return `"""${doc} (generated by npm run new)."""
from propsmith import prop


@prop
def ${id}():
    raise NotImplementedError("npm run new: Claude writes this variant")
`;
}

/** The files `scaffold` writes, relative to the root: path → content. */
export function scaffoldFiles(
  id: string,
  description: string,
): Record<string, string> {
  const dir = `${CATALOG_DIR}/${id}`;
  return {
    [`${dir}/asset.json`]: `${JSON.stringify(draftAsset(id, description), null, 2)}\n`,
    [`${dir}/asset.py`]: draftPy(id, description),
  };
}

/** Refuses an id whose folder exists or that another asset's variants already use. */
export function checkNewId(root: string, id: string): void {
  const dir = join(root, CATALOG_DIR, id);
  if (existsSync(dir))
    throw new Error(
      `asset "${id}" exists in ${relative(root, dir)}: pick another id, or fix it with the prop skill and npm run build -- ${id}`,
    );
  for (const other of assetIds(root)) {
    const json = join(root, CATALOG_DIR, other, "asset.json");
    if (!existsSync(json)) continue;
    const variants = (
      JSON.parse(readFileSync(json, "utf8")) as { variants?: unknown }
    ).variants;
    if (Array.isArray(variants) && variants.includes(id))
      throw new Error(
        `"${id}" is a variant of asset "${other}": pick another id`,
      );
  }
}

/** Writes the draft asset folder, after checking the draft against the schema and the vocabulary. */
export function scaffold(
  root: string,
  id: string,
  description: string,
): string[] {
  checkNewId(root, id);
  const tags = parseTags(
    JSON.parse(readFileSync(join(root, TAGS_FILE), "utf8")),
  );
  parseAsset(draftAsset(id, description), tags);
  const files = scaffoldFiles(id, description);
  mkdirSync(join(root, CATALOG_DIR, id), { recursive: true });
  for (const [path, content] of Object.entries(files))
    writeFileSync(join(root, path), content);
  return Object.keys(files);
}

/** The skill without its front matter: what is appended to Claude's system prompt. */
export function skillBody(markdown: string): string {
  return markdown.replace(/^---\n[\s\S]*?\n---\n+/, "").trim();
}

export interface PromptInput {
  id: string;
  description: string;
  rounds: number;
  /** Ledger texture ids Claude may use (downloaded by `npm run new` before it starts). */
  textures: readonly string[];
  /** Existing assets to learn from. */
  examples: readonly string[];
}

/** The task Claude gets; the rules are in the skill. */
export function buildPrompt(p: PromptInput): string {
  const dir = `${CATALOG_DIR}/${p.id}`;
  const list = (xs: readonly string[]) =>
    xs.length > 0 ? xs.map((x) => `\`${x}\``).join(", ") : "none";
  return [
    `Make the catalogue asset \`${p.id}\` from this description:`,
    "",
    ...p.description.split("\n").map((line) => `> ${line}`),
    "",
    `\`npm run new\` scaffolded \`${dir}/\`: \`asset.json\` is a draft (replace every field except \`id\` and \`provenance\`; keep the description's meaning) and \`asset.py\` is a stub that fails the build. Follow the prop skill in your system prompt.`,
    "",
    `- Write only in \`${dir}/\`. Read anything in the repository: the library \`lib/propsmith/\`, the tag vocabulary \`${TAGS_FILE}\`, the schema \`tools/schema.ts\`, and the existing assets as examples: ${list(p.examples)}.`,
    `- Ledger textures you may use (already downloaded): ${list(p.textures)}.`,
    `- The only command you may run is \`npm run build -- ${p.id}\` (add \`--force\` to rebuild without changes, \`--only <variant>\` for one variant). Its check report and the snapshots in \`.cache/assets/${p.id}/review/\` are your feedback.`,
    `- At most ${p.rounds} build round${p.rounds === 1 ? "" : "s"}. Stop earlier when every check is OK and the snapshots match the description.`,
    "- Finish with the short final report the skill describes.",
  ].join("\n");
}

/** The `claude` arguments: headless, restricted, writes confined to the asset folder, one command allowed. */
export function claudeArgs(
  root: string,
  id: string,
  prompt: string,
  system: string,
): string[] {
  const dir = `/${join(root, CATALOG_DIR, id)}`; // `//abs/path`: an absolute path in a permission rule
  const build = `npm run build -- ${id}`;
  return [
    "-p",
    prompt,
    "--append-system-prompt",
    system,
    "--restricted",
    "--strict-mcp-config",
    "--tools",
    TOOLS.join(","),
    "--allowedTools",
    `Read(/${root}/**)`,
    `Edit(${dir}/**)`,
    `Write(${dir}/**)`,
    `Bash(${build})`,
    `Bash(${build} --*)`,
    "--permission-mode",
    "dontAsk",
    "--output-format",
    "stream-json",
    "--verbose",
  ];
}

/** Quotes arguments for a POSIX shell, for `--dry-run`. */
export function shellQuote(args: readonly string[]): string {
  return args
    .map((a) =>
      /^[\w@%+=:,./-]+$/.test(a) ? a : `'${a.replaceAll("'", `'\\''`)}'`,
    )
    .join(" ");
}

const firstLine = (s: string, max = 160): string => {
  const line = s.trim().split("\n")[0] ?? "";
  return line.length > max ? `${line.slice(0, max - 1)}…` : line;
};

/** What a tool call does, in one line: the command, or the file relative to the root. */
function describeTool(
  root: string,
  name: string,
  input: Record<string, unknown>,
): string {
  const path = typeof input.file_path === "string" ? input.file_path : null;
  if (name === "Bash" && typeof input.command === "string")
    return `${name}: ${firstLine(input.command)}`;
  if (path !== null)
    return `${name}: ${path.startsWith(root) ? relative(root, path) : path}`;
  return name;
}

interface StreamBlock {
  type?: string;
  text?: string;
  name?: string;
  input?: Record<string, unknown>;
  is_error?: boolean;
  content?: unknown;
}

/**
 * One line of `claude --output-format stream-json` → the lines to print: Claude's text, `→ Tool: what` per tool call,
 * `  ✗ why` per failed or denied call, and the closing summary. Other events print nothing.
 */
export function describeEvent(root: string, json: string): string[] {
  let event: {
    type?: string;
    subtype?: string;
    message?: { content?: StreamBlock[] };
    num_turns?: number;
    duration_ms?: number;
    total_cost_usd?: number;
    is_error?: boolean;
  };
  try {
    event = JSON.parse(json) as typeof event;
  } catch {
    return json.trim() === "" ? [] : [json];
  }
  const blocks = event.message?.content ?? [];
  if (event.type === "assistant")
    return blocks.flatMap((b) => {
      if (b.type === "text" && b.text?.trim()) return [b.text.trim()];
      if (b.type === "tool_use")
        return [`→ ${describeTool(root, b.name ?? "?", b.input ?? {})}`];
      return [];
    });
  if (event.type === "user")
    return blocks
      .filter((b) => b.type === "tool_result" && b.is_error === true)
      .map((b) => {
        const content = Array.isArray(b.content)
          ? (b.content as StreamBlock[]).map((c) => c.text ?? "").join("\n")
          : String(b.content ?? "");
        return `  ✗ ${firstLine(content)}`;
      });
  if (event.type === "result") {
    const parts = [
      `claude ${event.is_error === true ? `stopped (${event.subtype ?? "error"})` : "done"}`,
      ...(event.num_turns !== undefined ? [`${event.num_turns} turns`] : []),
      ...(event.duration_ms !== undefined
        ? [`${Math.round(event.duration_ms / 1000)} s`]
        : []),
      ...(event.total_cost_usd !== undefined
        ? [`$${event.total_cost_usd.toFixed(2)}`]
        : []),
    ];
    return [parts.join(", ")];
  }
  return [];
}

/** Runs claude, printing its progress; resolves to its exit code. */
export function runClaude(
  root: string,
  args: readonly string[],
): Promise<number> {
  return new Promise((resolve, reject) => {
    const child = spawn("claude", args, {
      cwd: root,
      stdio: ["ignore", "pipe", "inherit"],
    });
    child.on("error", (error: NodeJS.ErrnoException) =>
      reject(
        error.code === "ENOENT"
          ? new Error(
              "claude not found: install Claude Code and log in (claude), then run again",
            )
          : error,
      ),
    );
    createInterface({ input: child.stdout }).on("line", (line) => {
      for (const out of describeEvent(root, line)) console.log(out);
    });
    child.on("close", (code) => resolve(code ?? 1));
  });
}

/** Everything `main` needs to know before it acts, so `--dry-run` shows exactly what a real run does. */
export function plan(
  root: string,
  args: Args,
): { files: string[]; command: string[]; prompt: string } {
  checkNewId(root, args.id);
  const ledger = readLedger(root);
  const prompt = buildPrompt({
    id: args.id,
    description: args.description,
    rounds: args.rounds,
    textures: ledger ? Object.keys(ledger.textures).sort() : [],
    examples: assetIds(root),
  });
  const system = skillBody(readFileSync(join(root, SKILL_FILE), "utf8"));
  return {
    files: Object.keys(scaffoldFiles(args.id, args.description)),
    command: ["claude", ...claudeArgs(root, args.id, prompt, system)],
    prompt,
  };
}

/** The `--dry-run` output: the scaffold, the command (the prompt and the system prompt elided) and the prompt. */
export function formatDryRun(p: ReturnType<typeof plan>): string {
  const elided: Record<string, string> = {
    "-p": "<the prompt below>",
    "--append-system-prompt": `<${SKILL_FILE} without front matter>`,
  };
  const shown = p.command.map((a, i) => elided[p.command[i - 1] ?? ""] ?? a);
  return [
    "dry run: nothing written, claude not started",
    "",
    "would scaffold:",
    ...p.files.map((f) => `  ${f}`),
    "",
    "would run (in the repository root):",
    `  ${shellQuote(shown)}`,
    "",
    "prompt:",
    p.prompt,
  ].join("\n");
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  const p = plan(ROOT, args);
  if (args.dryRun) {
    console.log(formatDryRun(p));
    return;
  }
  await ensureTextures(ROOT, []);
  for (const file of scaffold(ROOT, args.id, args.description))
    console.log(`wrote ${file}`);
  console.log(`claude: generating ${args.id}, at most ${args.rounds} rounds`);
  const [cmd = "claude", ...rest] = p.command;
  const code = await runClaude(ROOT, rest);
  if (code !== 0) console.error(`${cmd} exited with ${code}`);
  console.log("\nfinal check report:");
  const report = spawnSync("npm", ["run", "--silent", "build", "--", args.id], {
    cwd: ROOT,
    stdio: "inherit",
  });
  if (code !== 0 || report.status !== 0) process.exit(1);
}

if (process.argv[1]?.endsWith("tools/new.ts") === true) {
  try {
    await main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
