"""A village temple's dressed stone altar on a plinth step, a carved band under an overhanging top slab, a dull red
altar cloth and three ivory candles in iron dishes (generated by npm run new)."""
import random

from propsmith import anchor, prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder

# About 1.4 m wide (x), 0.8 m deep (y) and 1.15 m high with the candles. The altar stands behind the origin (+y),
# its back 0.72 m from it, so it can go against a wall.
BACK = 0.72  # y of the plinth's back face
PLINTH_W, PLINTH_D, PLINTH_H = 1.42, 0.80, 0.12
BODY_W, BODY_D = 1.24, 0.62
BAND_W, BAND_D, BAND_H = 1.28, 0.66, 0.08
TOP_W, TOP_D, TOP_H = 1.34, 0.72, 0.10
H = 0.95  # top of the slab
CY = BACK - PLINTH_D / 2  # centre line of the altar in y

CLOTH_W, CLOTH_T, CLOTH_DROP = 0.62, 0.008, 0.36
DISH_R, DISH_H = 0.07, 0.018
CANDLE_R, CANDLE_H = 0.032, 0.14
CANDLE_X = 0.46

STONE = (0.36, 0.34, 0.30)
STONE_OLD = (0.32, 0.305, 0.27)
CLOTH = (0.15, 0.07, 0.055)  # a dull madder red, not too saturated
HEM = (0.34, 0.26, 0.13)
IRON = (0.05, 0.05, 0.05)
WAX = (0.50, 0.47, 0.38)
FLAME = (0.50, 0.42, 0.18)


@prop
def altar_stone():
    rnd = random.Random(11)
    stone = material("altar_stone_stone", STONE, vary=0.2, scale=8)
    old = material("altar_stone_old", STONE_OLD, vary=0.25, scale=10)
    cloth = material("altar_stone_cloth", CLOTH, rough=0.95, vary=0.2, scale=30)
    hem = material("altar_stone_hem", HEM, rough=0.9, vary=0.15, scale=40)
    iron = material("altar_stone_iron", IRON, rough=0.5, metal=0.8)
    wax = material("altar_stone_wax", WAX, rough=0.6, vary=0.08, crevice=0.2)
    flame = material("altar_stone_flame", FLAME, rough=0.4, vary=0.05, crevice=0)

    # Plinth step: two long slabs, slightly uneven.
    for i, s in enumerate((-1, 1)):
        w = PLINTH_W / 2 - 0.006
        box(
            f"plinth_{i}",
            (w, PLINTH_D * rnd.uniform(0.985, 1.0), PLINTH_H * rnd.uniform(0.96, 1.0)),
            (s * PLINTH_W / 4, CY, PLINTH_H / 2 * rnd.uniform(0.96, 1.0)),
            old if i else stone,
            rot=(0, 0, rnd.uniform(-0.6, 0.6)),
            bevel=0.02,
        )

    # Body: dressed blocks in two courses with offset joints.
    body_h = H - TOP_H - BAND_H - PLINTH_H
    course_h = body_h / 2
    for c in range(2):
        z0 = PLINTH_H + c * course_h
        cuts = [0.0, 0.5, 1.0] if c == 0 else [0.0, 0.3, 0.7, 1.0]
        for k in range(len(cuts) - 1):
            x0 = -BODY_W / 2 + cuts[k] * BODY_W
            x1 = -BODY_W / 2 + cuts[k + 1] * BODY_W
            box(
                f"block_{c}_{k}",
                (x1 - x0 - 0.008, BODY_D * rnd.uniform(0.99, 1.0), course_h - 0.008),
                ((x0 + x1) / 2, CY, z0 + course_h / 2),
                old if rnd.random() < 0.35 else stone,
                rot=(0, 0, rnd.uniform(-0.5, 0.5)),
                bevel=0.016,
            )

    # Carved band: a recessed course with a row of raised dentils on the front and the sides.
    zb = H - TOP_H - BAND_H
    box("band", (BAND_W - 0.06, BAND_D - 0.06, BAND_H), (0, CY, zb + BAND_H / 2), stone, bevel=0.008)
    box("band_fillet", (BAND_W, BAND_D, 0.022), (0, CY, zb + 0.011), stone, bevel=0.008)
    dent = 0.05
    n_front = 11
    for i in range(n_front):
        x = -BAND_W / 2 + 0.06 + i * (BAND_W - 0.12) / (n_front - 1)
        for s in (-1, 1):
            box(
                f"dentil_y{s}_{i}",
                (dent, 0.035, BAND_H - 0.03),
                (x, CY + s * (BAND_D / 2 - 0.03), zb + 0.022 + (BAND_H - 0.03) / 2),
                stone,
                bevel=0.006,
            )
    n_side = 6
    for i in range(n_side):
        y = CY - BAND_D / 2 + 0.07 + i * (BAND_D - 0.14) / (n_side - 1)
        for s in (-1, 1):
            box(
                f"dentil_x{s}_{i}",
                (0.035, dent, BAND_H - 0.03),
                (s * (BAND_W / 2 - 0.03), y, zb + 0.022 + (BAND_H - 0.03) / 2),
                stone,
                bevel=0.006,
            )

    # Overhanging top slab.
    box("top", (TOP_W, TOP_D, TOP_H), (0, CY, H - TOP_H / 2), stone, rot=(0, 0, 0.4), bevel=0.022)

    # Altar cloth: over the top from back to front, folded over the front edge and hanging down.
    front = CY - TOP_D / 2
    box("cloth_top", (CLOTH_W, TOP_D - 0.04, CLOTH_T), (0, CY - 0.02, H + CLOTH_T / 2), cloth, bevel=0.003)
    box("cloth_fold", (CLOTH_W, 0.03, 0.03), (0, front + 0.002, H - 0.006), cloth, bevel=0.012)
    box(
        "cloth_drop", (CLOTH_W, CLOTH_T, CLOTH_DROP), (0, front - CLOTH_T / 2 - 0.004, H - CLOTH_DROP / 2), cloth,
        rot=(-1.5, 0, 0), bevel=0.003,
    )
    box(
        "cloth_hem", (CLOTH_W + 0.004, CLOTH_T + 0.006, 0.04),
        (0, front - CLOTH_T / 2 - 0.009, H - CLOTH_DROP + 0.022), hem, rot=(-1.5, 0, 0), bevel=0.003,
    )
    box("cloth_stripe", (0.06, CLOTH_T + 0.004, CLOTH_DROP - 0.08),
        (0, front - CLOTH_T / 2 - 0.007, H - CLOTH_DROP / 2 + 0.03), hem, rot=(-1.5, 0, 0), bevel=0.002)

    # Three candles in iron dishes; the flames carry the light anchors.
    cy = CY + 0.1
    for name, x in (("left", -CANDLE_X), ("centre", 0.0), ("right", CANDLE_X)):
        z = H + (CLOTH_T if x == 0 else 0)
        h = CANDLE_H * rnd.uniform(0.85, 1.05)
        cylinder(f"dish_{name}", DISH_R, DISH_H, (x, cy, z), iron, r_top=DISH_R * 1.15, segments=12, bevel=0.004)
        cylinder(f"candle_{name}", CANDLE_R, h, (x, cy, z + DISH_H - 0.004), wax, segments=10, bevel=0.005)
        fz = z + DISH_H - 0.004 + h + 0.028
        blob(f"flame_{name}", 0.016, (x, cy, fz), flame, squash=(1, 1, 1.9), subdiv=1, seed=3, jitter=0.05)
        anchor(f"light:candle_{name}", (x, cy, fz))
