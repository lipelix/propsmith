"""A weathered stone statue of a robed, hooded figure with hands folded on a point-down sword, on a moulded square
plinth (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder

# About 2.35 m high: a 0.5 m plinth and a ~1.86 m figure.
PLINTH_W, PLINTH_H = 0.9, 0.5
FIGURE_H = 1.86
Z0 = PLINTH_H  # the figure stands on the plinth top
ROBE_R, ROBE_R_TOP, ROBE_H = 0.3, 0.19, 1.33
ROBE_DEPTH = 0.75  # the robe is flattened front to back
SWORD_Y = -0.31  # the sword stands in front of the robe (front is -y)

STONE = (0.29, 0.265, 0.225)
STONE_OLD = (0.24, 0.225, 0.195)
FIGURE = (0.31, 0.29, 0.25)
SHADOW = (0.07, 0.065, 0.058)
MOSS = (0.075, 0.11, 0.035)


def limb(name, r, r_top, a, b, mat, segments=10, bevel=0):
    """A frustum from point `a` to point `b`."""
    dx, dy, dz = (b[i] - a[i] for i in range(3))
    length = math.sqrt(dx * dx + dy * dy + dz * dz)
    rx = math.degrees(math.asin(-dy / length))
    ry = math.degrees(math.atan2(dx, dz))
    return cylinder(name, r, length, a, mat, r_top=r_top, segments=segments, rot=(rx, ry, 0), bevel=bevel)


@prop
def statue_stone():
    rnd = random.Random(11)
    stone = material("statue_plinth", STONE, vary=0.25, scale=8)
    old = material("statue_plinth_old", STONE_OLD, vary=0.3, scale=8)
    fig = material("statue_figure", FIGURE, vary=0.3, scale=5, crevice=0.75)
    shadow = material("statue_hood_shadow", SHADOW, vary=0.1, crevice=0)
    moss = material("statue_moss", MOSS, vary=0.35, scale=20)

    # Plinth: a wide footing, two courses of dressed blocks, then a moulded cornice.
    W = PLINTH_W
    box("footing", (W + 0.06, W + 0.06, 0.1), (0, 0, 0.05), old, bevel=0.02)
    course_h = 0.135
    for c in range(2):
        for i in range(2):
            along = (i - 0.5) * W / 2
            size = (W / 2 - 0.012, W - 0.04, course_h - 0.008) if c % 2 == 0 else (W - 0.04, W / 2 - 0.012, course_h - 0.008)
            at = (along, 0, 0.1 + course_h * c + course_h / 2) if c % 2 == 0 else (0, along, 0.1 + course_h * c + course_h / 2)
            box(
                f"block_{c}_{i}",
                (size[0] * rnd.uniform(0.98, 1.0), size[1] * rnd.uniform(0.98, 1.0), size[2]),
                at,
                old if rnd.random() < 0.4 else stone,
                rot=(0, 0, rnd.uniform(-1, 1)),
                bevel=0.016,
            )
    top_courses = 0.1 + 2 * course_h
    box("moulding_cove", (W - 0.02, W - 0.02, 0.05), (0, 0, top_courses + 0.025), stone, bevel=0.022)
    box("moulding_fillet", (W + 0.02, W + 0.02, 0.035), (0, 0, top_courses + 0.05 + 0.0175), stone, bevel=0.012)
    cap_h = PLINTH_H - (top_courses + 0.085)
    box("moulding_cap", (W + 0.06, W + 0.06, cap_h), (0, 0, PLINTH_H - cap_h / 2), stone, bevel=0.02)

    # Moss creeping at the foot of the plinth.
    spots = [(-0.47, -0.3), (-0.3, -0.49), (0.42, -0.48), (0.49, -0.1), (0.48, 0.3), (-0.2, 0.48), (-0.48, 0.4)]
    for i, (x, y) in enumerate(spots):
        r = rnd.uniform(0.09, 0.13)
        blob(f"moss_{i}", r, (x, y, r * 0.42), moss, squash=(1.4, 1.1, 0.36), subdiv=1, seed=40 + i, jitter=0.15)

    # Robe: a tapered, flattened bell with a hem and a few heavy folds.
    robe = cylinder("robe", ROBE_R, ROBE_H, (0, 0, Z0), fig, r_top=ROBE_R_TOP, segments=16, bevel=0)
    robe.scale = (1, ROBE_DEPTH, 1)
    hem = cylinder("hem", ROBE_R + 0.02, 0.06, (0, 0, Z0), fig, segments=16, bevel=0.012)
    hem.scale = (1, ROBE_DEPTH + 0.02, 1)
    taper = math.degrees(math.atan2(ROBE_R - ROBE_R_TOP, ROBE_H))
    for i, a_deg in enumerate((-150, -115, -65, -30, 15, 60, 100, 140, 180)):
        a = math.radians(a_deg + rnd.uniform(-6, 6))
        rr = ROBE_R - 0.005
        h = ROBE_H * rnd.uniform(0.62, 0.8)
        t = taper * rnd.uniform(0.9, 1.1)
        cylinder(
            f"fold_{i}",
            rnd.uniform(0.04, 0.055),
            h,
            (rr * math.cos(a), rr * ROBE_DEPTH * math.sin(a), Z0 + 0.03),
            fig,
            r_top=0.012,
            segments=8,
            rot=(t * math.sin(a), -t * math.cos(a), 0),
            bevel=0,
        )

    # Shoulders, hood with a shadowed face, and a hood drape over the back.
    sh_z = Z0 + ROBE_H - 0.02
    blob("shoulders", 0.24, (0, 0.01, sh_z), fig, squash=(1.05, 0.68, 0.42), subdiv=2, seed=3, jitter=0.04)
    hood_z = Z0 + FIGURE_H - 0.22
    blob("hood", 0.16, (0, 0.02, hood_z), fig, squash=(0.92, 1.0, 1.25), subdiv=2, seed=5, jitter=0.05)
    blob("hood_peak", 0.08, (0, 0.05, hood_z + 0.12), fig, squash=(0.8, 1.0, 1.0), subdiv=1, seed=6, jitter=0.05)
    blob("hood_drape", 0.17, (0, 0.08, sh_z + 0.08), fig, squash=(0.95, 0.7, 0.9), subdiv=2, seed=8, jitter=0.05)
    blob("face", 0.085, (0, -0.105, hood_z - 0.03), shadow, squash=(0.9, 0.45, 1.15), subdiv=1, seed=9, jitter=0.03)

    # Sword: point down on the plinth in front of the figure.
    stone_dark = material("statue_sword", (0.27, 0.255, 0.225), vary=0.2, scale=10, crevice=0.6)
    blade_bot, blade_top = Z0 + 0.06, Z0 + 0.86
    box("blade", (0.07, 0.022, blade_top - blade_bot), (0, SWORD_Y, (blade_bot + blade_top) / 2), stone_dark, bevel=0.008)
    box("blade_point", (0.05, 0.02, 0.05), (0, SWORD_Y, Z0 + 0.04), stone_dark, rot=(0, 45, 0), bevel=0.006)
    box("guard", (0.3, 0.05, 0.05), (0, SWORD_Y, blade_top + 0.025), stone_dark, bevel=0.012)
    cylinder("grip", 0.022, 0.14, (0, SWORD_Y, blade_top + 0.05), stone_dark, segments=8, bevel=0.004)
    pommel_z = blade_top + 0.21
    blob("pommel", 0.04, (0, SWORD_Y, pommel_z), stone_dark, subdiv=1, seed=12, jitter=0.04)

    # Arms: wide sleeves from the shoulders to hands folded over the pommel.
    hands = (0, SWORD_Y + 0.01, pommel_z + 0.04)
    for s in (-1, 1):
        shoulder = (s * 0.2, -0.02, sh_z + 0.02)
        wrist = (s * 0.07, SWORD_Y + 0.06, hands[2] - 0.01)
        limb(f"sleeve_{s}", 0.08, 0.105, shoulder, wrist, fig, segments=12, bevel=0)
    blob("hands", 0.07, hands, fig, squash=(1.35, 0.85, 0.7), subdiv=2, seed=14, jitter=0.06)
