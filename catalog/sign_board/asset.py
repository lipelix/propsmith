"""A hanging wooden inn sign: a square timber post on a small stone footing with a short arm at the top, and a painted
plank hanging under the arm on two short chains, a faded ochre tankard on its dark face (generated by npm run
new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

# The post top is at 2.2 m, its cap about 2.27 m.
FOOT_W, FOOT_TOP_W, FOOT_H = 0.42, 0.34, 0.24  # stone footing: square, tapering
POST = 0.15  # post section
POST_X = -0.5  # post stands towards -x so the board hangs near the centre
POST_TOP = 2.2
CAP_H = 0.07
ARM_TOP = 2.12  # top of the arm
ARM_H, ARM_D = 0.1, 0.1  # arm section
ARM_END = 0.55  # arm tip, along +x
BRACE_Z = 1.72  # where the diagonal brace meets the post
BOARD_W, BOARD_H, BOARD_T = 0.7, 0.5, 0.04  # the painted plank
BOARD_X = 0.12  # board centre along x
CHAIN_LEN = 0.16  # from the arm underside to the board top
CHAIN_DX = 0.27  # chains at BOARD_X +- CHAIN_DX

STONE = (0.3, 0.27, 0.23)
WOOD = (0.17, 0.1, 0.055)
WOOD_OLD = (0.14, 0.085, 0.05)
BOARD = (0.075, 0.05, 0.035)  # dark painted ground
FRAME = (0.13, 0.08, 0.045)
OCHRE = (0.45, 0.28, 0.08)  # faded warm ochre paint
FOAM = (0.42, 0.36, 0.25)  # faded cream
IRON = (0.045, 0.045, 0.045)


@prop
def sign_board():
    rnd = random.Random(11)
    stone = material("sign_board_stone", STONE, vary=0.25, scale=9, crevice=0.6)
    wood = material("sign_board_wood", WOOD, vary=0.3, scale=16)
    wood_old = material("sign_board_wood_old", WOOD_OLD, vary=0.3, scale=14)
    board = material("sign_board_board", BOARD, vary=0.25, scale=12)
    frame = material("sign_board_frame", FRAME, vary=0.25, scale=14)
    ochre = material("sign_board_paint", OCHRE, vary=0.3, scale=18, crevice=0.3)
    foam = material("sign_board_foam", FOAM, vary=0.25, scale=18, crevice=0.3)
    iron = material("sign_board_iron", IRON, rough=0.55, vary=0.2, scale=20, metal=0.6)

    # Stone footing: a squat tapered block.
    r_bot, r_top = FOOT_W / math.sqrt(2), FOOT_TOP_W / math.sqrt(2)
    cylinder("foot", r_bot, FOOT_H, (POST_X, 0, 0), stone, r_top=r_top, segments=4,
             rot=(0, 0, 45 + rnd.uniform(-3, 3)), bevel=0.02)

    # Timber post with a pyramid cap.
    post_h = POST_TOP - FOOT_H + 0.02
    box("post", (POST, POST, post_h), (POST_X, 0, FOOT_H - 0.02 + post_h / 2), wood,
        rot=(0, rnd.uniform(-0.5, 0.5), rnd.uniform(-2, 2)), bevel=0.02)
    cylinder("cap", POST * 0.85, CAP_H, (POST_X, 0, POST_TOP - 0.005), wood_old, r_top=0.02, segments=4,
             rot=(0, 0, 45), bevel=0.008)

    # Arm through the post along +x, and a diagonal brace under it.
    arm_x0 = POST_X - POST / 2 - 0.05
    arm_z = ARM_TOP - ARM_H / 2
    box("arm", (ARM_END - arm_x0, ARM_D, ARM_H), ((arm_x0 + ARM_END) / 2, 0, arm_z), wood_old,
        rot=(rnd.uniform(-1, 1), 0, 0), bevel=0.015)
    bx0, bz0 = POST_X + POST / 2 - 0.01, BRACE_Z
    bx1, bz1 = POST_X + 0.42, ARM_TOP - ARM_H + 0.01
    length = math.hypot(bx1 - bx0, bz1 - bz0)
    angle = math.degrees(math.atan2(bz1 - bz0, bx1 - bx0))
    box("brace", (length, 0.07, 0.07), ((bx0 + bx1) / 2, 0, (bz0 + bz1) / 2), wood, rot=(0, -angle, 0), bevel=0.012)
    box("collar", (POST + 0.02, POST + 0.02, 0.04), (POST_X, 0, ARM_TOP - ARM_H - 0.05), iron, bevel=0.006)

    # Two short chains: eye bolts under the arm, then alternating links down to the board.
    arm_bottom = ARM_TOP - ARM_H
    board_top = arm_bottom - CHAIN_LEN
    link_R, link_r = 0.022, 0.006
    for i, sx in enumerate((-1, 1)):
        cx = BOARD_X + sx * CHAIN_DX
        box(f"bolt_{i}", (0.03, 0.03, 0.02), (cx, 0, arm_bottom - 0.005), iron, bevel=0.004)
        n = 4
        step = (CHAIN_LEN - 0.02) / n
        for k in range(n):
            z = arm_bottom - 0.01 - step * (k + 0.5)
            rot = (90, 0, 0) if k % 2 == 0 else (90, 0, 90)
            torus(f"link_{i}_{k}", link_R, link_r, (cx, 0, z), iron, rot=rot, major=10, minor=5)
        box(f"staple_{i}", (0.04, BOARD_T + 0.016, 0.03), (cx, 0, board_top + 0.005), iron, bevel=0.004)

    # The board: a dark plank with a slightly proud frame, hung a little skew.
    tilt = rnd.uniform(-2.0, 2.0)
    bz = board_top - BOARD_H / 2
    box("board", (BOARD_W - 0.04, BOARD_T, BOARD_H - 0.04), (BOARD_X, 0, bz), board, rot=(0, tilt, 0), bevel=0.008)
    fw = 0.035
    ft = BOARD_T + 0.012
    for name, size, off in (
        ("frame_top", (BOARD_W, ft, fw), (0, BOARD_H / 2 - fw / 2)),
        ("frame_bottom", (BOARD_W, ft, fw), (0, -BOARD_H / 2 + fw / 2)),
        ("frame_left", (fw, ft, BOARD_H - 2 * fw + 0.004), (-BOARD_W / 2 + fw / 2, 0)),
        ("frame_right", (fw, ft, BOARD_H - 2 * fw + 0.004), (BOARD_W / 2 - fw / 2, 0)),
    ):
        box(name, size, _on_board(off, bz, tilt), frame, rot=(0, tilt, 0), bevel=0.008)

    # The painted tankard on the -y face: body, base band, lid rim, foam and a handle on the right.
    face_y = -BOARD_T / 2 - 0.003
    paint_t = 0.008

    def paint(name, w, h, off, mat):
        x, _, z = _on_board(off, bz, tilt)
        box(name, (w, paint_t, h), (x, face_y, z), mat, rot=(0, tilt, 0), bevel=0.002)

    paint("tankard_body", 0.22, 0.25, (-0.05, -0.04), ochre)
    paint("tankard_base", 0.26, 0.04, (-0.05, -0.175), ochre)
    paint("tankard_rim", 0.26, 0.035, (-0.05, 0.1), ochre)
    paint("tankard_foam", 0.23, 0.06, (-0.05, 0.15), foam)
    paint("tankard_foam_drip", 0.06, 0.06, (-0.12, 0.1), foam)
    hx, _, hz = _on_board((0.09, -0.035), bz, tilt)
    torus("tankard_handle", 0.075, 0.018, (hx, face_y, hz), ochre, rot=(90, tilt, 0), major=14, minor=5)


def _on_board(off, bz, tilt):
    """A point `off` (x, z) on the board's face, turned by the board's tilt about y."""
    a = math.radians(tilt)
    dx, dz = off
    return (BOARD_X + dx * math.cos(a) + dz * math.sin(a), 0, bz - dx * math.sin(a) + dz * math.cos(a))
