"""A wooden village signpost: a square weathered oak post about 2.3 m high set in a low ring of stones, with two
pointed plank arrow boards near the top pointing in opposite directions at slightly different heights, and a small
iron cap on the post (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder

# Overall dimensions (metres), from the description.
POST = 0.14  # post section
POST_TOP = 2.28  # top of the timber
CAP_BAND_H, CAP_ROOF_H = 0.06, 0.05  # iron cap: a band and a low pyramid (top at about 2.35)
RING_R = 0.2  # stone ring, centre line
STONE_R = 0.105  # stone radius before squash
STONES = 7
BOARD_LEN, BOARD_H, BOARD_T = 0.72, 0.18, 0.036  # arrow board body; the point adds BOARD_H / 2
BOARD_BACK = 0.2  # how far the blunt end reaches behind the post centre
BOARD_HI_Z, BOARD_LO_Z = 2.02, 1.76  # board centres: +x arrow above, -x arrow below

OAK = (0.21, 0.16, 0.11)  # linear RGB: greyed, weathered oak
PLANK = (0.25, 0.18, 0.11)
PLANK_OLD = (0.17, 0.125, 0.085)
STONE = (0.3, 0.27, 0.23)
STONE_DARK = (0.22, 0.2, 0.175)
IRON = (0.045, 0.045, 0.045)


def _arrow(name, direction, z, tilt, mat, iron):
    """A plank on the post's front (-y) face, pointing along `direction` (+1 or -1) x, tilted `tilt` degrees."""
    y = -POST / 2 - BOARD_T / 2 + 0.004
    cx = direction * (BOARD_LEN / 2 - BOARD_BACK)
    box(f"{name}_plank", (BOARD_LEN, BOARD_T, BOARD_H), (cx, y, z), mat, rot=(0, tilt, 0), bevel=0.008)
    # The point: a diamond prism half sunk in the plank's end, a touch thinner so the faces do not fight.
    a = math.radians(tilt)
    dx = direction * BOARD_LEN / 2
    tip_t = BOARD_T - 0.006
    cylinder(f"{name}_point", BOARD_H / 2, tip_t, (cx + dx * math.cos(a), y + tip_t / 2, z - dx * math.sin(a)), mat,
             segments=4, rot=(90, tilt, 0), bevel=0.006)
    # Two iron nail heads over the post.
    for i, dz in enumerate((-0.05, 0.05)):
        cylinder(f"{name}_nail_{i}", 0.013, 0.012, (direction * 0.012 * (1 - 2 * i), y - BOARD_T / 2 + 0.004, z + dz),
                 iron, segments=8, rot=(90, 0, 0), bevel=0.003)


@prop
def signpost_wood():
    rnd = random.Random(11)
    oak = material("signpost_oak", OAK, vary=0.32, scale=16, crevice=0.6)
    plank = material("signpost_plank", PLANK, vary=0.28, scale=14)
    plank_old = material("signpost_plank_old", PLANK_OLD, vary=0.3, scale=14)
    stone = material("signpost_stone", STONE, vary=0.25, scale=9, crevice=0.6)
    stone_dark = material("signpost_stone_dark", STONE_DARK, vary=0.25, scale=9, crevice=0.6)
    iron = material("signpost_iron", IRON, rough=0.55, vary=0.2, scale=20, metal=0.6)

    # Oak post, standing square on the ground.
    box("post", (POST, POST, POST_TOP), (0, 0, POST_TOP / 2), oak, bevel=0.016)

    # Iron cap: a band round the post head and a low pyramid.
    band = POST + 0.024
    box("cap_band", (band, band, CAP_BAND_H), (0, 0, POST_TOP - CAP_BAND_H / 2 + 0.02), iron, bevel=0.006)
    cylinder("cap_roof", (band + 0.02) / math.sqrt(2), CAP_ROOF_H, (0, 0, POST_TOP + 0.015), iron, r_top=0.012,
             segments=4, rot=(0, 0, 45), bevel=0.006)

    # Low ring of field stones packed round the foot.
    for i in range(STONES):
        a = 2 * math.pi * (i + rnd.uniform(-0.15, 0.15)) / STONES
        r = STONE_R * rnd.uniform(0.85, 1.08)
        sz = rnd.uniform(0.6, 0.78)
        ring = RING_R * rnd.uniform(0.93, 1.05)
        # A blob is centred and lumpy (12 %): lift it so its lowest lump rests on the ground.
        blob(f"stone_{i}", r, (ring * math.cos(a), ring * math.sin(a), r * sz * 1.12 - 0.005),
             stone_dark if i % 3 == 1 else stone, squash=(1.0, 1.0, sz), subdiv=2, seed=40 + i)

    # Two arrow boards on the front face, opposite ways, at slightly different heights.
    _arrow("board_hi", 1, BOARD_HI_Z, rnd.uniform(-2.5, -1.0), plank, iron)
    _arrow("board_lo", -1, BOARD_LO_Z, rnd.uniform(1.0, 2.5), plank_old, iron)
