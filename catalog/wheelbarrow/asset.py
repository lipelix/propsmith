"""An old wooden wheelbarrow: a plank tray with sloped sides, one spoked wooden wheel with an iron tyre at the front (+x),
two long handles to the back resting on two short legs, holding a few logs or some earth (generated by npm run
new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder, torus

# The barrow runs along x, about 1.4 m long and 0.6 m wide, the tray rim ~0.6 m high.
WHEEL_R = 0.25  # outer radius of the iron tyre
WHEEL_X = 0.49  # axle position along x (front)
RAIL_FRONT = (0.56, 0.09, WHEEL_R)  # front end of a handle rail (x, |y|, z)
RAIL_BACK = (-0.71, 0.26, 0.43)  # grip end of a handle rail
LEG_X = -0.28  # the two short legs under the back of the tray
TRAY_Z = 0.40  # underside of the tray floor
TRAY_X0, TRAY_X1 = -0.30, 0.27  # floor ends along x
TRAY_W = 0.42  # floor width along y
WALL_SLANT = 0.26  # slanted height of a side wall (two planks)
SIDE_FLARE, FRONT_FLARE, BACK_FLARE = 22, 40, 18  # degrees outward from vertical
BOARD = 0.025  # plank thickness

WOOD = (0.2, 0.115, 0.058)
WOOD_OLD = (0.16, 0.11, 0.075)
WHEEL_WOOD = (0.18, 0.12, 0.07)
IRON = (0.045, 0.045, 0.045)
LOG_BARK = (0.13, 0.085, 0.05)
LOG_END = (0.42, 0.3, 0.17)
EARTH = (0.1, 0.07, 0.045)


def _rail_at(t):
    """Point on a +y handle rail, t = 0 at the front end, 1 at the grip."""
    return tuple(a + (b - a) * t for a, b in zip(RAIL_FRONT, RAIL_BACK))


def _barrow(rnd, tag):
    wood = material("wheelbarrow_wood", WOOD, vary=0.25, scale=14)
    old = material("wheelbarrow_boards", WOOD_OLD, vary=0.3, scale=11)
    wheel_wood = material("wheelbarrow_wheel", WHEEL_WOOD, vary=0.2, scale=16)
    iron = material("wheelbarrow_iron", IRON, rough=0.45, metal=0.8)

    # Handles: two long rails from beside the wheel back to the grips, splaying apart.
    fx, fy, fz = RAIL_FRONT
    bx, by, bz = RAIL_BACK
    dx, dy, dz = fx - bx, fy - by, fz - bz
    length = math.sqrt(dx * dx + dy * dy + dz * dz)
    pitch = math.degrees(math.atan2(-dz, math.hypot(dx, dy)))
    yaw = math.degrees(math.atan2(dy, dx))
    for s in (-1, 1):
        box(
            f"rail_{s}",
            (length, 0.045, 0.06),
            ((fx + bx) / 2, s * (fy + by) / 2, (fz + bz) / 2),
            wood,
            rot=(0, pitch, s * yaw),
            bevel=0.01,
        )
        # A rounded grip on the end of each handle.
        gx, gy, gz = _rail_at(0.9)
        cylinder(f"grip_{s}", 0.026, 0.15, (gx, s * gy, gz), wood, rot=(0, -90 + pitch, s * yaw), segments=8, bevel=0.005)

    # Legs under the back of the tray, and two bearers carrying the tray on the rails.
    t_leg = (fx - LEG_X) / (fx - bx)
    _, ly, lz = _rail_at(t_leg)
    for s in (-1, 1):
        box(f"leg_{s}", (0.05, 0.05, lz), (LEG_X, s * ly, lz / 2), wood, rot=(0, rnd.uniform(-2, 2), 0), bevel=0.008)
        box(f"brace_{s}", (0.03, 0.03, 0.3), (LEG_X + 0.12, s * (ly - 0.03), lz - 0.12), wood, rot=(0, -40, 0), bevel=0.005)
    box("bearer_back", (0.06, 2 * ly + 0.06, 0.04), (LEG_X, 0, TRAY_Z - 0.02), wood, bevel=0.008)
    t_front = (fx - 0.22) / (fx - bx)
    _, fy2, fz2 = _rail_at(t_front)
    front_h = TRAY_Z - (fz2 + 0.02)
    box("bearer_front", (0.07, 2 * fy2 + 0.08, front_h + 0.02), (0.22, 0, TRAY_Z - (front_h + 0.02) / 2), wood, bevel=0.008)

    # The tray: a plank floor and two-plank walls flaring outwards.
    n = 3
    for i in range(n):
        w = TRAY_W / n
        box(
            f"floor_{i}",
            (TRAY_X1 - TRAY_X0, w - 0.008, 0.035),
            ((TRAY_X0 + TRAY_X1) / 2 + rnd.uniform(-0.01, 0.01), -TRAY_W / 2 + w * (i + 0.5), TRAY_Z + 0.0175),
            old,
            bevel=0.006,
        )
    plank = WALL_SLANT / 2
    z0 = TRAY_Z + 0.02
    sa, ca = math.sin(math.radians(SIDE_FLARE)), math.cos(math.radians(SIDE_FLARE))
    fa, fc = math.sin(math.radians(FRONT_FLARE)), math.cos(math.radians(FRONT_FLARE))
    ba, bc = math.sin(math.radians(BACK_FLARE)), math.cos(math.radians(BACK_FLARE))
    for k in range(2):
        mid = plank * (k + 0.5)
        top = plank * (k + 1)
        # Along x each wall plank reaches the front and back walls at its own height.
        x_front = TRAY_X1 + fa * top + 0.01
        x_back = TRAY_X0 - ba * top - 0.01
        y_side = TRAY_W / 2 + sa * top + 0.01
        z = z0 + mid * ca
        for s in (-1, 1):
            mat = old if rnd.random() < 0.5 else wood
            box(
                f"side_{s}_{k}",
                (x_front - x_back, BOARD, plank - 0.006),
                ((x_front + x_back) / 2, s * (TRAY_W / 2 + BOARD / 2 + sa * mid), z),
                mat,
                rot=(-s * SIDE_FLARE + rnd.uniform(-1, 1), 0, rnd.uniform(-0.6, 0.6)),
                bevel=0.006,
            )
        box(
            f"front_{k}",
            (BOARD, 2 * y_side, plank - 0.006),
            (TRAY_X1 + BOARD / 2 + fa * mid, 0, z0 + mid * fc),
            old,
            rot=(rnd.uniform(-0.8, 0.8), FRONT_FLARE, 0),
            bevel=0.006,
        )
        box(
            f"back_{k}",
            (BOARD, 2 * (TRAY_W / 2 + sa * top), plank - 0.006),
            (TRAY_X0 - BOARD / 2 - ba * mid, 0, z0 + mid * bc),
            wood if k else old,
            rot=(rnd.uniform(-0.8, 0.8), -BACK_FLARE, 0),
            bevel=0.006,
        )
    # Corner straps of iron at the front, where the walls meet.
    for s in (-1, 1):
        box(
            f"strap_{s}",
            (0.02, 0.05, WALL_SLANT),
            (TRAY_X1 + fa * plank + 0.015, s * (TRAY_W / 2 + sa * plank + 0.005), z0 + plank * fc),
            iron,
            rot=(0, FRONT_FLARE, 0),
            bevel=0.004,
        )

    # The wheel, in the xz plane at the front: wooden felloe, iron tyre, hub and six spokes on an iron axle.
    c = (WHEEL_X, 0, WHEEL_R)
    torus("tyre", WHEEL_R - 0.016, 0.016, c, iron, rot=(90, 0, 0), major=32, minor=6)
    torus("felloe", WHEEL_R - 0.05, 0.03, c, wheel_wood, rot=(90, 0, 0), major=32, minor=8)
    cylinder("hub", 0.05, 0.12, (WHEEL_X, 0.06, WHEEL_R), wheel_wood, rot=(90, 0, 0), segments=12, bevel=0.008)
    cylinder("axle", 0.018, 2 * fy + 0.08, (WHEEL_X, fy + 0.04, WHEEL_R), iron, rot=(90, 0, 0), segments=8, bevel=0)
    for k in range(6):
        a = 60 * k + 15
        r_mid = (0.05 + WHEEL_R - 0.06) / 2
        box(
            f"spoke_{k}",
            (0.026, 0.026, WHEEL_R - 0.1),
            (WHEEL_X + math.sin(math.radians(a)) * r_mid, 0, WHEEL_R + math.cos(math.radians(a)) * r_mid),
            wheel_wood,
            rot=(0, a, 0),
            bevel=0,
        )


@prop
def wheelbarrow():
    rnd = random.Random(11)
    _barrow(rnd, "logs")
    bark = material("wheelbarrow_bark", LOG_BARK, vary=0.3, scale=20)
    end = material("wheelbarrow_log_end", LOG_END, vary=0.2, scale=25)
    # A few logs lying along the tray, two below and two on top.
    logs = [(-0.12, 0.07, 0), (0.02, 0.07, 0), (0.15, 0.065, 0), (-0.05, 0.065, 1), (0.09, 0.06, 1)]
    for i, (y, r, layer) in enumerate(logs):
        L = 0.62 + rnd.uniform(-0.06, 0.04)
        x0 = -0.31 + rnd.uniform(-0.02, 0.06)
        z = TRAY_Z + 0.035 + r + layer * 0.11
        yaw = rnd.uniform(-6, 6)
        cylinder(f"log_{i}", r, L, (x0, y, z), bark, rot=(0, 90, yaw), segments=10, bevel=0.008)
        cylinder(f"log_end_{i}", r - 0.012, 0.012, (x0 - 0.006, y, z), end, rot=(0, 90, yaw), segments=10, bevel=0)


@prop
def wheelbarrow_earth():
    rnd = random.Random(12)
    _barrow(rnd, "earth")
    earth = material("wheelbarrow_earth", EARTH, vary=0.35, scale=18, rough=1.0)
    blob("earth", 0.32, (0.03, 0, TRAY_Z + 0.14), earth, squash=(1.25, 0.95, 0.42), subdiv=2, seed=4, jitter=0.2)
    blob("earth_heap", 0.18, (-0.05, -0.04, TRAY_Z + 0.2), earth, squash=(1.2, 1.1, 0.6), subdiv=2, seed=6, jitter=0.22)
    stone = material("wheelbarrow_stone", (0.28, 0.25, 0.21), vary=0.2, scale=30)
    for i, (x, y, r, z) in enumerate([(0.2, 0.1, 0.05, 0.25), (-0.18, 0.13, 0.04, 0.24), (0.1, -0.15, 0.035, 0.23)]):
        blob(f"clod_{i}", r, (x, y, TRAY_Z + z), stone if i == 1 else earth, subdiv=1, seed=10 + i, jitter=0.2)
