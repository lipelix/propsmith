"""An inn's open stone hearth built against a wall, front on -y: a fieldstone block with an arched fire opening, a
heavy timber mantel, a hearth slab in front, burning logs on embers and an iron pot on a hook (generated by
npm run new)."""
import math
import random

from propsmith import anchor, prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder, torus

TILE = 1.5  # metres per tile
# Footprint 2x1 tiles = 3.0 x 1.5 m, height 1 tile = 1.5 m. The block stands flush with the back (+y) edge.
W, D = 2.6, 0.9  # stone block width (x) and depth (y)
BACK = 1 * TILE / 2  # back face on the footprint's +y edge
FRONT = BACK - D  # front face of the block
BODY_H = 1.34  # top of the stone courses (under the capstones)
CAP_H = 0.08  # capstones, top at 1.42 m
OPEN_HW = 0.48  # half width of the fire opening
SPRING = 0.4  # where the arch springs
ARCH_IN, ARCH_OUT = 0.48, 0.72  # voussoir ring radii (crown at 0.88 m, ring top at 1.12 m)
BAND_Z = SPRING + ARCH_OUT  # bottom of the stone band over the opening
PIER_COURSES = [0.3, 0.28, 0.28, 0.26]  # course heights of the piers, scaled to BAND_Z
MANTEL_W, MANTEL_D, MANTEL_H = 1.9, 0.28, 0.2  # timber beam
MANTEL_Z = BAND_Z + 0.02  # bottom of the mantel
HEARTH_W, HEARTH_D, HEARTH_H = 1.8, 0.48, 0.1  # stone slab in front
FLOOR_H = 0.08  # floor stone inside the opening
GAP = 0.026  # mortar joints
FIRE_Y = FRONT + 0.27  # where the logs lie, inside the opening
POT_R, POT_H, POT_Z = 0.15, 0.2, 0.37  # iron pot: radius, height, bottom
POT_Y = FRONT + 0.2  # the pot hangs just behind the arch

STONE = (0.34, 0.295, 0.235)  # same grey-brown fieldstone as the village wall set
STONE_OLD = (0.27, 0.235, 0.19)
CAP = (0.27, 0.255, 0.23)
MORTAR = (0.11, 0.10, 0.085)
SOOT = (0.05, 0.045, 0.04)
WOOD = (0.2, 0.12, 0.06)
LOG = (0.15, 0.09, 0.05)
CHAR = (0.06, 0.05, 0.045)
EMBER = (0.5, 0.16, 0.03)
FLAME = (0.5, 0.3, 0.07)
IRON = (0.075, 0.07, 0.065)  # a touch lighter than usual so the pot reads against the soot
IRON_WORN = (0.16, 0.14, 0.12)  # rubbed rim of the pot
FLOOR = (0.13, 0.11, 0.09)  # sooty hearth stone inside the opening
HEARTH = (0.115, 0.1, 0.085)  # worn, smoke-darkened slabs in front (#86: the cap stone read pale under the glow)


def _widths(rnd, total, n):
    raw = [rnd.uniform(0.8, 1.2) for _ in range(n)]
    s = sum(raw)
    return [total * r / s for r in raw]


@prop
def fireplace_stone():
    rnd = random.Random(11)
    stone = material("fireplace_stone_block", STONE, vary=0.22, scale=8, crevice=0.3)
    old = material("fireplace_stone_block_old", STONE_OLD, vary=0.25, scale=11, crevice=0.3)
    cap = material("fireplace_stone_cap", CAP, vary=0.22, scale=9, crevice=0.3)
    mortar = material("fireplace_stone_mortar", MORTAR, vary=0.2, scale=20, crevice=0.8)
    soot = material("fireplace_stone_soot", SOOT, vary=0.3, scale=10, crevice=0.6)
    wood = material("fireplace_stone_mantel", WOOD, vary=0.3, scale=14)
    log = material("fireplace_stone_log", LOG, vary=0.3, scale=18)
    char = material("fireplace_stone_char", CHAR, vary=0.3, scale=20)
    ember = material("fireplace_stone_ember", EMBER, rough=0.6, vary=0.35, scale=14, crevice=0.2)
    flame = material("fireplace_stone_flame", FLAME, rough=0.5, vary=0.3, scale=10, crevice=0.1)
    iron = material("fireplace_stone_iron", IRON, rough=0.55, vary=0.2, scale=20, metal=0.6)

    cy = (FRONT + BACK) / 2
    pier_w = W / 2 - OPEN_HW

    # Mortar cores, recessed behind the faces of the blocks.
    for s in (-1, 1):
        box(f"core_{s}", (pier_w - 0.04, D - 0.06, BODY_H - 0.01),
            (s * (OPEN_HW + pier_w / 2), cy + 0.01, (BODY_H - 0.01) / 2), mortar, bevel=0)
    box("core_band", (2 * OPEN_HW + 0.02, D - 0.06, BODY_H - BAND_Z),
        (0, cy + 0.01, (BAND_Z + BODY_H) / 2), mortar, bevel=0)

    # Sooty inside of the opening: back, sides and ceiling.
    back_y = BACK - 0.3
    box("soot_back", (2 * OPEN_HW + 0.02, BACK - back_y - 0.02, BAND_Z), (0, (back_y + BACK - 0.02) / 2, BAND_Z / 2),
        soot, bevel=0.01)
    for s in (-1, 1):
        box(f"soot_side_{s}", (0.03, back_y - FRONT - 0.04, BAND_Z),
            (s * (OPEN_HW - 0.005), (FRONT + 0.04 + back_y) / 2, BAND_Z / 2), soot, bevel=0)
    box("soot_ceiling", (2 * OPEN_HW + 0.02, back_y - FRONT - 0.2, 0.14),
        (0, (FRONT + 0.2 + back_y) / 2, BAND_Z - 0.07), soot, bevel=0)
    box("floor", (2 * OPEN_HW, back_y - FRONT + 0.02, FLOOR_H), (0, (FRONT + back_y) / 2, FLOOR_H / 2),
        material("fireplace_stone_floor", FLOOR, vary=0.3, scale=10, crevice=0.5), bevel=0.01)

    # Piers: staggered courses of full-depth blocks either side of the opening.
    scale = BAND_Z / sum(PIER_COURSES)
    for s in (-1, 1):
        z = 0.0
        for c, ch in enumerate(PIER_COURSES):
            h = ch * scale
            n = 2 if (c + (s > 0)) % 2 == 0 else 3
            x = OPEN_HW
            for i, w in enumerate(_widths(rnd, pier_w, n)):
                bw, bh = w - GAP, h - GAP
                tilt = (0, 0, 0) if c == 0 else (rnd.uniform(-1, 1), rnd.uniform(-1.2, 1.2), 0)
                box(f"pier_{s}_{c}_{i}",
                    (bw * rnd.uniform(0.95, 1.0), D * rnd.uniform(0.96, 1.0), bh * rnd.uniform(0.88, 1.0)),
                    (s * (x + w / 2), cy + rnd.uniform(-0.01, 0.01), z + GAP / 2 + bh / 2 if c else bh / 2 + 0.001),
                    old if rnd.random() < 0.35 else stone,
                    rot=(tilt[0], tilt[1], rnd.uniform(-2, 2)), bevel=0.024)
                x += w
            z += h

    # Band of long stones over the opening, under the capstones.
    x = -W / 2
    band_h = BODY_H - BAND_Z
    for i, w in enumerate(_widths(rnd, W, 5)):
        box(f"band_{i}", ((w - GAP) * rnd.uniform(0.96, 1.0), D * rnd.uniform(0.96, 1.0), band_h - GAP),
            (x + w / 2, cy + rnd.uniform(-0.01, 0.01), BAND_Z + band_h / 2), old if i % 2 else stone,
            rot=(rnd.uniform(-1, 1), rnd.uniform(-1, 1), rnd.uniform(-1.5, 1.5)), bevel=0.024)
        x += w

    # Arch: a ring of voussoirs standing a little proud of the face, spandrel stones filling the corners above.
    n = 9
    rm = (ARCH_IN + ARCH_OUT) / 2
    vd = 0.26
    for i in range(n):
        a = math.pi * (i + 0.5) / n
        tw = math.pi * rm / n - GAP
        box(f"voussoir_{i}", ((ARCH_OUT - ARCH_IN) * rnd.uniform(0.94, 1.0), vd, tw),
            (rm * math.cos(a), FRONT - 0.03 + vd / 2, SPRING + rm * math.sin(a)),
            old if rnd.random() < 0.4 else stone, rot=(0, -math.degrees(a) + rnd.uniform(-2, 2), 0), bevel=0.02)
    for s in (-1, 1):
        box(f"spandrel_{s}", (0.28, vd - 0.04, 0.22), (s * (OPEN_HW - 0.14), FRONT + vd / 2 - 0.01, BAND_Z - 0.11),
            stone, rot=(0, rnd.uniform(-2, 2), 0), bevel=0.02)

    # Heavy timber mantel over the opening, standing proud of the face.
    box("mantel", (MANTEL_W, MANTEL_D, MANTEL_H), (0, FRONT - 0.14 + MANTEL_D / 2, MANTEL_Z + MANTEL_H / 2), wood,
        rot=(rnd.uniform(-0.5, 0.5), 0, rnd.uniform(-0.8, 0.8)), bevel=0.02)

    # Capstones.
    x = -W / 2
    for i, w in enumerate(_widths(rnd, W, 4)):
        box(f"cap_{i}", (w - 0.012, D + 0.02, CAP_H * rnd.uniform(0.9, 1.0)),
            (x + w / 2, cy + rnd.uniform(-0.01, 0.0), BODY_H + CAP_H / 2), cap,
            rot=(0, 0, rnd.uniform(-1.5, 1.5)), bevel=0.018)
        x += w

    # Hearth slab in front: three flags, worn and darkened by smoke.
    hearth = material("fireplace_stone_hearth", HEARTH, vary=0.35, scale=9, crevice=0.4)
    x = -HEARTH_W / 2
    for i, w in enumerate(_widths(rnd, HEARTH_W, 3)):
        box(f"hearth_{i}", (w - 0.02, HEARTH_D * rnd.uniform(0.94, 1.0), HEARTH_H * rnd.uniform(0.85, 1.0)),
            (x + w / 2, FRONT - HEARTH_D / 2 + 0.01, HEARTH_H / 2), hearth,
            rot=(0, 0, rnd.uniform(-2, 2)), bevel=0.018)
        x += w

    # Embers and logs.
    blob("embers", 0.28, (0, FIRE_Y, FLOOR_H), ember, squash=(1.3, 0.8, 0.22), subdiv=2, seed=5, jitter=0.2)
    logs = [((-0.28, FIRE_Y - 0.08, FLOOR_H + 0.07), 18), ((-0.27, FIRE_Y + 0.1, FLOOR_H + 0.07), -14),
            ((-0.22, FIRE_Y + 0.02, FLOOR_H + 0.18), 4)]
    for i, (at, yaw) in enumerate(logs):
        cylinder(f"log_{i}", 0.065 * rnd.uniform(0.9, 1.1), 0.55, at, char if i == 1 else log, segments=10,
                 rot=(0, 90, yaw), bevel=0.008)
    # Low soft tongues of flame between the logs (the fire anchor animates the rest).
    for i, (fx, fy, fr) in enumerate([(-0.12, FIRE_Y - 0.05, 0.06), (0.06, FIRE_Y - 0.01, 0.07),
                                      (0.2, FIRE_Y + 0.03, 0.05)]):
        blob(f"flame_{i}", fr, (fx, fy, FLOOR_H + 0.17 + fr), flame, squash=(0.9, 0.8, 1.7), subdiv=1, seed=20 + i,
             jitter=0.15)

    # Iron pot on a hook from the ceiling.
    # It hangs just inside the arch, from a hook set into the crown, so the light from outside catches it.
    rim = material("fireplace_stone_pot_rim", IRON_WORN, rough=0.45, vary=0.25, scale=20, crevice=0.3, metal=0.6)
    py = POT_Y
    hook_top = BAND_Z - 0.14
    pot_top = POT_Z + POT_H
    cylinder("hook_rod", 0.012, hook_top - (pot_top + 0.12), (0, py, pot_top + 0.12), iron, segments=8, bevel=0)
    torus("hook", 0.03, 0.01, (0, py, pot_top + 0.11), iron, rot=(90, 0, 0), major=12, minor=6)
    torus("bail", POT_R * 0.95, 0.009, (0, py, pot_top), iron, rot=(90, 0, 0), major=20, minor=6)
    cylinder("pot", POT_R, POT_H, (0, py, POT_Z), iron, r_top=POT_R * 0.85, segments=16, bevel=0.01)
    torus("pot_rim", POT_R * 0.87, 0.018, (0, py, pot_top), rim, major=16, minor=6)

    # The flames rise from the embers across the logs and die under the arch (crown at SPRING + ARCH_IN).
    anchor("fire:hearth", (0, FIRE_Y, FLOOR_H + 0.08), size=(0.26, 0.26, SPRING + ARCH_IN - FLOOR_H - 0.2))
    anchor("light:hearth", (0, FIRE_Y, FLOOR_H + 0.4))
    anchor("smoke:hearth", (0, FRONT + 0.1, SPRING + ARCH_IN - 0.02))
