"""A short wooden jetty section: weathered planks with uneven gaps laid across two stringers, which rest on four
crossbeams, each on a pair of round timber posts standing on the ground, and a taller mooring post with a coil of rope
at the +x end (generated by npm run new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

# Overall dimensions (metres): the jetty runs along x.
L = 4.0  # deck length
W = 1.6  # deck width (plank length)
DECK_TOP = 0.70  # top of the planks
PLANK_T = 0.05  # plank thickness
PLANK_W = (0.17, 0.21)  # plank width range
GAP = (0.008, 0.035)  # uneven gaps between planks
STRINGER_W, STRINGER_H = 0.12, 0.17  # two stringers along x
STRINGER_Y = 0.52
CAP_W, CAP_H = 0.15, 0.14  # crossbeam on each post pair
CAP_LEN = 1.36
POST_R = 0.085
POST_X = (-1.72, -0.58, 0.58, 1.72)  # four pairs of posts
POST_Y = 0.55
MOOR_R = 0.11  # mooring post
MOOR_H = 1.30
MOOR_X, MOOR_Y = 1.86, -0.66
ROPE_Z = 1.02

WOOD = (0.24, 0.21, 0.17)  # sun-greyed planks
WOOD_OLD = (0.19, 0.165, 0.135)
FRAME = (0.17, 0.13, 0.09)  # darker, damp frame and posts
ROPE = (0.34, 0.27, 0.16)

STRINGER_TOP = DECK_TOP - PLANK_T
CAP_TOP = STRINGER_TOP - STRINGER_H
POST_H = CAP_TOP - CAP_H + 0.01  # posts tuck a hair into the crossbeams


@prop
def pier_wood():
    rnd = random.Random(11)
    wood = material("pier_wood_planks", WOOD, vary=0.3, scale=14)
    wood_old = material("pier_wood_planks_old", WOOD_OLD, vary=0.34, scale=14)
    frame = material("pier_wood_frame", FRAME, vary=0.28, scale=10)
    rope = material("pier_wood_rope", ROPE, vary=0.2, scale=30)

    # Round posts in pairs, slightly tapered and leaning a little.
    for i, x in enumerate(POST_X):
        for s in (-1, 1):
            cylinder(
                f"post_{i}_{s}",
                POST_R * rnd.uniform(0.94, 1.06),
                POST_H,
                (x + rnd.uniform(-0.02, 0.02), s * POST_Y, 0),
                frame,
                r_top=POST_R * 0.9,
                segments=10,
                rot=(rnd.uniform(-1.2, 1.2), rnd.uniform(-1.2, 1.2), rnd.uniform(0, 360)),
                bevel=0.012,
            )
        # A crossbeam across each pair.
        box(
            f"cap_{i}",
            (CAP_W, CAP_LEN, CAP_H),
            (x, 0, CAP_TOP - CAP_H / 2),
            frame,
            rot=(0, 0, rnd.uniform(-1.0, 1.0)),
            bevel=0.015,
        )

    # Two stringers along the full length.
    for s in (-1, 1):
        box(
            f"stringer_{s}",
            (L - 0.12, STRINGER_W, STRINGER_H),
            (0, s * STRINGER_Y, STRINGER_TOP - STRINGER_H / 2),
            frame,
            bevel=0.015,
        )

    # Planks across the stringers, uneven widths and gaps; notched around the mooring post.
    x = -L / 2 + 0.005
    n = 0
    while True:
        w = rnd.uniform(*PLANK_W)
        if x + w > L / 2:
            break
        cx = x + w / 2
        mat = wood_old if rnd.random() < 0.35 else wood
        length = W - rnd.uniform(0.0, 0.05)
        y0, y1 = -length / 2 + rnd.uniform(-0.015, 0.015), length / 2 + rnd.uniform(-0.015, 0.015)
        if abs(cx - MOOR_X) < MOOR_R + w / 2 + 0.01:
            y0 = MOOR_Y + MOOR_R + 0.015
        z = STRINGER_TOP + PLANK_T / 2 + rnd.uniform(-0.004, 0.006)
        box(
            f"plank_{n}",
            (w, y1 - y0, PLANK_T),
            (cx, (y0 + y1) / 2, z),
            mat,
            rot=(rnd.uniform(-0.6, 0.6), 0, rnd.uniform(-1.2, 1.2)),
            bevel=0.008,
        )
        n += 1
        x += w + rnd.uniform(*GAP)

    # The mooring post at the +x end, rising well above the deck, with a coil of rope.
    cylinder("mooring_post", MOOR_R, MOOR_H, (MOOR_X, MOOR_Y, 0), frame, r_top=MOOR_R * 0.88, segments=12,
             rot=(rnd.uniform(-1, 1), rnd.uniform(-1, 1), 0), bevel=0.015)
    cylinder("mooring_cap", MOOR_R * 0.88, 0.04, (MOOR_X, MOOR_Y, MOOR_H - 0.01), wood_old, r_top=MOOR_R * 0.6,
             segments=12, bevel=0.008)
    for k in range(2):
        torus(f"rope_{k}", MOOR_R * 0.98 + 0.018, 0.02, (MOOR_X, MOOR_Y, ROPE_Z + k * 0.04), rope,
              rot=(rnd.uniform(-4, 4), rnd.uniform(-4, 4), 0), major=16, minor=6)
