"""A heap of three plump burlap grain sacks, two lying side by side and one propped on top, tied at the neck with
twine; a variant is a single upright sack (generated by npm run new)."""
import math
import random

from mathutils import Euler, Matrix, Vector

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, cylinder, torus

# The heap is about 0.7 m high.
LIE_L = 0.88  # body length of a lying sack, metres
LIE_R = 0.28  # body half-width of a lying sack
LIE_FLAT = 0.85  # vertical squash of a lying sack (it slumps)
GAP = 0.27  # y offset of each lower sack from the centre line
TOP_Z = 0.47  # height of the top sack's body centre, settled into the valley between the lower two
UP_R = 0.2  # radius of the upright sack's body
UP_H = 0.48  # body height of the upright sack; neck and tuft bring it to about 0.6 m
NECK_L = 0.1  # gathered neck length
NECK_R = 0.08

BURLAP = (0.34, 0.25, 0.135)  # linear RGB, warm desaturated tan
BURLAP_PALE = (0.38, 0.29, 0.165)
BURLAP_DARK = (0.2, 0.145, 0.08)  # patches, stains
TWINE = (0.17, 0.12, 0.06)


def _mats():
    return {
        "cloth": material("sacks_grain_burlap", BURLAP, rough=0.95, vary=0.22, scale=30, crevice=0.6),
        "pale": material("sacks_grain_burlap_pale", BURLAP_PALE, rough=0.95, vary=0.2, scale=30, crevice=0.6),
        "dark": material("sacks_grain_patch", BURLAP_DARK, rough=0.95, vary=0.2, scale=20, crevice=0.5),
        "twine": material("sacks_grain_twine", TWINE, rough=0.9, vary=0.2, scale=40, crevice=0.4),
    }


def _put(obj, frame, at, rot=(0, 0, 0)):
    """Place `obj` at local `at` / rotation `rot` (degrees) inside the sack `frame` (a 4x4 matrix)."""
    local = Matrix.Translation(at) @ Euler([math.radians(a) for a in rot]).to_matrix().to_4x4()
    world = frame @ local
    obj.location = world.to_translation()
    obj.rotation_euler = world.to_euler()
    return obj


def _slump(obj, down, k):
    """Flatten the half of a blob facing local `down` by `k`, so the sack sags onto what it lies on."""
    down = Vector(down).normalized()
    for v in obj.data.vertices:
        d = v.co.dot(down)
        if d > 0:
            v.co -= down * d * (1 - k)


def _sack(name, length, radius, flat, frame, mats, seed, down=(0, 0, -1), body="cloth", patch=True):
    """A sack along local +x (neck at +x), centred on the frame's origin. Returns its parts."""
    rnd = random.Random(seed)
    parts = []
    b = blob(f"{name}_body", radius, (0, 0, 0), mats[body], squash=(length / (2 * radius), 1, flat), subdiv=3,
             seed=seed, jitter=0.035)
    _slump(b, down, 0.55)
    parts.append(_put(b, frame, (0, 0, 0), (rnd.uniform(-4, 4), 0, 0)))
    # Gathered neck rising out of the shoulder, then the twine and the frayed tuft.
    x0 = length / 2 * 0.8
    parts.append(_put(cylinder(f"{name}_neck", NECK_R * 1.6, NECK_L, (0, 0, 0), mats[body], r_top=NECK_R * 0.8,
                               segments=12, bevel=0.015), frame, (x0, 0, 0), (0, 90, 0)))
    parts.append(_put(torus(f"{name}_twine", NECK_R * 0.95, 0.014, (0, 0, 0), mats["twine"], major=16, minor=6),
                      frame, (x0 + NECK_L * 0.6, 0, 0), (0, 90, 0)))
    parts.append(_put(blob(f"{name}_tuft", 0.085, (0, 0, 0), mats[body], squash=(0.75, 1.25, 1.05), subdiv=2,
                           seed=seed + 1, jitter=0.25), frame, (x0 + NECK_L + 0.045, 0, 0)))
    if patch:  # a darker mended patch sunk into the upper flank so only its cap shows
        a = math.radians(rnd.uniform(35, 70))
        at = (rnd.uniform(-0.2, 0.1) * length, -radius * 0.62 * math.cos(a), radius * flat * 0.62 * math.sin(a))
        parts.append(_put(blob(f"{name}_patch", radius * 0.5, (0, 0, 0), mats["dark"], squash=(1.2, 0.9, 0.9),
                               subdiv=2, seed=seed + 2, jitter=0.04), frame, at))
    return parts


def _frame(at, yaw, pitch=0, roll=0):
    return Matrix.Translation(at) @ Euler((math.radians(roll), math.radians(pitch), math.radians(yaw)),
                                          "ZYX").to_matrix().to_4x4()


def _lowest(objs):
    low = math.inf
    for o in objs:
        m = Matrix.Translation(o.location) @ o.rotation_euler.to_matrix().to_4x4()
        for v in o.data.vertices:
            low = min(low, (m @ v.co).z)
    return low


def _settle(objs, z=0.0):
    """Shift `objs` so their lowest vertex sits at `z`."""
    dz = z - _lowest(objs)
    for o in objs:
        o.location.z += dz


@prop
def sacks_grain():
    mats = _mats()
    # Two sacks lying side by side, necks at opposite ends.
    for i, (y, yaw, x, seed) in enumerate([(-GAP, 4, -0.07, 10), (GAP, 183, 0.07, 20)]):
        parts = _sack(f"sacks_grain_low{i}", LIE_L, LIE_R, LIE_FLAT, _frame((x, y, 0), yaw), mats, seed,
                      body="cloth" if i == 0 else "pale")
        _settle(parts)
    # The third propped across them, neck tipped up.
    _sack("sacks_grain_top", LIE_L * 0.95, LIE_R * 0.96, LIE_FLAT, _frame((0.02, 0.0, TOP_Z), 78, -12, 0), mats,
          30)


@prop
def sacks_grain_one():
    mats = _mats()
    # Upright: the sack's local +x (neck) points up, its local -x end slumps on the ground.
    parts = _sack("sacks_grain_one", UP_H, UP_R, 1.0, _frame((0, 0, 0), 20, -90), mats, 40, down=(-1, 0, 0))
    _settle(parts)
