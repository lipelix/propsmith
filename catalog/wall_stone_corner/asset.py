"""An L-shaped corner of village fieldstone wall: arms running 0.75 m to +x and to +y, joined in a corner pier at the
origin; rough stone blocks in staggered courses over a recessed mortar core, flat capstones on top
(generated by npm run new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box

MODULE = 1.5  # metres: the length wall and fence sections join at
EDGE = MODULE / 2  # the arms end half a module out, where straight sections centred a module away begin
T = 0.45  # wall thickness, metres
H = 2.4  # overall height including the capstones
# The `_low` variant: a cutaway wall for buildings shown without a roof.
LOW_H = 1.38
CAP_H = 0.08  # capstone thickness
CAP_OVER = 0.025  # capstone overhang on each face
COURSE_H_FULL = (H - CAP_H - 0.01) / 8  # 8 courses at full height; lower walls keep fewer of the same height
GAP = 0.026  # mortar joint between blocks
INSET = 0.025  # how far the mortar core sits behind the block faces
QUOIN = 0.62  # length of the corner quoin block that ties the two arms together

# Shared stone palette of the village wall set (wall_stone_straight, _corner, _doorframe): keep them equal.
STONE = (0.34, 0.295, 0.235)
STONE_OLD = (0.27, 0.235, 0.19)
STONE_PALE = (0.40, 0.36, 0.29)
MORTAR = (0.11, 0.10, 0.085)
CAP = (0.27, 0.255, 0.23)


def _run(rnd, start, end, lo=0.3, hi=0.46):
    """Split [start, end] into block spans of lo..hi metres with mortar gaps; the last block ends at `end`."""
    spans, a = [], start
    while end - a > 0:
        length = rnd.uniform(lo, hi)
        if end - a - length < lo * 0.7:
            length = end - a
        spans.append((a, min(a + length, end)))
        a += length
    return spans


def _corner(top):
    """The corner, `top` metres high with its capstones."""
    body_h = top - CAP_H - 0.01  # top of the mortar core (capstones sit on it)
    courses = max(2, round(body_h / COURSE_H_FULL))
    course_h = body_h / courses
    rnd = random.Random(23)
    stones = [
        material("wall_stone_corner_stone", STONE, vary=0.28, scale=9),
        material("wall_stone_corner_old", STONE_OLD, vary=0.3, scale=8),
        material("wall_stone_corner_pale", STONE_PALE, vary=0.25, scale=10),
    ]
    mortar = material("wall_stone_corner_mortar", MORTAR, vary=0.15, scale=20)
    cap = material("wall_stone_corner_cap", CAP, vary=0.25, scale=7)

    def stone():
        r = rnd.random()
        return stones[0] if r < 0.6 else stones[1] if r < 0.85 else stones[2]

    # Mortar core: one slab per arm, a little thinner than the blocks so the joints read recessed.
    core = T - 2 * INSET
    box("core_x", (EDGE + core / 2, core, body_h), ((EDGE - core / 2) / 2, 0, body_h / 2), mortar, bevel=0)
    box("core_y", (core, EDGE - core / 2, body_h), (0, (EDGE + core / 2) / 2, body_h / 2), mortar, bevel=0)

    # Courses: the corner quoin alternates between the arms so the joints stagger round the corner.
    for c in range(courses):
        z0 = c * course_h
        h = course_h - GAP
        along_x = c % 2 == 0
        # Quoin: a long block through the corner, running along one arm.
        q_len = QUOIN * rnd.uniform(0.92, 1.05)
        if along_x:
            box(f"quoin_{c}", (q_len, T, h), (-T / 2 + q_len / 2, 0, z0 + h / 2), stone(),
                rot=(0, 0, rnd.uniform(-1, 1)), bevel=0.022)
            x_start, y_start = -T / 2 + q_len + GAP, T / 2 + GAP / 2
        else:
            box(f"quoin_{c}", (T, q_len, h), (0, -T / 2 + q_len / 2, z0 + h / 2), stone(),
                rot=(0, 0, rnd.uniform(-1, 1)), bevel=0.022)
            x_start, y_start = T / 2 + GAP / 2, -T / 2 + q_len + GAP
        for i, (a, b) in enumerate(_run(rnd, x_start, EDGE)):
            ln = b - a - GAP
            bh = h * rnd.uniform(0.9, 1.0)
            box(f"block_x_{c}_{i}", (ln, T * rnd.uniform(0.96, 1.0), bh),
                (a + ln / 2, rnd.uniform(-0.014, 0.014), z0 + bh / 2), stone(),
                rot=(0, 0, rnd.uniform(-1.2, 1.2)), bevel=rnd.uniform(0.018, 0.025))
        for i, (a, b) in enumerate(_run(rnd, y_start, EDGE)):
            ln = b - a - GAP
            bh = h * rnd.uniform(0.9, 1.0)
            box(f"block_y_{c}_{i}", (T * rnd.uniform(0.96, 1.0), ln, bh),
                (rnd.uniform(-0.014, 0.014), a + ln / 2, z0 + bh / 2), stone(),
                rot=(0, 0, rnd.uniform(-1.2, 1.2)), bevel=rnd.uniform(0.018, 0.025))

    # Capstones: a square one over the pier, then flat slabs out to the end of each arm.
    cw = T + 2 * CAP_OVER
    zc = body_h + CAP_H / 2
    box("cap_corner", (cw, cw, CAP_H), (0, 0, zc), cap, rot=(0, 0, rnd.uniform(-1.5, 1.5)), bevel=0.016)
    for axis in ("x", "y"):
        for i, (a, b) in enumerate(_run(rnd, cw / 2 + 0.012, EDGE, 0.24, 0.34)):
            ln = b - a - 0.014
            ch = CAP_H * rnd.uniform(0.85, 1.0)
            mid = a + ln / 2
            at = (mid, 0, body_h + ch / 2) if axis == "x" else (0, mid, body_h + ch / 2)
            size = (ln, cw * rnd.uniform(0.95, 1.0), ch) if axis == "x" else (cw * rnd.uniform(0.95, 1.0), ln, ch)
            box(f"cap_{axis}_{i}", size, at, cap, rot=(0, 0, rnd.uniform(-1.2, 1.2)), bevel=0.016)


@prop
def wall_stone_corner():
    _corner(H)


@prop
def wall_stone_corner_low():
    _corner(LOW_H)
