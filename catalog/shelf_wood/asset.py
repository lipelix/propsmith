"""A merchant's wooden shelf unit against a wall, open front on -y: two plank sides, a back of vertical boards, three
shelves plus the top holding clay jars, a folded bolt of dull cloth, small wooden boxes and a coil of rope (generated by
npm run new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

# Overall size: 1.35 m wide (x), 0.45 m deep (y), 1.5 m high with the goods on top. The unit stands behind the
# origin (+y), its back 0.74 m from it, so it can go against a wall.
W = 1.35
D = 0.45
H_TOP = 1.32  # top surface of the carcass; goods on top reach about 1.5 m
BACK_Y = 0.75 - 0.01  # outer face of the back
FRONT_Y = BACK_Y - D
MID_Y = (BACK_Y + FRONT_Y) / 2
SIDE_T = 0.035  # plank sides
BACK_T = 0.02  # vertical back boards
BACK_BOARDS = 6
SHELF_T = 0.03
SHELF_Z = (0.12, 0.52, 0.92)  # top surfaces of the three shelves
TOP_T = 0.04
TOP_OVER = 0.02  # the top overhangs the sides a little
PLINTH_H = 0.09  # kick board under the bottom shelf, set back
INNER_W = W - 2 * SIDE_T
IN_FRONT = FRONT_Y + 0.02  # usable shelf depth starts here
IN_BACK = BACK_Y - BACK_T

WOOD = (0.22, 0.135, 0.07)  # linear RGB
WOOD_OLD = (0.18, 0.11, 0.058)
WOOD_TOP = (0.23, 0.145, 0.078)
BOX_WOOD = (0.25, 0.17, 0.09)
CLAY = (0.38, 0.15, 0.07)
CLAY_PALE = (0.4, 0.27, 0.15)
GLAZE = (0.12, 0.16, 0.12)
CLOTH = (0.3, 0.25, 0.17)  # dull undyed wool
CLOTH_DYED = (0.22, 0.11, 0.08)  # faded madder
ROPE = (0.36, 0.27, 0.15)
IRON = (0.05, 0.05, 0.05)


def jar(name, x, y, z, r, h, mat, rnd):
    """A clay jar: belly, shoulder, short neck and a rolled rim."""
    cylinder(f"{name}_belly", r * 0.8, h * 0.55, (x, y, z), mat, r_top=r, segments=12, bevel=0.006)
    cylinder(f"{name}_shoulder", r, h * 0.3, (x, y, z + h * 0.55), mat, r_top=r * 0.55, segments=12, bevel=0.006)
    cylinder(f"{name}_neck", r * 0.42, h * 0.15, (x, y, z + h * 0.85), mat, r_top=r * 0.5, segments=10, bevel=0.004)


def crate(name, x, y, z, w, d, h, mat, iron, rnd):
    """A small lidded wooden box with a darker lid and an iron band."""
    rz = rnd.uniform(-6, 6)
    box(f"{name}_body", (w, d, h * 0.82), (x, y, z + h * 0.41), mat, rot=(0, 0, rz), bevel=0.008)
    box(f"{name}_lid", (w + 0.012, d + 0.012, h * 0.18), (x, y, z + h * 0.91), mat, rot=(0, 0, rz), bevel=0.008)
    box(f"{name}_band", (w + 0.006, 0.014, h * 0.82 + 0.004), (x, y, z + h * 0.41), iron, rot=(0, 0, rz), bevel=0)


def rope(name, x, y, z, R, r, turns, mat):
    """A coil of rope: stacked rings, each a little smaller."""
    for i in range(turns):
        torus(f"{name}_{i}", R - i * 0.008, r, (x + i * 0.003, y, z + r + i * r * 1.7), mat, major=14, minor=5)


@prop
def shelf_wood():
    rnd = random.Random(5)
    wood = material("shelf_wood", WOOD, vary=0.25, scale=14)
    old = material("shelf_wood_old", WOOD_OLD, vary=0.3, scale=11)
    top_mat = material("shelf_top", WOOD_TOP, vary=0.28, scale=12)
    box_wood = material("shelf_box", BOX_WOOD, vary=0.25, scale=16)
    clay = material("shelf_clay", CLAY, vary=0.2, scale=8, rough=0.9)
    clay_pale = material("shelf_clay_pale", CLAY_PALE, vary=0.2, scale=8, rough=0.9)
    glaze = material("shelf_glaze", GLAZE, vary=0.15, scale=10, rough=0.45)
    cloth = material("shelf_cloth", CLOTH, vary=0.2, scale=22, rough=0.95, crevice=0.4)
    cloth_dyed = material("shelf_cloth_dyed", CLOTH_DYED, vary=0.2, scale=22, rough=0.95, crevice=0.4)
    rope_mat = material("shelf_rope", ROPE, vary=0.3, scale=40, rough=0.95)
    iron = material("shelf_iron", IRON, vary=0.1, scale=20, rough=0.55, metal=0.6)

    # Two plank sides, full depth, standing on the ground.
    for i, s in enumerate((-1, 1)):
        box(f"side_{i}", (SIDE_T, D, H_TOP - TOP_T), (s * (W / 2 - SIDE_T / 2), MID_Y, (H_TOP - TOP_T) / 2),
            old if i else wood, rot=(0, 0, rnd.uniform(-0.3, 0.3)), bevel=0.01)

    # The back: vertical boards side by side, each slightly uneven.
    bw = INNER_W / BACK_BOARDS
    for i in range(BACK_BOARDS):
        x = -INNER_W / 2 + bw / 2 + i * bw
        box(f"back_{i}", (bw - 0.004, BACK_T, H_TOP - TOP_T - rnd.uniform(0, 0.01)),
            (x, BACK_Y - BACK_T / 2, (H_TOP - TOP_T) / 2), old if i % 3 == 1 else wood,
            rot=(0, rnd.uniform(-0.3, 0.3), 0), bevel=0.006)

    # Kick board under the bottom shelf, set back a little.
    box("plinth", (INNER_W, 0.025, PLINTH_H), (0, FRONT_Y + 0.04, PLINTH_H / 2), old, bevel=0.006)

    # Three shelves.
    for i, z in enumerate(SHELF_Z):
        box(f"shelf_{i}", (INNER_W + 0.002, D - BACK_T - 0.01, SHELF_T),
            (0, MID_Y - BACK_T / 2 - 0.005, z - SHELF_T / 2), old if i == 1 else wood,
            rot=(rnd.uniform(-0.3, 0.3), 0, 0), bevel=0.008)

    # The top board, overhanging the sides and the front.
    box("top", (W, D, TOP_T), (0, MID_Y, H_TOP - TOP_T / 2), top_mat, bevel=0.012)

    gy = (IN_FRONT + IN_BACK) / 2  # goods stand mid-depth

    # Bottom shelf: two big clay jars and the coil of rope.
    z0 = SHELF_Z[0]
    jar("jar_big_0", -0.44, gy, z0, 0.12, 0.33, clay, rnd)
    jar("jar_big_1", -0.17, gy + 0.02, z0, 0.1, 0.28, clay_pale, rnd)
    rope("rope", 0.33, gy, z0, 0.13, 0.026, 3, rope_mat)

    # Middle shelf: the folded bolt of cloth and a row of small boxes.
    z1 = SHELF_Z[1]
    for i, (h, mat) in enumerate(((0.07, cloth), (0.06, cloth_dyed), (0.065, cloth))):
        zz = z1 + sum((0.07, 0.06, 0.065)[:i])
        box(f"cloth_{i}", (0.42 - i * 0.02, 0.3, h), (-0.33 + rnd.uniform(-0.015, 0.015), gy, zz + h / 2),
            mat, rot=(0, 0, rnd.uniform(-3, 3)), bevel=0.02)
    crate("box_0", 0.12, gy, z1, 0.2, 0.22, 0.16, box_wood, iron, rnd)
    crate("box_1", 0.38, gy - 0.01, z1, 0.22, 0.24, 0.2, box_wood, iron, rnd)
    crate("box_2", 0.38, gy - 0.01, z1 + 0.2, 0.16, 0.18, 0.12, old, iron, rnd)

    # Upper shelf: a row of small glazed and plain jars.
    z2 = SHELF_Z[2]
    for i, x in enumerate((-0.47, -0.3, -0.13, 0.05)):
        mat = (glaze, clay, glaze, clay_pale)[i]
        jar(f"jar_small_{i}", x + rnd.uniform(-0.01, 0.01), gy + rnd.uniform(-0.03, 0.03), z2,
            0.065, rnd.uniform(0.17, 0.21), mat, rnd)
    crate("box_3", 0.36, gy, z2, 0.26, 0.24, 0.18, box_wood, iron, rnd)

    # On the top: one jar and a small box.
    jar("jar_top", -0.38, gy, H_TOP, 0.07, 0.17, clay, rnd)
    crate("box_top", 0.3, gy, H_TOP, 0.24, 0.22, 0.14, old, iron, rnd)
