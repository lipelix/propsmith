"""A crypt gate: a round-arched stone doorway frame with an iron grille door of vertical bars, two cross bands,
spear-point tips under the arch, heavy strap hinges and a large padlock on a hasp (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

# Overall dimensions (metres), from the description: 1.6 m wide, about 2.4 m high.
W = 1.6  # frame width (x)
T = 0.4  # frame depth (y)
OPEN_W = 1.0  # clear opening between the jambs
JAMB = (W - OPEN_W) / 2  # each jamb, 0.3 m
SPRING = 1.5  # springing line of the arch (top of the imposts)
R_IN = OPEN_W / 2  # arch intrados radius, apex at 2.0 m
R_OUT = R_IN + JAMB  # arch extrados radius, 2.3 m
KEY_OUT = R_OUT + 0.07  # keystone stands taller
VOUSSOIRS = 9
SILL_H = 0.06  # threshold slab
PLINTH_H = 0.26
IMPOST_H = 0.1
JOINT = 0.012  # mortar joint between stones

# Iron grille.
BAR = 0.022  # square bar
STILE = 0.035
BAND_H, BAND_T = 0.05, 0.014
BANDS_Z = (0.16, 0.7, 1.28)  # bottom rail and the two cross bands
BARS = 8
TIP_H = 0.1  # spear point
TIP_GAP = 0.05  # air between the spear points and the arch

STONE = (0.34, 0.325, 0.295)  # linear RGB: cold grey crypt stone
STONE_OLD = (0.25, 0.24, 0.215)
STONE_PALE = (0.42, 0.4, 0.36)
MORTAR = (0.08, 0.075, 0.065)
IRON = (0.045, 0.045, 0.045)
RUST = (0.09, 0.055, 0.035)


def _wedge(name, corners, y0, y1, mat, bevel=0.015):
    """A box reshaped into a prism: `corners` are four (x, z) points counter-clockwise (inner start, outer start,
    outer end, inner end), extruded from `y0` to `y1`."""
    obj = box(name, (1, 1, 1), (0, 0, 0), mat, bevel=bevel)
    for v in obj.data.vertices:
        i = {(False, False): 0, (True, False): 1, (True, True): 2, (False, True): 3}[(v.co.x > 0, v.co.z > 0)]
        x, z = corners[i]
        v.co.x, v.co.z = x, z
        v.co.y = y1 if v.co.y > 0 else y0
    return obj


def _polar(r, a):
    return (r * math.cos(a), SPRING + r * math.sin(a))


@prop
def crypt_gate_iron():
    rnd = random.Random(7)
    stone = material("crypt_gate_iron_stone", STONE, vary=0.28, scale=8, crevice=0.7)
    old = material("crypt_gate_iron_stone_old", STONE_OLD, vary=0.3, scale=9, crevice=0.7)
    pale = material("crypt_gate_iron_stone_pale", STONE_PALE, vary=0.22, scale=7, crevice=0.65)
    mortar = material("crypt_gate_iron_mortar", MORTAR, vary=0.1, scale=12)
    iron = material("crypt_gate_iron_iron", IRON, rough=0.55, vary=0.22, scale=20, metal=0.6)
    rust = material("crypt_gate_iron_rust", RUST, rough=0.8, vary=0.3, scale=24, metal=0.3)

    def pick():
        return rnd.choice((stone, stone, old, pale))

    # --- Stone frame.
    box("sill", (OPEN_W + 0.02, T - 0.02, SILL_H), (0, 0, SILL_H / 2), old, bevel=0.012)
    x_in, x_out = OPEN_W / 2, W / 2
    for s in (-1, 1):
        xc = s * (x_in + x_out) / 2
        box(f"core_{s}", (JAMB - 0.03, T - 0.06, SPRING), (xc, 0, SPRING / 2), mortar, bevel=0)
        # A heavy plinth block, a few courses of jamb stones, a projecting impost under the arch.
        box(f"plinth_{s}", (JAMB + 0.02, T + 0.04, PLINTH_H - JOINT), (xc, 0, (PLINTH_H - JOINT) / 2), old,
            rot=(0, 0, rnd.uniform(-0.6, 0.6)), bevel=0.02)
        z0, z1 = PLINTH_H, SPRING - IMPOST_H
        courses = 4
        ch = (z1 - z0) / courses
        for c in range(courses):
            box(f"jamb_{s}_{c}", (JAMB * rnd.uniform(0.96, 1.0), T * rnd.uniform(0.97, 1.0), ch - JOINT),
                (xc + s * rnd.uniform(-0.006, 0.004), rnd.uniform(-0.005, 0.005), z0 + ch * (c + 0.5)), pick(),
                rot=(rnd.uniform(-0.8, 0.8), 0, rnd.uniform(-1.2, 1.2)), bevel=0.02)
        box(f"impost_{s}", (JAMB + 0.03, T + 0.04, IMPOST_H - JOINT / 2), (xc + s * 0.01, 0, z1 + IMPOST_H / 2), pale,
            bevel=0.018)

    # Arch ring of wedge voussoirs over a recessed mortar ring; the keystone stands proud.
    step = math.pi / VOUSSOIRS
    half_j = JOINT / 2 / R_OUT
    for i in range(VOUSSOIRS):
        a0, a1 = i * step, (i + 1) * step
        key = i == VOUSSOIRS // 2
        r_out = KEY_OUT if key else R_OUT * rnd.uniform(0.985, 1.0)
        _wedge(f"mortar_{i}", [_polar(R_IN + 0.02, a0), _polar(R_OUT - 0.02, a0), _polar(R_OUT - 0.02, a1),
                               _polar(R_IN + 0.02, a1)], -T / 2 + 0.03, T / 2 - 0.03, mortar, bevel=0)
        b0, b1 = a0 + half_j, a1 - half_j
        depth = T / 2 + (0.02 if key else rnd.uniform(-0.004, 0.004))
        _wedge(f"voussoir_{i}", [_polar(R_IN, b0), _polar(r_out, b0), _polar(r_out, b1), _polar(R_IN, b1)],
               -depth, depth, pale if key else pick(), bevel=0.018)

    # --- Iron grille door, in the middle of the opening's depth, hinged on the left jamb.
    gx = x_in - 0.008 - STILE / 2  # stile centre
    bottom = SILL_H + 0.02
    stile_top = SPRING + 0.04
    for s in (-1, 1):
        cylinder(f"stile_{s}", STILE / 2, stile_top - bottom, (s * gx, 0, bottom), iron, segments=8, bevel=0)
        box(f"stile_cap_{s}", (0.05, 0.05, 0.05), (s * gx, 0, stile_top + 0.02), iron, rot=(0, 45, 45), bevel=0.008)
    for j, z in enumerate(BANDS_Z):
        for f in (-1, 1):
            box(f"band_{j}_{f}", (2 * gx, BAND_T, BAND_H), (0, f * (BAR / 2 + BAND_T / 2), z), iron, bevel=0)
    span = 2 * gx / (BARS + 1)
    for i in range(BARS):
        x = -gx + span * (i + 1)
        apex = SPRING + math.sqrt(R_IN ** 2 - x ** 2) - TIP_GAP
        top = apex - TIP_H
        mat = rust if rnd.random() < 0.3 else iron
        box(f"bar_{i}", (BAR, BAR, top - bottom + 0.01), (x, 0, (top + bottom) / 2), mat,
            rot=(0, rnd.uniform(-0.4, 0.4), 0), bevel=0)
        cylinder(f"collar_{i}", 0.02, 0.025, (x, 0, top - 0.02), iron, segments=8, bevel=0)
        cylinder(f"tip_{i}", 0.032, TIP_H, (x, 0, top + 0.005), iron, r_top=0.002, segments=4, rot=(0, 0, 45),
                 bevel=0)

    # Heavy strap hinges on the left: a knuckle on a pintle set into the jamb, a long strap on each face.
    for k, z in enumerate((BANDS_Z[0] + 0.12, BANDS_Z[2] - 0.08)):
        cylinder(f"knuckle_{k}", 0.026, 0.14, (-gx - 0.005, 0, z - 0.07), iron, segments=10, bevel=0.005)
        box(f"pintle_{k}", (0.06, 0.03, 0.04), (-x_in - 0.01, 0, z - 0.09), iron, bevel=0.005)
        for f in (-1, 1):
            y = f * (BAR / 2 + BAND_T + 0.006)
            box(f"strap_{k}_{f}", (0.4, 0.012, 0.07), (-gx + 0.2, y, z), iron, bevel=0.004)
            cylinder(f"strap_end_{k}_{f}", 0.05, 0.012, (-gx + 0.4, y + f * 0.006, z), iron, segments=10,
                     rot=(90 * f, 0, 0), bevel=0)

    # Hasp and padlock on the right: a strap on the gate over a staple set into the jamb, the lock hanging in front.
    lz = 1.0
    hy = -(BAR / 2 + BAND_T + 0.006)
    box("hasp", (0.2, 0.012, 0.05), (gx - 0.08, hy, lz), iron, bevel=0.004)
    box("staple_plate", (0.05, 0.06, 0.05), (x_in + 0.005, -0.04, lz), iron, bevel=0.005)
    torus("staple", 0.02, 0.006, (gx + 0.005, -0.075, lz), iron, rot=(0, 90, 0), major=12, minor=6)
    torus("shackle", 0.05, 0.011, (gx - 0.03, -0.085, lz - 0.06), iron, rot=(90, 0, 0), major=16, minor=6)
    box("padlock", (0.16, 0.06, 0.17), (gx - 0.03, -0.085, lz - 0.17), rust, bevel=0.016)
    box("keyhole_plate", (0.05, 0.006, 0.065), (gx - 0.03, -0.116, lz - 0.18), iron, bevel=0.003)
