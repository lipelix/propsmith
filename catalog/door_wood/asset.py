"""A sturdy village oak plank door standing closed: vertical planks, two ledges and a diagonal brace on the back, iron
strap hinges and a ring handle on the front (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

TILE = 1.5  # metres per tile
# Overall dimensions: fits the 1.0 x 2.0 m opening of wall_stone_doorframe, along x through the tile centre.
W, H = 1.0, 2.0  # door leaf width (x) and height (z)
PLANKS = 6
PLANK_T = 0.045  # plank thickness (y)
BACK_T = 0.035  # ledge thickness on the back (+y); planks + ledges = 0.08 m
PLANK_Y = -0.04 + PLANK_T / 2  # planks span y -0.04 .. +0.005
FRONT_Y = -0.04  # front face (-y)
BACK_Y = FRONT_Y + PLANK_T  # back face of the planks
LEDGE_H = 0.16
LEDGE_Z = (0.42, 1.58)  # ledge centres, the hinges sit on them
STRAP_L, STRAP_H, STRAP_T = 0.62, 0.05, 0.008
HANDLE_X, HANDLE_Z = 0.33, 1.0
RING_R, RING_T = 0.065, 0.012

OAK = (0.2, 0.12, 0.062)  # linear RGB
OAK_OLD = (0.155, 0.095, 0.052)
LEDGE = (0.175, 0.105, 0.055)
IRON = (0.04, 0.038, 0.036)


@prop
def door_wood():
    rnd = random.Random(7)
    oak = material("door_wood_plank", OAK, vary=0.25, scale=14)
    old = material("door_wood_plank_old", OAK_OLD, vary=0.28, scale=14)
    ledge = material("door_wood_ledge", LEDGE, vary=0.22, scale=12)
    iron = material("door_wood_iron", IRON, rough=0.55, vary=0.2, scale=20, metal=0.6)

    # Vertical planks with a hairline gap, a little jitter in width, height and lean.
    pw = W / PLANKS
    # Recessed core inside the planks: the joints read dark instead of letting light through.
    box("core", (W - 0.03, PLANK_T - 0.016, H - 0.04), (0, PLANK_Y, H / 2), old, bevel=0)
    for i in range(PLANKS):
        h = H - rnd.uniform(0.0, 0.025)
        box(
            f"plank_{i}",
            (pw - 0.005, PLANK_T * rnd.uniform(0.94, 1.0), h),
            (-W / 2 + pw * (i + 0.5) + rnd.uniform(-0.002, 0.002), PLANK_Y + rnd.uniform(-0.002, 0.002), h / 2 + 0.001),
            rnd.choice((oak, oak, old)),
            rot=(0, rnd.uniform(-0.25, 0.25), 0),
            bevel=0.008,
        )

    # Back: two horizontal ledges and a diagonal brace between them (bottom on the hinge side).
    ledge_w = W - 0.08
    for k, z in enumerate(LEDGE_Z):
        box(f"ledge_{k}", (ledge_w, BACK_T, LEDGE_H), (0, BACK_Y + BACK_T / 2, z), ledge, bevel=0.01)
    z0, z1 = LEDGE_Z[0] + LEDGE_H / 2 - 0.02, LEDGE_Z[1] - LEDGE_H / 2 + 0.02
    x0, x1 = -ledge_w / 2 + 0.1, ledge_w / 2 - 0.1
    ang = math.degrees(math.atan2(z1 - z0, x1 - x0))
    length = math.hypot(x1 - x0, z1 - z0)
    box(
        "brace",
        (length, BACK_T - 0.006, 0.13),
        ((x0 + x1) / 2, BACK_Y + (BACK_T - 0.006) / 2, (z0 + z1) / 2),
        ledge,
        rot=(0, -ang, 0),
        bevel=0.01,
    )

    # Front: two iron strap hinges on the ledge lines, knuckles on the -x edge, a round end and rivets.
    sy = FRONT_Y - STRAP_T / 2 + 0.001
    for k, z in enumerate(LEDGE_Z):
        x_end = -W / 2 + STRAP_L
        box(f"strap_{k}", (STRAP_L, STRAP_T, STRAP_H), (-W / 2 + STRAP_L / 2, sy, z), iron, bevel=0.003)
        cylinder(f"strap_end_{k}", 0.035, STRAP_T, (x_end, FRONT_Y + 0.001, z), iron, segments=12,
                 rot=(90, 0, 0), bevel=0.002)
        cylinder(f"knuckle_{k}", 0.02, 0.14, (-W / 2 - 0.005, FRONT_Y + 0.006, z - 0.07), iron, segments=10,
                 bevel=0.003)
        for r, rx in enumerate((-W / 2 + 0.12, -W / 2 + 0.33, x_end)):
            cylinder(f"rivet_{k}_{r}", 0.011, 0.008, (rx, FRONT_Y - STRAP_T + 0.002, z), iron, segments=8,
                     rot=(90, 0, 0), bevel=0.002)

    # Ring handle: a backplate, a staple and a hanging ring.
    box("handle_plate", (0.07, 0.01, 0.1), (HANDLE_X, FRONT_Y - 0.004, HANDLE_Z), iron, bevel=0.003)
    cylinder("handle_staple", 0.008, 0.03, (HANDLE_X, FRONT_Y - 0.006, HANDLE_Z + 0.02), iron, segments=8,
             rot=(90, 0, 0), bevel=0)
    torus("handle_ring", RING_R, RING_T, (HANDLE_X, FRONT_Y - 0.03, HANDLE_Z + 0.02 - RING_R), iron,
          rot=(90, 0, 0), major=20, minor=8)
