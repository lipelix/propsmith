"""A small wooden rowboat resting upright on the ground: overlapping clinker planks, a pointed bow (+x), a flat transom
(-x), two thwart seats and a pair of oars laid inside (generated by npm run new)."""
import math
import random

import bmesh
import bpy
from mathutils import Vector

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder

# Overall dimensions (metres): about 3.2 m long, 1.2 m wide, sheer ~0.6 m high amidships.
STERN_X0, STERN_X1 = -1.50, -1.55  # transom end of the planks at the keel and at the sheer (raked)
BOW_X0, BOW_X1 = 1.40, 1.54  # stem line at the keel and at the sheer (raked)
HALF_BEAM = 0.54  # half-breadth of the plank surface at the widest station
TRANSOM_RATIO = 0.72  # half-breadth at the transom / at the widest station
WIDEST = 0.45  # station (0 transom .. 1 bow) of the widest point and lowest keel
KEEL_Z = 0.07  # hull bottom above the ground at the lowest point (the keel is under it)
KEEL_RISE_STERN, KEEL_RISE_BOW = 0.06, 0.2  # rocker of the keel line
SHEER_Z = 0.56  # sheer height amidships
SHEER_RISE_STERN, SHEER_RISE_BOW = 0.07, 0.17
STRAKES = 6  # planks per side
STEP = 0.034 # clinker step: how far a plank's lower edge stands out
OVERLAP = 0.035  # lap of one plank over the next (fraction of the girth)
# Plank thickness (normal to the hull): enough that each lap closes onto the plank below, no light through the seam.
PLANK_T = STEP * (1 / STRAKES) / (1 / STRAKES + OVERLAP) + 0.004
NU, NV = 20, 3  # mesh stations along the hull and across a plank
THWART_TOP = 0.38
THWART_XS = (-0.55, 0.35)
OAR_LEN, OAR_R = 2.35, 0.022

PLANK = (0.25, 0.16, 0.085)
PLANK_OLD = (0.17, 0.125, 0.085)
TIMBER = (0.13, 0.08, 0.045)
SEAT = (0.22, 0.145, 0.08)
OAR = (0.27, 0.19, 0.11)
IRON = (0.045, 0.045, 0.045)


def _smooth(t):
    return max(0.0, min(1.0, t))


def _hb(u):
    """Half-breadth of the plank surface at station u."""
    if u <= WIDEST:
        k = (WIDEST - u) / WIDEST
        return HALF_BEAM * (1 - (1 - TRANSOM_RATIO) * k * k)
    k = (u - WIDEST) / (1 - WIDEST)
    return max(0.004, HALF_BEAM * (1 - k * k) ** 0.75)


def _keel(u):
    if u <= WIDEST:
        return KEEL_Z + KEEL_RISE_STERN * ((WIDEST - u) / WIDEST) ** 2
    return KEEL_Z + KEEL_RISE_BOW * ((u - WIDEST) / (1 - WIDEST)) ** 2.5


def _sheer(u):
    if u <= WIDEST:
        return SHEER_Z + SHEER_RISE_STERN * ((WIDEST - u) / WIDEST) ** 2
    return SHEER_Z + SHEER_RISE_BOW * ((u - WIDEST) / (1 - WIDEST)) ** 2


def _x(u, v):
    x0 = STERN_X0 + (STERN_X1 - STERN_X0) * v
    x1 = BOW_X0 + (BOW_X1 - BOW_X0) * v
    return x0 + u * (x1 - x0)


def _section(u, v):
    """(y, z) of the plank surface at station u, girth v (0 keel .. 1 sheer), +y side."""
    th = _smooth(v) * math.pi / 2
    zk = _keel(u)
    return _hb(u) * math.sin(th) ** 0.6, zk + (_sheer(u) - zk) * (1 - math.cos(th))


def _normal(u, v):
    """Outward normal (ny, nz) of the section at (u, v), +y side."""
    e = 0.002
    a, b = _section(u, max(0.0, v - e)), _section(u, min(1.0, v + e))
    dy, dz = b[0] - a[0], b[1] - a[1]
    n = math.hypot(dy, dz) or 1.0
    return dz / n, -dy / n


def _point(u, v, off, s):
    y, z = _section(u, v)
    ny, nz = _normal(u, v)
    return Vector((_x(u, v), s * (y + ny * off), z + nz * off))


def _link(name, bm, mat, sharp=40):
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    mesh.shade_smooth()
    mesh.set_sharp_from_angle(angle=math.radians(sharp))
    mesh.materials.append(mat)
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def _solid(name, outer, inner, mat):
    """A closed slab between two grids of points outer[i][j], inner[i][j] of the same shape."""
    bm = bmesh.new()
    A = [[bm.verts.new(p) for p in row] for row in outer]
    B = [[bm.verts.new(p) for p in row] for row in inner]
    ni, nj = len(outer), len(outer[0])
    for i in range(ni - 1):
        for j in range(nj - 1):
            bm.faces.new((A[i][j], A[i + 1][j], A[i + 1][j + 1], A[i][j + 1]))
            bm.faces.new((B[i][j], B[i][j + 1], B[i + 1][j + 1], B[i + 1][j]))
    for i in range(ni - 1):
        for j in (0, nj - 1):
            bm.faces.new((A[i][j], B[i][j], B[i + 1][j], A[i + 1][j]))
    for j in range(nj - 1):
        for i in (0, ni - 1):
            bm.faces.new((A[i][j], A[i][j + 1], B[i][j + 1], B[i][j]))
    return _link(name, bm, mat)


def _sweep(name, centres, sides, ups, side, up, mat):
    """A closed bar along `centres`, its rectangle spanning `side` (lo, hi) along `sides` and `up` along `ups`."""
    outer, inner = [], []
    for c, a, b in zip(centres, sides, ups):
        outer.append([c + a * side[1] + b * up[0], c + a * side[1] + b * up[1]])
        inner.append([c + a * side[0] + b * up[0], c + a * side[0] + b * up[1]])
    return _solid(name, outer, inner, mat)


def _y_inside(x, z):
    """Half-breadth of the plank surface at (x, z), for fitting seats and boards inside the hull."""
    u = (x - _x(0, 0.7)) / (_x(1, 0.7) - _x(0, 0.7))
    lo, hi = 0.0, 1.0
    for _ in range(30):
        mid = (lo + hi) / 2
        if _section(u, mid)[1] < z:
            lo = mid
        else:
            hi = mid
    return _section(u, lo)[0]


def _hull(rnd):
    planks = [
        material("rowboat_planks", PLANK, vary=0.25, scale=12),
        material("rowboat_planks_old", PLANK_OLD, vary=0.3, scale=10),
    ]
    timber = material("rowboat_timber", TIMBER, vary=0.2, scale=14)

    # Clinker strakes: each plank's lower edge laps outside the top of the plank below.
    h = 1 / STRAKES
    assert abs(h - 1 / 6) < 1e-9  # PLANK_T assumes six strakes
    for s in (-1, 1):
        for k in range(STRAKES):
            v0 = max(0.0, k * h - (OVERLAP if k else 0))
            v1 = (k + 1) * h
            # Alternate tones per strake so the laps read, with the odd plank swapped.
            mat = planks[(k + (rnd.random() < 0.2)) % 2]
            outer, inner = [], []
            for i in range(NU + 1):
                u = i / NU
                ro, ri = [], []
                for j in range(NV + 1):
                    v = v0 + (v1 - v0) * j / NV
                    off = PLANK_T + STEP * (v1 - v) / (v1 - v0)
                    ro.append(_point(u, v, off, s))
                    ri.append(_point(u, v, off - PLANK_T, s))
                outer.append(ro)
                inner.append(ri)
            _solid(f"strake_{s}_{k}", outer, inner, mat)

    # Keel along the bottom, turning up into the stem at the bow.
    line = [Vector((_x(i / NU, 0), 0, _keel(i / NU))) for i in range(NU + 1)]
    zk, zs = _keel(1), _sheer(1)
    for j in range(1, 9):
        th = j / 8 * math.pi / 2
        line.append(Vector((_x(1, j / 8), 0, zk + (zs - zk) * (1 - math.cos(th)))))
    line.append(line[-1] + Vector((0.01, 0, 0.06)))
    norms = []
    for i, p in enumerate(line):
        a, b = line[max(0, i - 1)], line[min(len(line) - 1, i + 1)]
        t = (b - a).normalized()
        norms.append(Vector((t.z, 0, -t.x)))
    sides = [Vector((0, 1, 0))] * len(line)
    _sweep("keel", line, norms, sides, (-0.018, 0.05), (-0.03, 0.03), timber)

    # Gunwale rails along the sheer.
    for s in (-1, 1):
        cs, ns, us = [], [], []
        for i in range(NU + 1):
            u = min(i / NU, 0.985)
            ny, nz = _normal(u, 1.0)
            cs.append(_point(u, 1.0, PLANK_T, s))
            ns.append(Vector((0, s * ny, nz)))
            us.append(Vector((0, 0, 1)))
        _sweep(f"gunwale_{s}", cs, ns, us, (-0.012, 0.03), (-0.045, 0.018), timber)

    # Ribs inside the planking.
    for k, u in enumerate((0.14, 0.26, 0.38, 0.5, 0.62, 0.74)):
        for s in (-1, 1):
            cs, ns, xs = [], [], []
            for j in range(9):
                v = j / 8 * 0.97
                ny, nz = _normal(u, v)
                cs.append(_point(u, v, 0, s))
                ns.append(Vector((0, s * ny, nz)))
                xs.append(Vector((1, 0, 0)))
            _sweep(f"rib_{k}_{s}", cs, ns, xs, (-0.022, 0.0), (-0.018, 0.018), timber)

    # Flat transom closing the stern, a little proud of the planks.
    outline = []
    off = PLANK_T + STEP + 0.006
    for s, vs in ((-1, [1 - j / 10 for j in range(11)]), (1, [j / 10 for j in range(1, 11)])):
        for v in vs:
            p = _point(0, v, off, s)
            outline.append(p)
    top = max(p.z for p in outline) + 0.03
    outline = [Vector((p.x, p.y, p.z)) for p in outline]
    outline[0].z = outline[-1].z = top
    bm = bmesh.new()
    front = [bm.verts.new(p + Vector((0.008, 0, 0))) for p in outline]
    back = [bm.verts.new(p + Vector((-0.035, 0, 0))) for p in outline]
    bm.faces.new(front)
    bm.faces.new(list(reversed(back)))
    n = len(outline)
    for i in range(n):
        bm.faces.new((front[i], front[(i + 1) % n], back[(i + 1) % n], back[i]))
    _link("transom", bm, planks[1], sharp=30)
    return planks, timber


def _interior(rnd, timber):
    seat = material("rowboat_seat", SEAT, vary=0.22, scale=14)
    iron = material("rowboat_iron", IRON, rough=0.45, metal=0.8)

    # Two thwarts across the hull.
    for k, x in enumerate(THWART_XS):
        half = _y_inside(x, THWART_TOP - 0.035) - 0.004
        box(f"thwart_{k}", (0.22, 2 * half, 0.035), (x, 0, THWART_TOP - 0.0175), seat, rot=(0, 0, rnd.uniform(-1, 1)),
            bevel=0.008)

    # Floorboards on the ribs.
    z = KEEL_Z + 0.04
    for k, y in enumerate((-0.17, 0, 0.17)):
        box(f"floor_{k}", (1.45 + rnd.uniform(-0.05, 0.05), 0.13, 0.02), (-0.15 + rnd.uniform(-0.03, 0.03), y, z), seat,
            rot=(0, 0, rnd.uniform(-0.8, 0.8)), bevel=0.006)

    # Thole pins on the gunwales between the thwarts.
    for s in (-1, 1):
        p = _point((-0.12 - STERN_X1) / (BOW_X1 - STERN_X1), 1.0, PLANK_T + 0.01, s)
        cylinder(f"thole_{s}", 0.012, 0.09, (p.x, p.y, p.z + 0.01), iron, segments=8, bevel=0)


def _oar(name, handle, tip, z, mat):
    """An oar lying flat from the handle (x, y) to the blade tip (x, y), its loom at height z."""
    dx, dy = tip[0] - handle[0], tip[1] - handle[1]
    L = math.hypot(dx, dy)
    yaw = math.degrees(math.atan2(dy, dx))
    ux, uy = dx / L, dy / L
    blade = 0.55
    loom = L - blade + 0.1
    cylinder(f"{name}_loom", OAR_R, loom, (handle[0], handle[1], z), mat, rot=(0, 90, yaw), segments=8, bevel=0.004)
    cylinder(f"{name}_grip", OAR_R * 0.8, 0.14, (handle[0] - ux * 0.13, handle[1] - uy * 0.13, z), mat,
             rot=(0, 90, yaw), segments=8, bevel=0.004)
    c = L - blade / 2
    box(f"{name}_blade", (blade, 0.13, 0.016), (handle[0] + ux * c, handle[1] + uy * c, z), mat, rot=(0, 0, yaw),
        bevel=0.006)


@prop
def rowboat_wood():
    rnd = random.Random(7)
    planks, timber = _hull(rnd)
    _interior(rnd, timber)
    oar = material("rowboat_oar", OAR, vary=0.2, scale=16)
    z = THWART_TOP + OAR_R
    _oar("oar_a", (1.0, 0.1), (1.0 - OAR_LEN, 0.2), z, oar)
    _oar("oar_b", (0.92, -0.12), (0.92 - OAR_LEN, -0.24), z + 0.002, oar)
