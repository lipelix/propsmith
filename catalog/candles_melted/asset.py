"""A cluster of melted church candles on the floor about 0.4 m across: seven pale wax candles of different heights from
0.08 to 0.3 m, with drips and a shared puddle of hardened wax around their feet, small dark wicks on top (generated by
npm run new)."""
import math
import random

from propsmith import anchor, prop
from propsmith.materials import material
from propsmith.shapes import blob, cylinder, torus

# Overall dimensions (metres), from the description.
PUDDLE_R = 0.18  # main puddle radius (the cluster is about 0.4 m across with its lobes)
PUDDLE_SQUASH = 0.075  # puddle height as a fraction of its radius
WICK_R, WICK_H = 0.0035, 0.014

# The seven candles: (x, y, radius, body height). Heights 0.08 to 0.29 m; the wick brings the tallest to 0.3 m.
CANDLES = [
    (0.005, 0.030, 0.042, 0.290),
    (-0.090, -0.025, 0.036, 0.210),
    (0.095, -0.035, 0.034, 0.170),
    (-0.015, -0.105, 0.030, 0.120),
    (0.065, 0.100, 0.028, 0.140),
    (-0.090, 0.095, 0.032, 0.240),
    (0.135, 0.045, 0.024, 0.080),
]

WAX = (0.5, 0.45, 0.34)  # linear RGB, pale ivory
WAX_OLD = (0.44, 0.38, 0.27)
WAX_POOL = (0.46, 0.4, 0.29)
WICK = (0.05, 0.044, 0.038)


@prop
def candles_melted():
    rnd = random.Random(23)
    wax = material("candles_melted_wax", WAX, rough=0.45, vary=0.08, scale=12, crevice=0.25)
    old = material("candles_melted_wax_old", WAX_OLD, rough=0.5, vary=0.1, scale=12, crevice=0.3)
    pool = material("candles_melted_pool", WAX_POOL, rough=0.4, vary=0.12, scale=9, crevice=0.35)
    wick = material("candles_melted_wick", WICK, rough=0.9, vary=0.1, scale=30)

    # The shared puddle: one wide flat lump with a few smaller lobes spilling out of its edge.
    half = PUDDLE_R * PUDDLE_SQUASH
    blob("puddle", PUDDLE_R, (0, 0, half), pool, squash=(1, 0.92, PUDDLE_SQUASH), subdiv=2, seed=5, jitter=0.06)
    for i in range(4):
        a = math.radians(30 + i * 95 + rnd.uniform(-15, 15))
        r = rnd.uniform(0.045, 0.065)
        d = PUDDLE_R * 0.88
        sz = 0.012 / r
        blob(f"puddle_lobe_{i}", r, (d * math.cos(a), d * math.sin(a), r * sz), pool,
             squash=(1, 0.8, sz), subdiv=1, seed=40 + i, jitter=0.08)

    tallest = max(CANDLES, key=lambda c: c[3])
    for i, (x, y, r, h) in enumerate(CANDLES):
        x += rnd.uniform(-0.004, 0.004)
        y += rnd.uniform(-0.004, 0.004)
        h *= rnd.uniform(0.97, 1.0)
        m = old if i in (2, 5) else wax

        # Body, slightly narrower at the softened top, with a melted rim and a sunken crater.
        cylinder(f"candle_{i}", r, h, (x, y, 0.004), m, r_top=r * 0.96, segments=14, bevel=0.006)
        top = 0.004 + h
        torus(f"rim_{i}", r * 0.78, r * 0.2, (x, y, top - r * 0.08), m,
              rot=(rnd.uniform(-6, 6), rnd.uniform(-6, 6), 0), major=14, minor=6)
        # A slumped lip on one side where the wax ran over.
        lip_a = rnd.uniform(0, 2 * math.pi)
        blob(f"lip_{i}", r * 0.35, (x + r * 0.85 * math.cos(lip_a), y + r * 0.85 * math.sin(lip_a), top - r * 0.25), m,
             squash=(1, 1, 1.4), subdiv=1, seed=60 + i, jitter=0.1)

        # Drips running down the sides; the first one starts at the slumped lip.
        for k in range(3):
            a = lip_a if k == 0 else rnd.uniform(0, 2 * math.pi)
            length = rnd.uniform(0.3, 0.7) * h if k == 0 else rnd.uniform(0.15, 0.45) * h
            dr = rnd.uniform(0.006, 0.009)
            zc = top - r * 0.2 - length / 2
            blob(f"drip_{i}_{k}", dr, (x + (r + dr * 0.3) * math.cos(a), y + (r + dr * 0.3) * math.sin(a), zc), m,
                 squash=(1, 1, length / (2 * dr)), subdiv=1, seed=100 + i * 10 + k, jitter=0.12)

        # A thicker foot of run-off where the candle meets the puddle.
        foot_h = 0.012
        blob(f"foot_{i}", r * 1.35, (x, y, foot_h + 0.006), pool, squash=(1, 1, foot_h / (r * 1.35)),
             subdiv=1, seed=200 + i, jitter=0.1)

        # Small dark wick, a little bent.
        cylinder(f"wick_{i}", WICK_R, WICK_H, (x, y, top - 0.006), wick, segments=6,
                 rot=(rnd.uniform(-12, 12), rnd.uniform(-12, 12), 0), bevel=0)

        if CANDLES[i] == tallest:
            anchor("light:candles", (x, y, top + WICK_H + 0.02))
