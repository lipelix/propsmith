"""A village market stall: plank counter on the front, four posts and a striped awning sloping to the front, with
crates, baskets and produce on the counter (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder, torus

# The stall is about 2.8 x 1.3 m, the awning top about 2.3 m.
L, D = 2.8, 1.3
POST = 0.09  # post section
PX, PY = L / 2 - POST / 2, D / 2 - POST / 2  # post centres
COUNTER_H = 0.9  # top of the counter
COUNTER_D = 0.5  # counter depth, front edge at the front posts
AWN_BACK_Y, AWN_BACK_Z = D / 2 + 0.02, 2.28  # awning high edge
AWN_FRONT_Y, AWN_FRONT_Z = -(D / 2 + 0.08), 1.9  # awning low edge, overhanging the front
AWN_W = L + 0.1
STRIPES = 9
VALANCE = 0.2  # depth of the hanging front flap

WOOD = (0.2, 0.115, 0.058)
WOOD_OLD = (0.16, 0.11, 0.075)
CRATE = (0.24, 0.15, 0.08)
RED = (0.28, 0.075, 0.065)
CREAM = (0.46, 0.4, 0.28)
WICKER = (0.34, 0.22, 0.1)
APPLE = (0.38, 0.07, 0.04)
CABBAGE = (0.17, 0.26, 0.08)
TURNIP = (0.42, 0.33, 0.24)
ORANGE = (0.45, 0.2, 0.05)


def awning_z(y):
    t = (y - AWN_FRONT_Y) / (AWN_BACK_Y - AWN_FRONT_Y)
    return AWN_FRONT_Z + t * (AWN_BACK_Z - AWN_FRONT_Z)


@prop
def market_stall():
    rnd = random.Random(7)
    wood = material("market_stall_wood", WOOD, vary=0.25, scale=14)
    old = material("market_stall_planks", WOOD_OLD, vary=0.3, scale=11)
    crate_m = material("market_stall_crate", CRATE, vary=0.3, scale=12)
    red = material("market_stall_red", RED, vary=0.15, scale=20, rough=0.95, crevice=0.4)
    cream = material("market_stall_cream", CREAM, vary=0.12, scale=20, rough=0.95, crevice=0.4)
    wicker = material("market_stall_wicker", WICKER, vary=0.35, scale=60, rough=1.0)
    produce = {
        "apple": material("market_stall_apple", APPLE, vary=0.2, scale=25, rough=0.6),
        "cabbage": material("market_stall_cabbage", CABBAGE, vary=0.3, scale=30),
        "turnip": material("market_stall_turnip", TURNIP, vary=0.2, scale=25),
        "orange": material("market_stall_orange", ORANGE, vary=0.2, scale=25, rough=0.7),
    }

    # Four corner posts, cut to the awning's slope; the back ones are taller.
    for sx in (-1, 1):
        for sy in (-1, 1):
            h = awning_z(sy * PY) - 0.035
            box(f"post_{sx}_{sy}", (POST, POST, h), (sx * PX, sy * PY, h / 2), wood,
                rot=(rnd.uniform(-0.6, 0.6), rnd.uniform(-0.6, 0.6), 0), bevel=0.012)

    # Frame: rails along x on the post tops, sloping side rails.
    for sy in (-1, 1):
        z = awning_z(sy * PY) - 0.06
        box(f"rail_x_{sy}", (L, 0.06, 0.06), (0, sy * PY, z), wood, bevel=0.01)
    slope = math.degrees(math.atan2(AWN_BACK_Z - AWN_FRONT_Z, AWN_BACK_Y - AWN_FRONT_Y))
    rail_len = (2 * PY) / math.cos(math.radians(slope))
    for sx in (-1, 1):
        box(f"rail_y_{sx}", (0.06, rail_len, 0.06), (sx * PX, 0, awning_z(0) - 0.06), wood, rot=(slope, 0, 0), bevel=0.01)

    # Striped awning: cloth strips running front to back, alternating red and cream.
    awn_len = math.hypot(AWN_BACK_Y - AWN_FRONT_Y, AWN_BACK_Z - AWN_FRONT_Z)
    cy = (AWN_BACK_Y + AWN_FRONT_Y) / 2
    sw = AWN_W / STRIPES
    for i in range(STRIPES):
        x = -AWN_W / 2 + sw * (i + 0.5)
        m = red if i % 2 == 0 else cream
        sag = rnd.uniform(-0.006, 0.006)
        box(f"awning_{i}", (sw + 0.002, awn_len, 0.03), (x, cy, awning_z(cy) - 0.015 + sag), m,
            rot=(slope, 0, 0), bevel=0.008)
        # Hanging front flap with a scalloped look: each strip a slightly different drop.
        drop = VALANCE * rnd.uniform(0.9, 1.05)
        box(f"valance_{i}", (sw + 0.002, 0.025, drop), (x, AWN_FRONT_Y + 0.015, AWN_FRONT_Z - drop / 2 - 0.01), m,
            rot=(rnd.uniform(-2, 2), 0, 0), bevel=0.006)

    # Counter: front panel of horizontal planks, a plank top, side boards and a back leg rail.
    fy = -PY
    top_y = fy + COUNTER_D / 2 - POST / 2
    planks = 5
    ph = (COUNTER_H - 0.1) / planks
    for k in range(planks):
        box(f"front_{k}", (L - POST, 0.035, ph - 0.008), (rnd.uniform(-0.01, 0.01), fy - 0.01, 0.06 + ph * (k + 0.5)),
            old if k % 2 else wood, rot=(rnd.uniform(-0.8, 0.8), 0, 0), bevel=0.006)
    for k in range(3):
        d = (COUNTER_D + 0.04) / 3
        box(f"top_{k}", (L + 0.04, d - 0.008, 0.045),
            (0, fy - 0.05 + d * (k + 0.5), COUNTER_H - 0.0225), old if k == 1 else wood,
            rot=(0, rnd.uniform(-0.4, 0.4), 0), bevel=0.008)
    for sx in (-1, 1):
        box(f"side_{sx}", (0.035, COUNTER_D - POST, COUNTER_H - 0.15), (sx * PX, top_y + 0.02, (COUNTER_H - 0.1) / 2 + 0.05),
            old, bevel=0.006)
        box(f"leg_{sx}", (0.07, 0.07, COUNTER_H - 0.045), (sx * (PX - 0.1), fy + COUNTER_D - 0.08, (COUNTER_H - 0.045) / 2),
            wood, bevel=0.008)
    for leg_x in (-0.45, 0.45):
        box(f"leg_mid_{leg_x}", (0.07, 0.07, COUNTER_H - 0.045), (leg_x, fy + COUNTER_D - 0.08, (COUNTER_H - 0.045) / 2),
            wood, bevel=0.008)

    on = COUNTER_H  # goods stand on the counter top

    # Two small crates heaped with produce.
    def crate(name, x, y, w, d, h, kind, yaw, seed):
        box(f"{name}_body", (w, d, h), (x, y, on + h / 2), crate_m, rot=(0, 0, yaw), bevel=0.01)
        box(f"{name}_band", (w + 0.012, d + 0.012, 0.04), (x, y, on + h - 0.03), wood, rot=(0, 0, yaw), bevel=0.006)
        r = random.Random(seed)
        for j in range(4):
            px = x + r.uniform(-w / 3, w / 3)
            py = y + r.uniform(-d / 3, d / 3)
            blob(f"{name}_item_{j}", 0.068, (px, py, on + h + 0.01), produce[kind], subdiv=1, seed=seed * 10 + j, jitter=0.1)

    crate("crate_a", -1.0, top_y, 0.36, 0.3, 0.2, "apple", 6, 11)
    crate("crate_b", 0.62, top_y + 0.03, 0.32, 0.28, 0.18, "orange", -9, 12)

    # Two wicker baskets: a tapered body, a rim and produce on top.
    def basket(name, x, y, r, h, kind, seed):
        cylinder(f"{name}_body", r * 0.8, h, (x, y, on), wicker, r_top=r, segments=12, bevel=0.008)
        torus(f"{name}_rim", r, 0.016, (x, y, on + h), wicker, major=16, minor=6)
        rr = random.Random(seed)
        for j in range(3):
            a = 2 * math.pi * j / 3 + rr.uniform(0, 1)
            blob(f"{name}_item_{j}", 0.085 if kind == "cabbage" else 0.062,
                 (x + math.cos(a) * r * 0.4, y + math.sin(a) * r * 0.4, on + h + 0.01), produce[kind],
                 subdiv=1, seed=seed * 10 + j, jitter=0.12)

    basket("basket_a", -0.35, top_y - 0.02, 0.17, 0.14, "cabbage", 21)
    basket("basket_b", 1.12, top_y - 0.04, 0.13, 0.12, "turnip", 22)

    # Loose produce on the boards.
    for j, (x, kind) in enumerate([(-0.62, "apple"), (-0.56, "apple"), (0.2, "cabbage"), (0.05, "turnip"), (0.3, "orange")]):
        r = 0.085 if kind == "cabbage" else 0.058
        blob(f"loose_{j}", r, (x, top_y + rnd.uniform(-0.1, 0.08), on + r * 0.85), produce[kind],
             squash=(1, 1, 0.9), subdiv=1, seed=40 + j, jitter=0.1)

    # Behind the counter: a spare crate and a sack on the ground.
    box("spare_crate", (0.45, 0.38, 0.36), (0.8, PY - 0.3, 0.18), crate_m, rot=(0, 0, 12), bevel=0.012)
    box("spare_lid", (0.47, 0.4, 0.03), (0.8, PY - 0.3, 0.375), wood, rot=(0, 0, 12), bevel=0.006)
    blob("sack", 0.24, (-0.7, PY - 0.3, 0.22), material("market_stall_sack", (0.42, 0.33, 0.2), vary=0.18, scale=30, rough=1.0),
         squash=(1.0, 0.9, 0.85), subdiv=2, seed=5, jitter=0.08)
