"""A rustic split-rail fence section: two round split posts near the ends and two slightly sagging split rails running
the full tile along x, so sections join end to end (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import cylinder

TILE = 1.5  # metres per tile
# Overall dimensions: footprint 1x1 tile, the fence runs along x through the tile centre, height 0.75 tile = 1.125 m.
L = 1 * TILE - 0.01  # rail length, the full tile less a hair so neighbours meet without overlapping
POST_H = 1.1  # post top
POST_R = 0.075  # round post radius
POST_X = L / 2 - 0.16  # posts near the ends
RAIL_R = 0.055  # split rail half-width before flattening
RAIL_FLAT = 0.62  # rails are split: flatter in y than tall in z
RAIL_Z = (0.42, 0.86)  # rail heights at the posts
RAIL_Y = -0.055  # rails sit against the front (-y) of the posts
SAG = 0.025  # how far a rail droops at mid-span

WOOD = (0.25, 0.22, 0.175)  # weathered grey-brown
WOOD_OLD = (0.20, 0.18, 0.15)


def rail(name, z, mat, rnd):
    """A split rail from end to end in two halves that dip by SAG at the middle."""
    half = L / 2
    a = math.degrees(math.atan2(SAG, half))
    length = math.hypot(half, SAG) + 0.02
    twist = rnd.uniform(-8, 8)
    y = RAIL_Y + rnd.uniform(-0.008, 0.008)
    left = cylinder(f"{name}_l", RAIL_R, length, (-half, y, z), mat, segments=6, bevel=0.01)
    right = cylinder(f"{name}_r", RAIL_R, length, (half, y, z), mat, segments=6, bevel=0.01)
    for part, pitch, roll in ((left, 90 + a, twist), (right, -90 - a, -twist)):
        # ZYX order applies the roll about the rail's own axis first, then lays the rail along x.
        part.rotation_mode = "ZYX"
        part.rotation_euler = (0, math.radians(pitch), math.radians(roll))
        part.scale = (1, RAIL_FLAT, 1)


@prop
def fence_wood():
    rnd = random.Random(7)
    wood = material("fence_wood_wood", WOOD, vary=0.3, scale=14)
    wood_old = material("fence_wood_old", WOOD_OLD, vary=0.32, scale=14)

    # Two round posts, slightly tapered and leaning a little.
    for s in (-1, 1):
        cylinder(
            f"post_{s}",
            POST_R * rnd.uniform(0.95, 1.05),
            POST_H,
            (s * POST_X, 0, 0),
            wood_old if s > 0 else wood,
            r_top=POST_R * 0.8,
            segments=9,
            rot=(rnd.uniform(-1.5, 1.5), rnd.uniform(-1.5, 1.5), rnd.uniform(0, 360)),
            bevel=0.012,
        )

    # Two split rails, sagging a little between the posts.
    rail("rail_low", RAIL_Z[0], wood_old, rnd)
    rail("rail_high", RAIL_Z[1], wood, rnd)
