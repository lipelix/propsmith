"""Ivy creeping along the foot of a wall: a low strip of overlapping pointed ivy leaves on thin woody vines, flat and
tall against a wall on +y, spilling forward and down to the ground on -y, tapering off at both ends, with a few
runners climbing the wall plane (generated by npm run new). Variants: a 1.5 m strip and a 0.8 m strip."""
import math
import random

from mathutils import Matrix, Vector

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder

# Overall dimensions (metres), from the description.
LONG_L = 1.5  # length of the long strip (local x)
SHORT_L = 0.8  # length of the short strip
BACK_Y = 0.1  # the wall plane the foliage hugs (+y side)
DEPTH = 0.19  # how far the foliage spills forward from the wall plane at full height
FOLIAGE_H = 0.3  # tallest foliage against the wall
RUNNER_H = 0.385  # highest point a climbing runner reaches
END_TAPER = 0.32  # metres over which each end fades into the ground
SHAPE_P = 2.6  # superellipse exponent of the cross-section (2 = quarter ellipse, higher = fuller, flatter top)

LEAF_TIP = 0.05  # leaf centre to tip
LEAF_BASE = 0.026  # leaf centre to stalk end
LEAF_W = 0.031  # half-width of a leaf
LEAF_T = 0.004  # leaf card thickness
CUP = 0.004  # how far leaf edges curl up
VINE_R = 0.0055  # radius of a woody vine

LEAVES_PER_M = 125  # outer leaves per metre of strip
INNER_PER_M = 20  # shadow leaves inside the clump per metre
SKIRT_PER_M = 16  # leaves lying on the ground at the front per metre
CORE_SPACING = 0.3  # metres between the dark core blobs

SHADOW = (0.04, 0.06, 0.02)  # linear RGB, deep shadow green
OLIVE = (0.1, 0.13, 0.035)  # mid olive green
LIT = (0.21, 0.24, 0.065)  # lit yellow-green
CORE = (0.035, 0.05, 0.018)  # the dark heart of the clump
VINE = (0.13, 0.085, 0.045)  # woody vine bark


def _mats():
    return {
        "shadow": material("ivy_creeper_shadow", SHADOW, rough=0.85, vary=0.3, scale=30, crevice=0.6),
        "olive": material("ivy_creeper_olive", OLIVE, rough=0.75, vary=0.3, scale=30, crevice=0.5),
        "lit": material("ivy_creeper_lit", LIT, rough=0.7, vary=0.25, scale=30, crevice=0.35),
        "core": material("ivy_creeper_core", CORE, rough=0.95, vary=0.25, scale=20, crevice=0.6),
        "vine": material("ivy_creeper_vine", VINE, rough=0.9, vary=0.25, scale=40, crevice=0.4),
    }


def _profile(x, length, phase):
    """Foliage height and forward depth at x: uneven along the strip, fading out over END_TAPER at both ends."""
    d = length / 2 - abs(x)
    t = max(0.0, min(1.0, d / END_TAPER))
    env = t * t * (3 - 2 * t)
    wave = 0.78 + 0.13 * math.sin(x * 7.1 + phase[0]) + 0.09 * math.sin(x * 15.3 + phase[1])
    h = FOLIAGE_H * max(0.08, env * wave)
    ry = DEPTH * (0.45 + 0.55 * env) * (0.9 + 0.1 * math.sin(x * 9.7 + phase[2]))
    return h, ry, env


def _surface(x, th, h, ry, scale=1.0):
    """A point on the superellipse cross-section (th 0 = front on the ground, pi/2 = top at the wall), its normal
    and the tangent running forward and down."""
    e = 2 / SHAPE_P
    c, s = max(1e-4, math.cos(th)), max(1e-4, math.sin(th))
    y = BACK_Y - ry * scale * c ** e
    z = h * scale * s ** e
    k = e * (SHAPE_P - 1)
    n = Vector((0, -(c ** k) / ry, (s ** k) / h)).normalized()
    t = Vector((0, -n.z, n.y))
    return Vector((x, y, z)), n, t


def _jitter(rnd, v, amount):
    return (v + Vector((rnd.uniform(-1, 1), rnd.uniform(-1, 1), rnd.uniform(-1, 1))) * amount).normalized()


def _leaf(name, at, normal, tip, mat, rnd):
    """One pointed leaf card: a thin kite with its tip along `tip`, its face along `normal`, lifted off the ground."""
    size = rnd.uniform(0.75, 1.15)
    obj = box(name, (1, 1, LEAF_T), (0, 0, 0), mat, bevel=0)
    tip = (tip - normal * tip.dot(normal)).normalized()
    side = normal.cross(tip)
    m = Matrix((tip, side, normal)).transposed()
    corners = {(1, 1): (LEAF_TIP, 0), (-1, 1): (0, LEAF_W), (-1, -1): (-LEAF_BASE, 0), (1, -1): (0, -LEAF_W)}
    pts = []
    for v in obj.data.vertices:
        sx = 1 if v.co.x > 0 else -1
        sy = 1 if v.co.y > 0 else -1
        lx, ly = corners[(sx, sy)]
        lx, ly = lx * size, ly * size
        lz = v.co.z + CUP * (abs(ly) / LEAF_W) ** 2 - 0.004 * (lx > 0)
        pts.append(m @ Vector((lx, ly, lz)) + at)
    lift = max(0.0, 0.0015 - min(p.z for p in pts))
    for v, p in zip(obj.data.vertices, pts):
        v.co = p + Vector((0, 0, lift))
    return obj


def _stick(name, a, b, mat, r=VINE_R):
    """A thin four-sided vine segment from a to b."""
    d = b - a
    ln = d.length
    d.normalize()
    tilt = math.degrees(math.acos(max(-1.0, min(1.0, d.z))))
    yaw = math.degrees(math.atan2(d.x, -d.y))
    cylinder(name, r, ln, tuple(a), mat, r_top=r * 0.85, segments=4, rot=(tilt, 0, yaw), bevel=0)


def _colour(rnd, th, outer):
    """Dark underneath and inside, olive in between, lit on the top and outer rims."""
    if not outer:
        return "shadow" if rnd.random() < 0.75 else "olive"
    r = rnd.random()
    if th > 0.95:
        return "lit" if r < 0.6 else "olive"
    if th > 0.5:
        return "lit" if r < 0.3 else ("olive" if r < 0.85 else "shadow")
    return "olive" if r < 0.55 else ("shadow" if r < 0.85 else "lit")


def _ivy(length, seed, runners):
    rnd = random.Random(seed)
    mats = _mats()
    phase = [rnd.uniform(0, 6.3) for _ in range(3)]
    half = length / 2

    # Dark cores inside the clumps, so the gaps between the leaves read dark.
    n_core = max(3, round(length / CORE_SPACING))
    for i in range(n_core):
        x = -half + END_TAPER * 0.4 + (length - END_TAPER * 0.8) * (i + 0.5) / n_core + rnd.uniform(-0.03, 0.03)
        h, ry, _ = _profile(x, length, phase)
        rx = length / n_core * 0.75
        rz = h * 0.42
        rdy = ry * 0.42
        core = blob(f"ivy_creeper_core_{i}", 0.1, (x, BACK_Y - rdy * 0.95, rz * 1.12), mats["core"],
                    squash=(rx / 0.1, rdy / 0.1, rz / 0.1), subdiv=1, seed=seed + i, jitter=0.1)
        core.rotation_euler = (0, 0, math.radians(rnd.uniform(-6, 6)))  # keep the long axis along the wall

    # Outer and inner leaves over the cross-section, stratified along x.
    def layer(count, outer, prefix):
        for i in range(count):
            x = -half + length * (i + rnd.random()) / count
            x = max(-half + 0.03, min(half - 0.03, x))
            h, ry, env = _profile(x, length, phase)
            th = rnd.uniform(0.04, 1.57) if outer else rnd.uniform(0.2, 1.4)
            at, n, t = _surface(x, th, h, ry, 1.0 if outer else 0.72)
            # Near the ends the foliage slopes down along x too.
            n = (n + Vector((math.copysign(0.6 * (1 - env), x), 0, 0))).normalized()
            n = _jitter(rnd, n, 0.55)
            tip = _jitter(rnd, t + Vector((rnd.uniform(-1.1, 1.1), 0, 0)), 0.3)
            at = at + n * rnd.uniform(0.0, 0.012) + Vector((0, 0, 0))
            at.y = min(at.y, BACK_Y - 0.01)
            _leaf(f"ivy_creeper_{prefix}_{i}", at, n, tip, mats[_colour(rnd, th, outer)], rnd)

    layer(round(INNER_PER_M * length), False, "inner")
    layer(round(LEAVES_PER_M * length), True, "leaf")

    # A skirt of leaves lying on the ground in front, where the ivy spills down.
    for i in range(round(SKIRT_PER_M * length)):
        x = -half + 0.08 + (length - 0.16) * (i + rnd.random()) / round(SKIRT_PER_M * length)
        h, ry, env = _profile(x, length, phase)
        at = Vector((x, BACK_Y - ry - rnd.uniform(-0.01, 0.035), 0.004))
        n = _jitter(rnd, Vector((0, -0.35, 1)), 0.35)
        tip = Vector((rnd.uniform(-0.8, 0.8), -1, 0))
        _leaf(f"ivy_creeper_skirt_{i}", at, n, tip, mats["olive" if rnd.random() < 0.6 else "shadow"], rnd)

    # The main woody vine along the foot of the wall, half hidden, with its ends showing on the ground.
    n_seg = max(4, round(length / 0.13))
    pts = []
    for i in range(n_seg + 1):
        x = -half + 0.02 + (length - 0.04) * i / n_seg
        _, ry, env = _profile(x, length, phase)
        pts.append(Vector((x, BACK_Y - ry * 0.55 + rnd.uniform(-0.02, 0.02), VINE_R + 0.01 * env + rnd.uniform(0, 0.01))))
    for i in range(n_seg):
        _stick(f"ivy_creeper_vine_{i}", pts[i], pts[i + 1], mats["vine"])

    # Runners climbing the wall plane above the foliage, with a few leaves facing out.
    k = 0
    for j, fx in enumerate(runners):
        x0 = fx * half
        h, _, _ = _profile(x0, length, phase)
        top = RUNNER_H * rnd.uniform(0.9, 0.97) - LEAF_W
        z0 = h * 0.45
        steps = 5
        p = Vector((x0, BACK_Y - 0.008, z0))
        for s in range(steps):
            q = Vector((p.x + rnd.uniform(-0.05, 0.05), BACK_Y - 0.008, z0 + (top - z0) * (s + 1) / steps))
            _stick(f"ivy_creeper_runner_{j}_{s}", p, q, mats["vine"], r=VINE_R * 0.8)
            if q.z > h * 0.75:
                side = 1 if s % 2 else -1
                n = _jitter(rnd, Vector((0.35 * side, -1, 0.35)), 0.2)
                tip = Vector((0.6 * side, 0, -1))
                at = q + Vector((0.022 * side, -0.012, -0.012))
                mat = "lit" if s == steps - 1 or rnd.random() < 0.3 else "olive"
                _leaf(f"ivy_creeper_runleaf_{k}", at, n, tip, mats[mat], rnd)
                k += 1
            p = q


@prop
def ivy_creeper():
    _ivy(LONG_L, 11, (-0.55, 0.05, 0.42))


@prop
def ivy_creeper_short():
    _ivy(SHORT_L, 23, (-0.3, 0.35))
