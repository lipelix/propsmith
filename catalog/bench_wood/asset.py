"""A simple backless village plank bench: a thick plank seat on two splayed trestle legs joined by a pegged stretcher
(generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder

# Overall size: 1.4 m long along x, 0.35 m deep, seat top 0.45 m.
L = 1.4  # seat length
D = 0.35  # seat depth
H = 0.45  # seat top height
SEAT_T = 0.07  # thick seat plank
SEAT_Z = H - SEAT_T  # underside of the seat
TX = 0.5  # trestles at x = +-TX
LEG_W, LEG_T = 0.06, 0.065  # leg width (x) and thickness (y)
LEG_TOP_Y = 0.11  # leg centre line under the seat
LEG_FOOT_Y = 0.22  # leg centre line at the floor (splayed out)
CLEAT_H = 0.05  # cross bar under the seat
RAIL_Z, RAIL_H = 0.15, 0.05  # low cross rail of each trestle
STR_W, STR_H = 0.05, 0.06  # stretcher section
STR_OUT = 0.05  # stretcher tenon sticking out past each rail
PEG_R = 0.012

WOOD = (0.22, 0.14, 0.075)  # linear RGB
WOOD_OLD = (0.18, 0.12, 0.07)
SEAT = (0.24, 0.16, 0.09)
PEG = (0.11, 0.07, 0.04)


@prop
def bench_wood():
    rnd = random.Random(11)
    seat = material("bench_seat", SEAT, vary=0.25, scale=12)
    wood = material("bench_legs", WOOD, vary=0.25, scale=14)
    old = material("bench_legs_old", WOOD_OLD, vary=0.3, scale=11)
    peg = material("bench_pegs", PEG, vary=0.2, scale=10)

    # The seat: one thick plank, a touch uneven.
    box("seat", (L, D, SEAT_T), (0, rnd.uniform(-0.004, 0.004), SEAT_Z + SEAT_T / 2), seat,
        rot=(0, 0, rnd.uniform(-0.6, 0.6)), bevel=0.018)

    # Splay angle of the legs (in the y-z plane).
    dy = LEG_FOOT_Y - LEG_TOP_Y
    ang = math.atan2(dy, SEAT_Z)
    length = math.hypot(dy, SEAT_Z) + LEG_T * math.sin(ang)
    for i, x in enumerate((-TX, TX)):
        x += rnd.uniform(-0.006, 0.006)
        # Cleat under the seat, across y.
        box(f"cleat_{i}", (LEG_W + 0.01, 2 * LEG_TOP_Y + 0.12, CLEAT_H), (x, 0, SEAT_Z - CLEAT_H / 2), wood,
            bevel=0.01)
        for s in (-1, 1):
            # A leg tilted so its foot is out at +-LEG_FOOT_Y; centre placed so the lowest corner sits on z = 0.
            half = length / 2
            cz = half * math.cos(ang) + LEG_T / 2 * math.sin(ang)
            cy = s * (LEG_FOOT_Y - dy * (cz / SEAT_Z))
            mat = old if rnd.random() < 0.4 else wood
            box(f"leg_{i}_{s}", (LEG_W, LEG_T, length), (x, cy, cz), mat,
                rot=(s * math.degrees(ang) + rnd.uniform(-1, 1), 0, rnd.uniform(-1.5, 1.5)), bevel=0.01)
        # Low cross rail between the two legs.
        ry = LEG_FOOT_Y - dy * (RAIL_Z / SEAT_Z)
        box(f"rail_{i}", (LEG_W - 0.01, 2 * ry + LEG_T, RAIL_H), (x, 0, RAIL_Z), wood, bevel=0.008)
        # Dowels through the seat into the legs.
        for s in (-1, 1):
            cylinder(f"dowel_{i}_{s}", PEG_R * 1.4, 0.004, (x, s * LEG_TOP_Y, H - 0.001), peg, segments=8, bevel=0)

    # Stretcher along x through both rails, its tenons wedged outside them.
    sl = 2 * TX + LEG_W + 2 * STR_OUT
    box("stretcher", (sl, STR_W, STR_H), (0, 0, RAIL_Z + RAIL_H / 2 + STR_H / 2 - 0.01), old, bevel=0.01)
    for i, s in enumerate((-1, 1)):
        wx = s * (TX + LEG_W / 2 + STR_OUT * 0.5)
        box(f"wedge_{i}", (0.018, 0.03, STR_H + 0.04), (wx, 0, RAIL_Z + RAIL_H / 2 + STR_H / 2 - 0.01), peg,
            rot=(0, s * 6, 0), bevel=0.005)
