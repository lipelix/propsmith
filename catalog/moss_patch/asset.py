"""A flat clump of moss to lay on stones, wall caps and the foot of walls: a low lumpy cushion with a soft irregular
outline, built from a dark flat-bottomed core, squashed rounded bumps and many small tilted leaf cards, lit
yellow-green at the top and rims, with a few tiny tufts (generated by npm run new). Variants: a patch and a long thin
strip for a wall cap."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder

# Overall dimensions (metres), from the description.
PATCH_X, PATCH_Y, PATCH_H = 0.4, 0.3, 0.06
LONG_X, LONG_Y, LONG_H = 0.8, 0.2, 0.05
CORE_H = 0.012  # metres, height of the flat dark core on the ground
CARD_T = 0.004  # metres, thickness of a leaf card
CARD_L = (0.026, 0.044)  # metres, length range of a leaf card
CARD_W = (0.024, 0.038)  # metres, width range of a leaf card
TUFT_L = (0.018, 0.028)  # metres, length range of a tuft sprig

DEEP = (0.035, 0.05, 0.015)  # linear RGB, shadow green inside and underneath
OLIVE = (0.1, 0.13, 0.035)  # mid olive
LIT = (0.2, 0.24, 0.06)  # lit yellow-green on top and rims
LIT_PALE = (0.26, 0.28, 0.08)  # the brightest bump tips


def _mats():
    return {
        "deep": material("moss_deep", DEEP, rough=0.95, vary=0.3, scale=40, crevice=0.7),
        "olive": material("moss_olive", OLIVE, rough=0.9, vary=0.3, scale=40, crevice=0.6),
        "lit": material("moss_lit", LIT, rough=0.9, vary=0.3, scale=40, crevice=0.4),
        "pale": material("moss_lit_pale", LIT_PALE, rough=0.9, vary=0.25, scale=40, crevice=0.3),
    }


class _Shape:
    """A soft irregular outline (a superellipse with wobble) and a cushion height profile over it."""

    def __init__(self, rnd, lx, ly, h, power):
        self.a, self.b, self.h, self.p = lx / 2, ly / 2, h, power
        self.ph = [rnd.uniform(0, 2 * math.pi) for _ in range(3)]

    def edge(self, theta):
        """Outline radius (normalised, at most 1) in direction `theta`."""
        w = 0.08 * math.sin(3 * theta + self.ph[0]) + 0.05 * math.sin(5 * theta + self.ph[1])
        w += 0.04 * math.sin(7 * theta + self.ph[2])
        return 0.87 + w

    def d(self, x, y):
        """Normalised distance from the centre: 0 in the middle, 1 on the outline."""
        u, v = abs(x / self.a), abs(y / self.b)
        r = (u ** self.p + v ** self.p) ** (1 / self.p)
        return r / self.edge(math.atan2(y / self.b, x / self.a))

    def height(self, d):
        return self.h * max(0.0, 1 - d * d) ** 0.7

    def sample(self, rnd, dmin=0.0, dmax=1.0):
        while True:
            x, y = rnd.uniform(-self.a, self.a), rnd.uniform(-self.b, self.b)
            d = self.d(x, y)
            if dmin <= d <= dmax:
                return x, y, d


def _core(s, mats, n):
    """Flat dark discs on the ground along the long axis: the flat underside and the shadow inside."""
    for i in range(n):
        t = (i + 0.5) / n * 2 - 1
        x = t * s.a * 0.55
        rx = s.a * (0.9 / n + 0.28)
        ry = s.b * 0.72
        o = cylinder(f"moss_core_{i}", 1.0, CORE_H, (x, 0, 0), mats["deep"], segments=9, bevel=0)
        o.scale = (rx, ry, 1)
        o.rotation_euler.z = math.radians(15 * i)


def _bumps(rnd, s, mats, n, r_range):
    """Squashed rounded bumps: olive mostly, a few deep ones as hollows between them."""
    for i in range(n):
        x, y, d = s.sample(rnd, 0.0, 0.8)
        r = rnd.uniform(*r_range)
        top = s.height(d) * rnd.uniform(0.7, 0.85)
        sz = max(top / (2.2 * r), 0.2)
        mat = mats["deep"] if i % 3 == 2 else mats["olive"]
        blob(f"moss_bump_{i}", r, (x, y, r * sz * 1.08), mat, squash=(1, rnd.uniform(0.7, 0.95), sz), subdiv=1,
             seed=100 + i, jitter=0.1)


def _point(obj, tail=0.6):
    """Reshape a leaf card box (corners at +-x, +-y) into a pointed leaf: the tip on +x, a shorter blunt end on -x
    (`tail` of the half-length), widest in the middle. Same vertices and faces, so it stays a closed mesh."""
    for v in obj.data.vertices:
        x, y = v.co.x, v.co.y
        if x > 0 and y > 0:
            v.co.x, v.co.y = x, 0.0
        elif x < 0 < y:
            v.co.x = 0.0
        elif x < 0 and y < 0:
            v.co.x, v.co.y = x * tail, 0.0
        else:
            v.co.x = 0.0
    return obj


def _cards(rnd, s, mats, n):
    """Small leaf cards tilted outward along the cushion: lit at the top and rims, olive between."""
    for i in range(n):
        x, y, d = s.sample(rnd, 0.0, 1.0)
        ln, w = rnd.uniform(*CARD_L), rnd.uniform(*CARD_W)
        yaw = math.degrees(math.atan2(y / s.b, x / s.a)) + rnd.uniform(-35, 35)
        tilt = 4 + 22 * d ** 1.5 + rnd.uniform(-5, 6)
        roll = rnd.uniform(-14, 14)
        dip = ln / 2 * math.sin(math.radians(tilt)) + w / 2 * math.sin(math.radians(abs(roll))) + CARD_T
        z = max(min(s.height(d) - 0.004 + rnd.uniform(-0.004, 0.003), s.h * 0.95 - dip), dip + 0.001)
        if d > 0.72 or d < 0.35:
            mat = mats["pale"] if rnd.random() < 0.25 else mats["lit"]
        else:
            mat = mats["olive"] if rnd.random() < 0.55 else mats["lit"]
        _point(box(f"moss_card_{i}", (ln, w, CARD_T), (x, y, z), mat, rot=(roll, tilt, yaw), bevel=0))


def _tufts(rnd, s, mats, n, sprigs=3):
    """A few tiny upright tufts poking out of the cushion, staying under the full height."""
    for i in range(n):
        x, y, d = s.sample(rnd, 0.15, 0.5)
        z0 = s.height(d) - 0.008
        for j in range(sprigs):
            ln = min(rnd.uniform(*TUFT_L), s.h * 0.97 - z0)
            yaw = 120 * j + rnd.uniform(-30, 30)
            tilt = rnd.uniform(10, 30)
            cylinder(f"moss_tuft_{i}_{j}", 0.0035, ln, (x, y, z0), mats["pale"], r_top=0.0008, segments=4,
                     rot=(tilt, 0, yaw), bevel=0)


@prop
def moss_patch():
    rnd = random.Random(7)
    mats = _mats()
    s = _Shape(rnd, PATCH_X, PATCH_Y, PATCH_H, 2.0)
    _core(s, mats, 3)
    _bumps(rnd, s, mats, 15, (0.04, 0.065))
    _cards(rnd, s, mats, 66)
    _tufts(rnd, s, mats, 3)


@prop
def moss_patch_long():
    rnd = random.Random(19)
    mats = _mats()
    s = _Shape(rnd, LONG_X, LONG_Y, LONG_H, 3.0)
    _core(s, mats, 5)
    _bumps(rnd, s, mats, 14, (0.04, 0.06))
    _cards(rnd, s, mats, 76)
    _tufts(rnd, s, mats, 3)
