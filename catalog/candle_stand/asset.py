"""A tall wrought-iron candle stand: a three-legged splayed iron foot, a thin slightly twisted square iron stem, a
round drip pan at the top holding one thick ivory wax candle (generated by npm run new)."""
import math
import random

from propsmith import anchor, prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder, torus

TILE = 1.5  # metres per tile
# Footprint 1x1 tile = 1.5 x 1.5 m, height 1 tile = 1.5 m: the stand is about 1.3 m to the pan, the wick tip 1.48 m.
HUB_Z = 0.26  # where the three legs meet the stem
LEG_REACH = 0.36  # leg tip distance from the axis
LEG_TIP_Z = 0.035
LEG_T = 0.026  # leg bar section
STEM_T = 0.028  # square stem section
STEM_SEGMENTS = 18
STEM_TWIST = 9  # degrees per segment: half a turn over the stem
PAN_Z = 1.28  # bottom of the drip pan
PAN_R, PAN_H = 0.12, 0.025
CANDLE_R, CANDLE_H = 0.045, 0.17
WICK_H = 0.02

IRON = (0.045, 0.045, 0.045)
IRON_WORN = (0.085, 0.08, 0.075)
WAX = (0.5, 0.44, 0.32)
WICK = (0.06, 0.05, 0.04)


@prop
def candle_stand():
    rnd = random.Random(7)
    iron = material("candle_stand_iron", IRON, rough=0.55, vary=0.25, scale=22, metal=0.6)
    worn = material("candle_stand_iron_worn", IRON_WORN, rough=0.4, vary=0.3, scale=30, metal=0.7)
    wax = material("candle_stand_wax", WAX, rough=0.5, vary=0.08, scale=10, crevice=0.12)
    wick = material("candle_stand_wick", WICK, rough=0.9, vary=0.1, scale=20)

    # Three splayed legs, each with a small curled toe and a flat pad on the ground.
    spin = rnd.uniform(0, 120)
    for i in range(3):
        az = spin + i * 120 + rnd.uniform(-3, 3)
        a = math.radians(az)
        dx, dz = LEG_REACH - 0.02, LEG_TIP_Z - (HUB_Z - 0.02)
        length = math.hypot(dx, dz)
        pitch = math.degrees(math.atan2(dz, dx))
        mid_r = 0.02 + dx / 2
        box(f"leg_{i}", (length, LEG_T, LEG_T),
            (mid_r * math.cos(a), mid_r * math.sin(a), (HUB_Z - 0.02 + LEG_TIP_Z) / 2), iron,
            rot=(0, -pitch, az), bevel=0.005)
        tip = (LEG_REACH * math.cos(a), LEG_REACH * math.sin(a))
        cylinder(f"pad_{i}", 0.035, 0.018, (tip[0], tip[1], 0), worn, segments=10, bevel=0.004)
        cr = LEG_REACH + 0.03
        torus(f"toe_{i}", 0.032, 0.009, (cr * math.cos(a), cr * math.sin(a), 0.052), iron,
              rot=(90, 0, az + 90), major=12, minor=6)

    # Hub collar where the legs meet.
    cylinder("hub", 0.045, 0.05, (0, 0, HUB_Z - 0.04), worn, r_top=0.03, segments=12, bevel=0.006)
    cylinder("hub_cap", 0.03, 0.025, (0, 0, HUB_Z + 0.008), iron, r_top=0.02, segments=12, bevel=0.004)

    # The twisted square stem: short square segments, each turned a little further.
    stem_bottom, stem_top = HUB_Z + 0.03, PAN_Z - 0.05
    seg = (stem_top - stem_bottom) / STEM_SEGMENTS
    twist0 = rnd.uniform(0, 90)
    for i in range(STEM_SEGMENTS):
        z = stem_bottom + (i + 0.5) * seg
        box(f"stem_{i}", (STEM_T, STEM_T, seg + 0.004), (0, 0, z), iron,
            rot=(0, 0, twist0 + i * STEM_TWIST), bevel=0.004)

    # A knop halfway up and a collar below the pan.
    knop_z = (stem_bottom + stem_top) / 2
    blob("knop", 0.035, (0, 0, knop_z), worn, squash=(1, 1, 0.75), subdiv=1, seed=11, jitter=0.05)
    cylinder("cup", 0.022, 0.05, (0, 0, stem_top - 0.002), iron, r_top=0.05, segments=12, bevel=0.004)

    # Drip pan with a rolled rim.
    cylinder("pan", PAN_R, PAN_H, (0, 0, PAN_Z), iron, r_top=PAN_R + 0.008, segments=20, bevel=0.005)
    torus("pan_rim", PAN_R + 0.006, 0.008, (0, 0, PAN_Z + PAN_H), worn, major=24, minor=6)

    # Thick ivory candle with a few drips and a pool of wax on the pan.
    top = PAN_Z + PAN_H
    cylinder("candle", CANDLE_R, CANDLE_H, (0, 0, top - 0.005), wax, segments=16, bevel=0.006)
    candle_top = top - 0.005 + CANDLE_H
    for i in range(3):
        a = math.radians(rnd.uniform(0, 360))
        z = candle_top - rnd.uniform(0.03, 0.09)
        blob(f"drip_{i}", 0.012, (CANDLE_R * math.cos(a), CANDLE_R * math.sin(a), z), wax,
             squash=(0.8, 0.8, 1.8), subdiv=1, seed=20 + i, jitter=0.1)
    blob("wax_pool", 0.065, (0.01, -0.005, top + 0.002), wax, squash=(1, 1, 0.12), subdiv=1, seed=30, jitter=0.08)
    cylinder("wick", 0.004, WICK_H, (0, 0, candle_top - 0.004), wick, segments=6, bevel=0)

    flame = (0, 0, candle_top + WICK_H)
    anchor("light:candle", flame)
    anchor("fire:candle", (0, 0, candle_top), size=(0.012, 0.012, 0.05))
