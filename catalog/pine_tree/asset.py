"""A tall pine tree about 6 m high: a straight tapering brown trunk with rough bark, a few roots spreading at the foot,
and five stacked tiers of drooping dark-green needle boughs narrowing to a pointed top, each tier irregular and turned
(generated by npm run new). Each tier is a dark cone core ringed by squashed, bent bough clumps that sag at the tips."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, cylinder

# Overall dimensions (metres), from the description.
H = 6.0  # total height, tip of the crown
TRUNK_R = 0.17  # trunk radius at the ground
TRUNK_TOP_R = 0.04  # trunk radius where it vanishes in the top tier
TRUNK_H = 5.5  # trunk length (hidden in the top tiers)
ROOT_N = 5  # roots spreading at the foot
ROOT_L = 0.5  # root length
ROOT_R = 0.11  # root radius where it leaves the trunk

TIERS = 5
CROWN_BASE = 1.35  # height of the lowest tier's skirt
CROWN_R = 1.55  # radius of the lowest tier
CROWN_TOP_R = 0.42  # radius of the highest tier
TIER_STEP = 0.88  # vertical spacing of the tiers
TIER_H = 1.25  # height of one tier core cone
TOP_H = 1.0  # height of the pointed top above the last tier's base cone
DROOP = 0.32  # how far a bough tip sags, as a fraction of its length

BARK = (0.13, 0.075, 0.042)  # linear RGB, brown bark
ROOT = (0.11, 0.065, 0.038)
NEEDLE_DARK = (0.03, 0.058, 0.032)  # core shadow green
NEEDLE = (0.04, 0.075, 0.035)  # dark needle green
NEEDLE_LIT = (0.07, 0.11, 0.045)  # sunlit bough tops


def _mats():
    return {
        "bark": material("pine_tree_bark", BARK, rough=0.95, vary=0.4, scale=22, crevice=0.75),
        "root": material("pine_tree_root", ROOT, rough=0.95, vary=0.35, scale=18, crevice=0.75),
        "core": material("pine_tree_core", NEEDLE_DARK, rough=0.9, vary=0.3, scale=10, crevice=0.7),
        "needle": material("pine_tree_needles", NEEDLE, rough=0.85, vary=0.35, scale=16, crevice=0.6),
        "lit": material("pine_tree_needles_lit", NEEDLE_LIT, rough=0.8, vary=0.3, scale=16, crevice=0.5),
    }


def _roughen(obj, rnd, amount):
    """Seeded radial jitter of the vertices: rough bark, uneven roots."""
    for v in obj.data.vertices:
        r = math.hypot(v.co.x, v.co.y)
        if r > 1e-4:
            k = 1 + rnd.uniform(-amount, amount)
            v.co.x *= k
            v.co.y *= k


def _trunk(mats, rnd):
    t = cylinder("pine_tree_trunk", TRUNK_R, TRUNK_H, (0, 0, 0), mats["bark"], r_top=TRUNK_TOP_R, segments=12,
                 bevel=0)
    _roughen(t, rnd, 0.08)
    # Roots: tapered cylinders leaving the trunk low and sloping down to the ground, their tips just touching it.
    for i in range(ROOT_N):
        yaw = 360 * i / ROOT_N + rnd.uniform(-20, 20)
        tilt = rnd.uniform(98, 106)  # past horizontal: pointing out and down
        length = ROOT_L * rnd.uniform(0.75, 1.1)
        r, r_top = ROOT_R * rnd.uniform(0.85, 1.1), 0.04
        dz = math.cos(math.radians(tilt))
        flat = math.sqrt(1 - dz * dz)
        # Tip's lowest point at the ground; the trunk end (and the 10 % jitter) never below it.
        z0 = max(0.003 + 1.1 * r_top * flat - length * dz, 0.003 + 1.1 * r * flat)
        root = cylinder(f"pine_tree_root_{i}", r, length, (0, 0, z0), mats["root"], r_top=r_top, segments=8,
                        rot=(tilt, 0, yaw), bevel=0)
        _roughen(root, rnd, 0.1)


def _bough(name, length, width, thick, at, pitch, yaw, mat, seed):
    """A squashed blob, long along x, bent so its outer half sags: one drooping needle bough."""
    b = blob(name, 1.0, (0, 0, 0), mat, squash=(length / 2, width / 2, thick / 2), subdiv=1, seed=seed, jitter=0.18)
    half = length / 2
    for v in b.data.vertices:
        u = (v.co.x + half) / length  # 0 at the trunk end, 1 at the tip
        v.co.z -= DROOP * length * u * u
    b.location = at
    b.rotation_euler = (0, math.radians(pitch), math.radians(yaw))
    return b


def _tier(i, mats, rnd):
    f = i / (TIERS - 1)
    radius = CROWN_R + (CROWN_TOP_R - CROWN_R) * f
    base = CROWN_BASE + TIER_STEP * i
    top = i == TIERS - 1
    height = TIER_H * (1 - 0.25 * f) + (TOP_H if top else 0)
    if top:
        height = H - base
    # Dark core cone: fills the gaps between boughs, so the tier reads dense and dark inside.
    core = cylinder(f"pine_tree_core_{i}", radius * 0.62, height * 0.9, (0, 0, base + 0.05), mats["core"],
                    r_top=0.0 if top else radius * 0.08, segments=10, bevel=0)
    core.rotation_euler = (0, 0, math.radians(rnd.uniform(0, 36)))
    _roughen(core, rnd, 0.1)
    if top:
        # The pointed leader: a slim cone above the last rings of boughs.
        cylinder("pine_tree_leader", radius * 0.32, height * 0.45, (0, 0, H - height * 0.45), mats["needle"],
                 r_top=0.0, segments=8, bevel=0)
    # Boughs: rings of drooping clumps up the tier, each ring turned and offset, tips on the tier's cone.
    n = 10 - i // 2
    turn = rnd.uniform(0, 360)
    rings = ((0.06, n), (0.34, n - 3), (0.58, max(4, n - 5))) if not top else ((0.06, n - 1), (0.3, n - 4))
    for j, (t, count) in enumerate(rings):
        reach = radius * (1 - 0.95 * t)  # where the tips of this ring end
        for k in range(count):
            yaw = turn + 360 * (k + 0.5 * j) / count + rnd.uniform(-14, 14)
            length = reach * rnd.uniform(0.82, 1.0)
            pitch = rnd.uniform(4, 14) + (8 if j == 0 else 6 * j)
            mid = max(length * 0.45, reach - length * 0.5 * math.cos(math.radians(pitch)))
            z = base + height * t + rnd.uniform(-0.06, 0.06)
            a = math.radians(yaw)
            key = "lit" if rnd.random() < 0.3 + 0.15 * j else "needle"
            _bough(f"pine_tree_bough_{i}_{j}_{k}", length, reach * rnd.uniform(0.5, 0.62),
                   0.34 * (1 - 0.35 * f) * (1 - 0.2 * j), (mid * math.cos(a), mid * math.sin(a), z), pitch, yaw,
                   mats[key], 100 * i + 20 * j + k)


@prop
def pine_tree():
    rnd = random.Random(7)
    mats = _mats()
    _trunk(mats, rnd)
    for i in range(TIERS):
        _tier(i, mats, rnd)
