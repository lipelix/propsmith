"""A rounded weathered grey boulder with thick moss cushions on its upward-facing top surfaces, a little moss creeping
down the shoulders and bare stone on the sides and base (generated by npm run new). Variants: a boulder with a smaller
stone leaning against it, a small single stone, a large heap of two or three stacked and merged boulders.

The moss is clumped: each cushion is a dark squashed core with small leaf cards (thin bevel-free boxes) tilted round
it, deep green inside, olive in the middle, lit yellow-green on top and at the rims. Cushions are placed by casting
rays down onto the finished stones, so they only sit where the surface faces up."""
import math
import random

import bpy
from mathutils import Quaternion, Vector
from mathutils.bvhtree import BVHTree

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box

# Overall dimensions (metres), from the description.
MAIN_R, MAIN_H = 0.3, 0.46  # rock_mossy: half-width and stone height of the main boulder
LEAN_R, LEAN_H = 0.15, 0.27  # rock_mossy: the smaller stone leaning against it
SMALL_R, SMALL_H = 0.16, 0.22  # rock_mossy_small
LARGE_R, LARGE_H = 0.44, 0.52  # rock_mossy_large: the bottom boulder
SIDE_R, SIDE_H = 0.27, 0.36  # rock_mossy_large: the boulder merged beside it
TOP_R, TOP_H = 0.27, 0.34  # rock_mossy_large: the boulder stacked on top
TOP_LIFT = 0.36  # metres, lowest point of the stacked boulder (sunk into the ones below)
FLAT = 0.1  # share of a boulder's height cut flat where it rests on the ground
CARD_T = 0.004  # metres, thickness of a leaf card

STONE = (0.24, 0.24, 0.225)  # linear RGB, cool grey
STONE_DARK = (0.17, 0.17, 0.16)
MOSS_DEEP = (0.035, 0.055, 0.016)  # shadow green: cores and undersides
MOSS_OLIVE = (0.1, 0.13, 0.035)  # mid olive
MOSS_LIT = (0.21, 0.25, 0.07)  # lit yellow-green: tops and rims


def _mats():
    return {
        "stone": material("rock_mossy_stone", STONE, rough=0.9, vary=0.28, scale=9, crevice=0.75),
        "dark": material("rock_mossy_stone_dark", STONE_DARK, rough=0.9, vary=0.28, scale=9, crevice=0.75),
        "deep": material("rock_mossy_moss_deep", MOSS_DEEP, rough=0.95, vary=0.3, scale=40, crevice=0.6),
        "olive": material("rock_mossy_moss_olive", MOSS_OLIVE, rough=0.95, vary=0.3, scale=40, crevice=0.5),
        "lit": material("rock_mossy_moss_lit", MOSS_LIT, rough=0.9, vary=0.25, scale=40, crevice=0.35),
    }


def _rock(name, r, h, xy, mat, seed, stretch=1.0, yaw=0.0, tilt=(0.0, 0.0), z_min=0.0, subdiv=3):
    """A rounded boulder `r` half-wide and `h` high (before tilting): a lumpy blob with its base cut flat, turned by
    `yaw`, leant by `tilt` (x, y degrees) and moved so its lowest point is at `z_min`."""
    rz = h / (2 * (1 - FLAT / 2))
    obj = blob(name, r, (xy[0], xy[1], 0), mat, squash=(stretch, 1 / stretch, rz / r), subdiv=subdiv, seed=seed,
               jitter=0.11)
    verts = obj.data.vertices
    low = min(v.co.z for v in verts)
    cut = low + FLAT * (max(v.co.z for v in verts) - low)
    for v in verts:
        v.co.z = max(v.co.z, cut)
    obj.rotation_euler = (math.radians(tilt[0]), math.radians(tilt[1]), math.radians(yaw))
    bpy.context.view_layer.update()
    lowest = min((obj.matrix_world @ v.co).z for v in verts)
    obj.location.z += z_min - lowest
    bpy.context.view_layer.update()
    return obj


def _surface(rocks):
    """A BVH tree of the stones in world space, for dropping moss onto them."""
    verts, polys = [], []
    for obj in rocks:
        base = len(verts)
        verts += [obj.matrix_world @ v.co for v in obj.data.vertices]
        polys += [[base + i for i in p.vertices] for p in obj.data.polygons]
    return BVHTree.FromPolygons(verts, polys)


def _drop(tree, x, y):
    """The topmost stone point and its normal under (x, y), or None off the stones."""
    loc, normal, _, _ = tree.ray_cast(Vector((x, y, 5.0)), Vector((0, 0, -1)))
    if loc is None:
        return None
    if normal.z < 0:
        normal = -normal
    return loc, normal


def _point(obj, tail=0.6):
    """Reshape a leaf card box (corners at +-x, +-y) into a pointed leaf: the tip on +x, a shorter blunt end on -x
    (`tail` of the half-length), widest in the middle. Same vertices and faces, so it stays a closed mesh."""
    for v in obj.data.vertices:
        x, y = v.co.x, v.co.y
        if x > 0 and y > 0:
            v.co.x, v.co.y = x, 0.0
        elif x < 0 < y:
            v.co.x = 0.0
        elif x < 0 and y < 0:
            v.co.x, v.co.y = x * tail, 0.0
        else:
            v.co.x = 0.0
    return obj


def _card(name, size, at, facing, spin, mat):
    """One leaf card: a thin bevel-free box whose broad face looks along `facing`, turned `spin` degrees about it."""
    obj = _point(box(name, (size[0], size[1], CARD_T), at, mat, bevel=0))
    q = facing.normalized().to_track_quat("Z", "Y") @ Quaternion((0, 0, 1), math.radians(spin))
    obj.rotation_euler = q.to_euler("XYZ")
    return obj


def _cushion(name, tree, hit, normal, rc, leaf, mats, rnd, cards):
    """A moss cushion of radius `rc` on the stone at `hit`: a deep green core and `cards` leaf cards round it, the
    upper inner ones lit, the low outer ones olive or deep."""
    hc = rc * 0.45
    blob(f"{name}_core", rc * 0.95, hit + normal * (hc * 0.15), mats["deep"], squash=(1, 0.9, 0.42), subdiv=1,
         seed=rnd.randrange(1000), jitter=0.22)
    yaw0 = rnd.uniform(0, 360)
    for i in range(cards):
        a = math.radians(yaw0 + 137.5 * i + rnd.uniform(-15, 15))  # golden-angle spiral
        rho = rc * math.sqrt((i + 0.5) / cards) * rnd.uniform(0.75, 1.05)
        x, y = hit.x + rho * math.cos(a), hit.y + rho * math.sin(a)
        got = _drop(tree, x, y)
        if got is None:
            continue
        loc, n = got
        edge = rho / rc  # 0 at the centre, 1 at the rim
        lift = hc * (1 - 0.75 * edge * edge) * rnd.uniform(0.7, 1.1)
        out = Vector((math.cos(a), math.sin(a), 0))
        tilt = 0.12 + 0.4 * edge + rnd.uniform(-0.1, 0.1)  # rim cards stand up more and face outward
        facing = n + out * tilt + Vector((rnd.uniform(-0.25, 0.25), rnd.uniform(-0.25, 0.25), 0))
        if edge < 0.55:
            mat = mats["lit"] if rnd.random() < 0.75 else mats["olive"]
        elif edge < 0.85:
            mat = rnd.choice([mats["lit"], mats["olive"], mats["olive"]])
        else:
            mat = rnd.choice([mats["lit"], mats["olive"], mats["deep"]])
        size = (leaf * rnd.uniform(0.8, 1.2), leaf * rnd.uniform(0.7, 0.95))
        _card(f"{name}_card_{i}", size, loc + n * lift, facing, rnd.uniform(0, 360), mat)


def _moss(prefix, rocks, rc, leaf, mats, seed, cards=12, creep=0.35):
    """Cushions on every upward-facing patch of the stones (normal z above 0.8), smaller ones creeping down the
    shoulders (0.55 to 0.8, with probability `creep`), none on the sides or the base."""
    rnd = random.Random(seed)
    tree = _surface(rocks)
    xs = [(r.matrix_world @ v.co) for r in rocks for v in r.data.vertices]
    x0, x1 = min(v.x for v in xs), max(v.x for v in xs)
    y0, y1 = min(v.y for v in xs), max(v.y for v in xs)
    step = rc * 1.15
    placed = []
    n = 0
    y = y0 + step / 2
    while y < y1:
        x = x0 + step / 2
        while x < x1:
            px, py = x + rnd.uniform(-0.3, 0.3) * step, y + rnd.uniform(-0.3, 0.3) * step
            x += step
            got = _drop(tree, px, py)
            if got is None:
                continue
            loc, nrm = got
            if nrm.z > 0.8:
                r = rc * rnd.uniform(0.8, 1.1)
                k = cards
            elif nrm.z > 0.55 and rnd.random() < creep:
                r = rc * rnd.uniform(0.5, 0.65)
                k = max(5, cards // 2)
            else:
                continue
            if any((loc - p).length < (r + pr) * 0.55 for p, pr in placed):
                continue
            placed.append((loc, r))
            _cushion(f"{prefix}_moss_{n}", tree, loc, nrm, r, leaf * r / rc, mats, rnd, k)
            n += 1
        y += step


@prop
def rock_mossy():
    mats = _mats()
    main = _rock("rock_mossy_main", MAIN_R, MAIN_H, (-0.06, 0.02), mats["stone"], 3, stretch=1.08, yaw=12)
    lean = _rock("rock_mossy_lean", LEAN_R, LEAN_H, (0.24, -0.15), mats["dark"], 8, stretch=1.1, yaw=-30,
                 tilt=(8, -22), subdiv=2)
    _moss("rock_mossy", [main, lean], 0.085, 0.052, mats, 5)


@prop
def rock_mossy_small():
    mats = _mats()
    stone = _rock("rock_mossy_stone", SMALL_R, SMALL_H, (0, 0), mats["stone"], 14, stretch=1.1, yaw=-20)
    _moss("rock_mossy", [stone], 0.055, 0.036, mats, 9, cards=12)


@prop
def rock_mossy_large():
    mats = _mats()
    base = _rock("rock_mossy_base", LARGE_R, LARGE_H, (-0.12, 0.03), mats["stone"], 21, stretch=1.1, yaw=8)
    side = _rock("rock_mossy_side", SIDE_R, SIDE_H, (0.3, -0.14), mats["dark"], 27, stretch=1.05, yaw=-35,
                 tilt=(0, -10), subdiv=2)
    top = _rock("rock_mossy_top", TOP_R, TOP_H, (-0.08, 0.06), mats["stone"], 33, stretch=1.15, yaw=40,
                tilt=(6, 8), z_min=TOP_LIFT, subdiv=2)
    _moss("rock_mossy", [base, side, top], 0.12, 0.072, mats, 13, cards=10)
