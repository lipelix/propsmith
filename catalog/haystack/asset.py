"""A rounded farm haystack: a lumpy dome of golden-brown straw with loose wisps at the base and a few darker
weathered patches on top (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, cylinder

# The stack is about 1.4 m across and 1.7 m high.
R = 0.62  # base radius of the stack, metres
H = 1.7  # overall height, metres
BODY_H = 0.85  # height of the slightly tapering lower body
DOME_R = 0.63  # radius of the dome blob before squash
DOME_SQUASH = 1.2  # vertical stretch of the dome
DOME_JITTER = 0.06

STRAW = (0.42, 0.29, 0.1)  # linear RGB, golden-brown
STRAW_LIGHT = (0.48, 0.35, 0.13)
STRAW_OLD = (0.2, 0.15, 0.075)  # weathered grey-brown


@prop
def haystack():
    rnd = random.Random(7)
    straw = material("haystack_straw", STRAW, rough=0.95, vary=0.3, scale=18, crevice=0.7)
    light = material("haystack_straw_light", STRAW_LIGHT, rough=0.95, vary=0.3, scale=22, crevice=0.6)
    old = material("haystack_straw_old", STRAW_OLD, rough=0.95, vary=0.25, scale=12, crevice=0.6)

    # Lower body: a short tapering drum the dome sits on.
    cylinder("haystack_body", R, BODY_H, (0, 0, 0), straw, r_top=R * 0.95, segments=16, bevel=0)

    # Dome: one lumpy squashed sphere, its top at H.
    half = DOME_R * DOME_SQUASH * (1 + DOME_JITTER)
    blob("haystack_dome", DOME_R, (0, 0, H - half), straw, squash=(1, 1, DOME_SQUASH), subdiv=2, seed=11,
         jitter=DOME_JITTER)

    # Bulges around the flank so the outline is lumpy, not a clean drum.
    for i in range(6):
        a = math.radians(i * 60 + rnd.uniform(-15, 15))
        r = 0.24 * rnd.uniform(0.9, 1.1)
        z = rnd.uniform(0.4, 0.9)
        mat = light if i % 2 else straw
        blob(f"haystack_bulge_{i}", r, (0.44 * math.cos(a), 0.44 * math.sin(a), z), mat, squash=(1, 1, 1.3),
             subdiv=2, seed=20 + i, jitter=0.08)

    # Darker weathered patches on the crown, sunk just under the dome's surface so only their caps show.
    centre = H - half
    for i, (az, el) in enumerate([(-60, 70), (150, 45), (40, 40)]):
        a, e = math.radians(az), math.radians(el)
        k = 0.6
        at = (k * DOME_R * math.cos(e) * math.cos(a), k * DOME_R * math.cos(e) * math.sin(a),
              centre + k * DOME_R * DOME_SQUASH * math.sin(e))
        blob(f"haystack_old_{i}", 0.26, at, old, squash=(1.4, 1, 0.85), subdiv=2, seed=40 + i, jitter=0.05)

    # Loose wisps fanned out on the ground round the base.
    for i in range(8):
        a = math.radians(i * 45 + 22.5 + rnd.uniform(-8, 8))  # off the axes, where the square footprint has room
        r = 0.15 * rnd.uniform(0.9, 1.05)
        sz = 0.22
        d = 0.6 + rnd.uniform(-0.03, 0.0)
        z = r * sz * 1.12 + 0.004
        blob(f"haystack_wisp_{i}", r, (d * math.cos(a), d * math.sin(a), z), light if i % 3 else straw,
             squash=(1.2, 1.0, sz), subdiv=1, seed=60 + i, jitter=0.1)
