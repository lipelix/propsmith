"""A village shop's wooden sales counter: a closed boxy body with vertical front planks over a darker plinth, a thick
overhanging oak top, a small iron balance scale and a stack of coins on it (generated by npm run new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder

TILE = 1.5  # metres per tile
# Footprint 2x1 tiles (3.0 x 1.5 m), height 0.7 tile = 1.05 m. The counter is about 2.6 m long, 0.7 m deep and its top
# surface sits at 0.92 m so the little scale on it stays under the height.
L = 2.6  # body length (x)
D = 0.7  # body depth (y)
H = 0.92  # top surface height
TOP_T = 0.075  # thick oak top
TOP_OVER_X = 0.06  # top overhang at each end
TOP_OVER_FRONT = 0.08  # overhang on the customer side (-y)
TOP_OVER_BACK = 0.02
PLINTH_H, PLINTH_T = 0.13, 0.035  # darker kick board at the bottom
PLANK_T = 0.025  # front and side planks, proud of the core
FRONT_PLANKS = 13
SIDE_PLANKS = 4
POST = 0.075  # square corner posts
RAIL_H = 0.07  # frieze rail under the top
# The balance scale and the coins.
SCALE_AT = (0.55, 0.05)
SCALE_H = 0.1  # post height above the base
BEAM_L = 0.34
PAN_R, PAN_Z = 0.07, 0.035
COINS_AT = (0.2, -0.12)
COIN_R, COIN_T = 0.024, 0.006

OAK_TOP = (0.24, 0.15, 0.078)  # linear RGB
OAK = (0.23, 0.14, 0.072)
OAK_OLD = (0.18, 0.108, 0.056)
PLINTH = (0.085, 0.055, 0.032)
IRON = (0.05, 0.05, 0.052)
BRASS = (0.36, 0.25, 0.09)
COIN = (0.42, 0.3, 0.1)
COIN_OLD = (0.3, 0.2, 0.08)


@prop
def counter_wood():
    rnd = random.Random(11)
    top = material("counter_top", OAK_TOP, vary=0.28, scale=10)
    oak = material("counter_planks", OAK, vary=0.25, scale=14)
    old = material("counter_planks_old", OAK_OLD, vary=0.3, scale=11)
    dark = material("counter_plinth", PLINTH, vary=0.25, scale=12)
    iron = material("counter_iron", IRON, rough=0.55, vary=0.15, scale=25, metal=0.5)
    brass = material("counter_pans", BRASS, rough=0.45, vary=0.15, scale=25, metal=0.6)
    coin = material("counter_coins", COIN, rough=0.4, vary=0.12, scale=40, metal=0.6)
    coin_old = material("counter_coins_old", COIN_OLD, rough=0.45, vary=0.12, scale=40, metal=0.5)

    body_h = H - TOP_T
    x0, y0 = L / 2, D / 2

    # The closed core behind the planks.
    box("core", (L - 2 * PLANK_T, D - 2 * PLANK_T, body_h), (0, 0, body_h / 2), old, bevel=0.006)

    # Darker plinth board around the front and both ends.
    box("plinth_front", (L, PLINTH_T, PLINTH_H), (0, -y0 + PLINTH_T / 2 - 0.012, PLINTH_H / 2), dark, bevel=0.01)
    for i, s in enumerate((-1, 1)):
        box(f"plinth_end_{i}", (PLINTH_T, D, PLINTH_H), (s * (x0 - PLINTH_T / 2 + 0.012), 0, PLINTH_H / 2), dark,
            bevel=0.01)

    # Corner posts at the front corners.
    for i, s in enumerate((-1, 1)):
        box(f"post_{i}", (POST, POST, body_h), (s * (x0 - POST / 2 + 0.01), -y0 + POST / 2 - 0.01, body_h / 2), oak,
            bevel=0.012)

    plank_z0 = PLINTH_H
    plank_h = body_h - PLINTH_H - RAIL_H

    # Vertical front planks between the posts.
    span = L - 2 * POST + 0.02
    pw = span / FRONT_PLANKS
    for i in range(FRONT_PLANKS):
        x = -span / 2 + pw / 2 + i * pw
        mat = old if rnd.random() < 0.3 else oak
        h = plank_h - rnd.uniform(0, 0.012)
        box(f"front_{i}", (pw - 0.012, PLANK_T, h), (x, -y0 + PLANK_T / 2 - 0.004, plank_z0 + h / 2), mat,
            rot=(0, rnd.uniform(-0.6, 0.6), 0), bevel=0.008)

    # Vertical planks on both ends.
    sspan = D - POST
    sw = sspan / SIDE_PLANKS
    for side, s in enumerate((-1, 1)):
        for i in range(SIDE_PLANKS):
            y = -y0 + POST + sw / 2 + i * sw - 0.01
            mat = old if rnd.random() < 0.3 else oak
            h = plank_h - rnd.uniform(0, 0.012)
            box(f"side_{side}_{i}", (PLANK_T, sw - 0.006, h), (s * (x0 - PLANK_T / 2), y, plank_z0 + h / 2), mat,
                rot=(rnd.uniform(-0.6, 0.6), 0, 0), bevel=0.008)

    # Frieze rail under the top, front and ends.
    rail_z = body_h - RAIL_H / 2
    box("rail_front", (L - 0.01, PLANK_T + 0.01, RAIL_H), (0, -y0 + PLANK_T / 2 - 0.008, rail_z), oak, bevel=0.01)
    for i, s in enumerate((-1, 1)):
        box(f"rail_end_{i}", (PLANK_T + 0.01, D - 0.01, RAIL_H), (s * (x0 - PLANK_T / 2 + 0.002), 0, rail_z), oak,
            bevel=0.01)

    # The thick overhanging oak top, two boards along x.
    top_l = L + 2 * TOP_OVER_X
    top_d = D + TOP_OVER_FRONT + TOP_OVER_BACK
    top_y = (TOP_OVER_BACK - TOP_OVER_FRONT) / 2
    half = top_d / 2
    for i, (dy, mat) in enumerate(((-half / 2, top), (half / 2, top))):
        box(f"top_{i}", (top_l - rnd.uniform(0, 0.015), half - 0.004, TOP_T - rnd.uniform(0, 0.004)),
            (rnd.uniform(-0.005, 0.005), top_y + dy, H - TOP_T / 2), mat,
            rot=(0, 0, rnd.uniform(-0.15, 0.15)), bevel=0.016)

    # A small iron balance scale: base, post, beam, two hanging pans.
    sx, sy = SCALE_AT
    box("scale_base", (0.16, 0.09, 0.018), (sx, sy, H + 0.009), iron, bevel=0.005)
    cylinder("scale_post", 0.01, SCALE_H, (sx, sy, H + 0.018), iron, segments=8, bevel=0.002)
    beam_z = H + 0.018 + SCALE_H - 0.012
    box("scale_beam", (BEAM_L, 0.016, 0.016), (sx, sy, beam_z), iron, bevel=0.003)
    cylinder("scale_knob", 0.014, 0.014, (sx, sy, beam_z + 0.004), iron, segments=8, bevel=0.003)
    for i, s in enumerate((-1, 1)):
        px = sx + s * (BEAM_L / 2 - 0.01)
        pan_z = H + PAN_Z
        for j, (ox, oy) in enumerate(((-0.03, -0.03), (0.03, -0.03), (0.0, 0.035))):
            # three short rods from the beam end down to the pan rim, leaning in
            box(f"scale_rod_{i}_{j}", (0.004, 0.004, beam_z - pan_z - 0.004),
                (px + ox / 2, sy + oy / 2, (beam_z + pan_z) / 2), iron,
                rot=(oy * 7, -ox * 7, 0), bevel=0)
        cylinder(f"scale_pan_{i}", PAN_R * 0.6, 0.016, (px, sy, pan_z - 0.006), brass, r_top=PAN_R, segments=12,
                 bevel=0.003)
    # The pans hang from feet on a little bar so nothing floats.
    for i, s in enumerate((-1, 1)):
        px = sx + s * (BEAM_L / 2 - 0.01)
        cylinder(f"scale_foot_{i}", 0.012, PAN_Z - 0.006, (px, sy, H), iron, segments=8, bevel=0.002)

    # A little stack of coins and a couple loose beside it.
    cx, cy = COINS_AT
    for i in range(7):
        mat = coin_old if i % 3 == 1 else coin
        cylinder(f"coin_{i}", COIN_R, COIN_T, (cx + rnd.uniform(-0.003, 0.003), cy + rnd.uniform(-0.003, 0.003),
                                                 H + i * COIN_T), mat, segments=10, bevel=0.001)
    for i, (dx, dy) in enumerate(((0.045, 0.015), (0.03, -0.035))):
        cylinder(f"coin_loose_{i}", COIN_R, COIN_T, (cx + dx, cy + dy, H), coin, segments=10, bevel=0.001)
