"""A short wooden barrel: curved staves of slightly varied wood, three dark iron hoops and a plank lid
(generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

TILE = 1.5  # metres per tile; the footprint is 1x1 tile, height 0.65 tile = 0.975 m

# Overall dimensions (metres), from the description: about 0.6 m wide and 0.9 m high.
H = 0.9  # height of the staves
R_BELLY = 0.3  # outer radius at the bulge
R_END = 0.265  # outer radius at the heads
STAVES = 16
STAVE_T = 0.03  # stave thickness
SEG = (0.0, 0.3, 0.6, H)  # stave segment breaks: a tapered foot, a straight belly, a tapered head
HOOP_Z = (0.07, H / 2, H - 0.07)
HOOP_TUBE = 0.012
LID_DROP = 0.025  # the lid sits this far below the stave tops (the chime)
LID_T = 0.03

WOOD = (0.2, 0.115, 0.058)  # linear RGB
WOOD_LIGHT = (0.25, 0.155, 0.08)
WOOD_OLD = (0.16, 0.11, 0.075)
WOOD_INNER = (0.11, 0.065, 0.035)
IRON = (0.045, 0.045, 0.045)


def outer_r(z):
    """Outer stave radius at height z: tapering from the heads to the straight belly."""
    if z <= SEG[1]:
        return R_END + (R_BELLY - R_END) * z / SEG[1]
    if z >= SEG[2]:
        return R_END + (R_BELLY - R_END) * (H - z) / (H - SEG[2])
    return R_BELLY


@prop
def barrel_wood():
    rnd = random.Random(1)
    woods = [
        material("barrel_staves", WOOD, vary=0.25, scale=14),
        material("barrel_staves_light", WOOD_LIGHT, vary=0.25, scale=12),
        material("barrel_staves_old", WOOD_OLD, vary=0.3, scale=11),
    ]
    inner = material("barrel_inner", WOOD_INNER, vary=0.2, scale=8)
    lids = [
        material("barrel_lid", WOOD_OLD, vary=0.3, scale=13),
        material("barrel_lid_light", WOOD_LIGHT, vary=0.3, scale=13),
    ]
    lid = lids[0]
    iron = material("barrel_hoops", IRON, rough=0.5, metal=0.8, vary=0.3, scale=20)

    # A closed core behind the staves, so gaps between them read dark rather than see-through.
    cylinder("core", R_END - STAVE_T + 0.004, H - 0.02, (0, 0, 0.005), inner, segments=16, bevel=0)

    # Staves: each one three boxes (foot, belly, head) tilted to follow the bulge.
    pitch = 2 * math.pi * R_BELLY / STAVES
    tilt = math.degrees(math.atan((R_BELLY - R_END) / SEG[1]))
    for i in range(STAVES):
        a = 360 * i / STAVES + rnd.uniform(-1.2, 1.2)
        w = pitch * rnd.uniform(0.9, 0.96)
        mat = woods[rnd.choice((0, 0, 1, 1, 2))]
        top = H - rnd.uniform(0.0, 0.008)
        parts = (
            (SEG[0], SEG[1] + 0.012, tilt),
            (SEG[1] - 0.012, SEG[2] + 0.012, 0.0),
            (SEG[2] - 0.012, top, -tilt),
        )
        for k, (z0, z1, t) in enumerate(parts):
            zc = (z0 + z1) / 2
            rc = outer_r(zc) - STAVE_T / 2
            ar = math.radians(a)
            length = (z1 - z0) / math.cos(math.radians(t))
            box(
                f"stave_{i}_{k}",
                (STAVE_T, w, length),
                (rc * math.cos(ar), rc * math.sin(ar), zc + (0.0015 if k == 0 else 0)),
                mat,
                rot=(0, t, a),
                bevel=0.006,
            )

    # Three dark iron hoops hugging the staves.
    for j, z in enumerate(HOOP_Z):
        torus(f"hoop_{j}", outer_r(z) + HOOP_TUBE * 0.6, HOOP_TUBE, (0, 0, z), iron, major=32, minor=6)

    # The plank lid, set into the chime below the stave heads.
    lid_r = R_END - STAVE_T - 0.004
    lid_z = H - LID_DROP - LID_T / 2
    n = 4
    pw = 2 * lid_r / n
    for p in range(n):
        y = -lid_r + pw * (p + 0.5)
        edge = max(abs(y) - pw / 2, abs(y) + pw / 2)
        span = 2 * math.sqrt(max(lid_r**2 - (abs(y) - pw / 2) ** 2, 0.0)) if edge > lid_r else 2 * lid_r
        span = min(span, 2 * math.sqrt(max(lid_r**2 - (min(abs(y), lid_r) - pw / 2) ** 2, 0.0)))
        box(
            f"lid_{p}",
            (span * 0.92, pw - 0.016, LID_T),
            (0, y, lid_z + rnd.uniform(-0.002, 0.002)),
            lids[p % 2],
            rot=(0, 0, rnd.uniform(-1.5, 1.5)),
            bevel=0.006,
        )
    # A batten across the planks.
    box("lid_batten", (0.06, 2 * lid_r * 0.8, 0.02), (0.08, 0, lid_z + LID_T / 2 + 0.01), lid, rot=(0, 0, 2), bevel=0.006)
