"""Two small wooden crates stacked, the top one smaller and turned; or one open small crate full of apples
(generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box

TILE = 1.5  # metres per tile
# Overall sizes: a 0.35 m crate with a 0.28 m crate on top, about 0.63 m tall (footprint 1x1 tile, height 0.45 tile).
BIG = 0.35  # outer size of the bottom crate, lid included
SMALL = 0.28  # outer size of the top crate
TOP_YAW = 14  # degrees the top crate is turned
TOP_OFF = (0.012, -0.01)  # the top crate sits a little off centre
BW = 0.038  # corner batten width (square posts)
T = 0.016  # wall plank thickness
INSET = 0.007  # planks sit this far behind the battens' outer faces
LID_T = 0.02  # lid plank thickness
PLANKS = 3  # wall planks per face
LID_PLANKS = 3
GAP = 0.006  # gap between planks
APPLE_R = 0.036

WOOD = (0.24, 0.16, 0.088)  # linear RGB
WOOD_OLD = (0.2, 0.145, 0.095)
BATTEN = (0.11, 0.068, 0.04)
INSIDE = (0.08, 0.055, 0.035)
APPLE_RED = (0.3, 0.07, 0.045)
APPLE_GREEN = (0.17, 0.22, 0.06)
STEM = (0.08, 0.055, 0.03)


def _mats():
    return {
        "wood": material("crate_small_planks", WOOD, vary=0.25, scale=18),
        "old": material("crate_small_planks_old", WOOD_OLD, vary=0.3, scale=14),
        "batten": material("crate_small_battens", BATTEN, vary=0.25, scale=16),
        "inside": material("crate_small_inside", INSIDE, vary=0.1, scale=4, crevice=0.2),
    }


def _crate(tag, s, centre, yaw, rnd, m, lid=True):
    """One crate of outer size `s` (lid included when `lid`), standing on `centre` (x, y, z0), turned `yaw` degrees.
    Returns the height of its walls' top."""
    cx, cy, z0 = centre
    c, sn = math.cos(math.radians(yaw)), math.sin(math.radians(yaw))

    def part(name, size, x, y, z, mat, rot=(0, 0, 0), bevel=0.006):
        box(f"{tag}_{name}", size, (cx + x * c - y * sn, cy + x * sn + y * c, z0 + z), mat,
            rot=(rot[0], rot[1], rot[2] + yaw), bevel=bevel)

    wall_h = s - LID_T if lid else s
    h = s / 2
    # Dark inner box so plank gaps show shadow; in an open crate it is the floor under the fill.
    inner = 2 * (h - INSET - T)
    fill = wall_h - (0.01 if lid else 0.05)
    part("inside", (inner, inner, fill), 0, 0, fill / 2, m["inside"], bevel=0)

    # Corner battens: square posts at the four corners, full wall height.
    for i, (sx, sy) in enumerate(((-1, -1), (1, -1), (1, 1), (-1, 1))):
        part(f"post_{i}", (BW, BW, wall_h - rnd.uniform(0, 0.004)), sx * (h - BW / 2), sy * (h - BW / 2),
             wall_h / 2, m["batten"], rot=(0, 0, rnd.uniform(-1, 1)), bevel=0.006)

    # Wall planks between the posts, recessed a little behind them.
    ph = wall_h / PLANKS
    length = s - 2 * BW + 0.01
    off = h - INSET - T / 2
    for f, (nx, ny) in enumerate(((0, -1), (1, 0), (0, 1), (-1, 0))):
        for k in range(PLANKS):
            ht = ph - GAP + rnd.uniform(-0.003, 0.001)
            z = ph * (k + 0.5) + rnd.uniform(-0.0015, 0.0015)
            mat = m["old"] if rnd.random() < 0.35 else m["wood"]
            tilt = rnd.uniform(-0.8, 0.8)
            o = off + rnd.uniform(-0.0015, 0.0015)
            if nx == 0:
                part(f"plank_{f}_{k}", (length, T, ht), rnd.uniform(-0.003, 0.003), ny * o, z, mat, rot=(0, tilt, 0))
            else:
                part(f"plank_{f}_{k}", (T, length, ht), nx * o, rnd.uniform(-0.003, 0.003), z, mat, rot=(tilt, 0, 0))

    if lid:
        lw = s / LID_PLANKS
        for i in range(LID_PLANKS):
            y = -h + lw * (i + 0.5)
            t = LID_T - rnd.uniform(0, 0.003)
            mat = m["old"] if rnd.random() < 0.35 else m["wood"]
            part(f"lid_{i}", (s - rnd.uniform(0, 0.008), lw - GAP, t), rnd.uniform(-0.003, 0.003),
                 y + rnd.uniform(-0.0015, 0.0015), wall_h + t / 2, mat, rot=(0, 0, rnd.uniform(-1.2, 1.2)), bevel=0.005)
    return wall_h


@prop
def crate_small():
    rnd = random.Random(11)
    m = _mats()
    _crate("low", BIG, (0, 0, 0), rnd.uniform(-2, 2), rnd, m)
    _crate("high", SMALL, (TOP_OFF[0], TOP_OFF[1], BIG), TOP_YAW, rnd, m)


@prop
def crate_small_open():
    rnd = random.Random(23)
    m = _mats()
    wall_h = _crate("open", BIG, (0, 0, 0), 3, rnd, m, lid=False)
    red = material("crate_small_apple_red", APPLE_RED, rough=0.55, vary=0.3, scale=30)
    green = material("crate_small_apple_green", APPLE_GREEN, rough=0.55, vary=0.3, scale=30)
    stem = material("crate_small_apple_stem", STEM, vary=0.1)

    inner = BIG / 2 - INSET - T  # half the inner span
    step = 2 * inner / 4
    n = 0

    def apple(x, y, z):
        nonlocal n
        mat = green if rnd.random() < 0.3 else red
        r = APPLE_R * rnd.uniform(0.92, 1.06)
        blob(f"apple_{n}", r, (x, y, z), mat, squash=(1, 1, 0.88), subdiv=1, seed=100 + n, jitter=0.05)
        box(f"apple_stem_{n}", (0.005, 0.005, 0.014), (x, y, z + r * 0.88), stem,
            rot=(rnd.uniform(-20, 20), rnd.uniform(-20, 20), 0), bevel=0)
        n += 1

    # A packed layer just under the rim, then a heap in the hollows above it.
    for i in range(4):
        for j in range(4):
            x = -inner + step * (i + 0.5) + rnd.uniform(-0.005, 0.005)
            y = -inner + step * (j + 0.5) + rnd.uniform(-0.005, 0.005)
            apple(x, y, wall_h - 0.012 + rnd.uniform(-0.004, 0.004))
    for i in range(3):
        for j in range(3):
            if (i, j) in ((0, 0), (2, 2)):
                continue
            x = -inner + step * (i + 1) + rnd.uniform(-0.006, 0.006)
            y = -inner + step * (j + 1) + rnd.uniform(-0.006, 0.006)
            apple(x, y, wall_h + 0.036 + (0.012 if (i, j) == (1, 1) else 0))
