"""A straight 1.5 m section of fieldstone wall: staggered courses of rough blocks on recessed mortar, flat capstones on top
(generated by npm run new). The `_end` variants (by hand) finish a run at a gap: a pier of
big dressed quoins at the +x end, a little proud of both faces and, on the low wall, a little higher."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box

MODULE = 1.5  # metres: the length wall and fence sections join at
L = MODULE  # wall length along x: one module so sections join end to end
T = 0.45  # wall thickness (y)
H = 2.4  # overall height including capstones
# The `_low` variant: a cutaway wall for buildings shown without a roof, so what is inside stays visible.
LOW_H = 1.38
CAP_H = 0.08  # capstone thickness
CAP_D = 0.52  # capstone depth: a slight overhang on both faces
GAP = 0.026  # mortar joint between blocks
RECESS = 0.035  # how far the mortar sits behind the faces of the blocks

# Course heights, bottom to top, scaled to the body height; blocks per course alternate so the joints stagger.
COURSES = [0.38, 0.35, 0.33, 0.32, 0.31, 0.31, 0.30]
PER_COURSE = [4, 5, 4, 5, 4, 5, 4]
CAPS = 4
# The end pier (`_end`): quoin courses alternating long and short along x, proud of the wall faces.
PIER_LONG, PIER_SHORT = 0.5, 0.34
PIER_D = T + 0.07
PIER_RISE = 0.1  # how much higher the pier stands than a low wall (a full-height wall is at its footprint height)
PIER_CAP = 0.1

# Shared stone palette of the village wall set (wall_stone_straight, _corner, _doorframe): keep them equal.
STONE = (0.34, 0.295, 0.235)  # linear RGB, grey-brown fieldstone
STONE_OLD = (0.27, 0.235, 0.19)
MORTAR = (0.11, 0.10, 0.085)
CAP = (0.27, 0.255, 0.23)


def _widths(rnd, n):
    """n block widths jittered around L/n that add up to L; staggered courses start with a half-ish block."""
    raw = [rnd.uniform(0.8, 1.2) for _ in range(n)]
    if n == 5:  # offset course: shorter end blocks so the joints fall over the blocks below
        raw[0] *= 0.55
        raw[-1] *= 0.55
    s = sum(raw)
    return [L * r / s for r in raw]


def _wall(top):
    """The wall, `top` metres high with its capstones; a lower wall keeps fewer courses of about the same height."""
    body_h = top - CAP_H - 0.02  # top of the stone courses (a hair of headroom for jitter)
    k = max(2, min(len(COURSES), round(body_h / (sum(COURSES) / len(COURSES)))))
    courses = COURSES[:k]
    rnd = random.Random(23)
    stone = material("wall_stone_straight_block", STONE, vary=0.22, scale=8, crevice=0.3)
    old = material("wall_stone_straight_block_old", STONE_OLD, vary=0.25, scale=11, crevice=0.3)
    cap = material("wall_stone_straight_cap", CAP, vary=0.22, scale=9, crevice=0.3)
    mortar = material("wall_stone_straight_mortar", MORTAR, vary=0.2, scale=20, crevice=0.8)

    # Mortar core, recessed behind both faces; flush with the section ends so neighbours meet.
    box("core", (L, T - 2 * RECESS, body_h), (0, 0, body_h / 2), mortar, bevel=0)

    scale = body_h / sum(courses)
    z = 0.0
    for c, (ch, n) in enumerate(zip(courses, PER_COURSE)):
        h = ch * scale
        x = -L / 2
        for i, w in enumerate(_widths(rnd, n)):
            end = i in (0, n - 1)
            bw = w - (GAP / 2 if end else GAP)  # end blocks run to the section end
            cx = x + w / 2 + ((GAP / 4) if i == 0 else (-GAP / 4) if i == n - 1 else 0)
            bh = h - GAP
            # Small faces-in/out and height wobble; upper courses tip a degree or two.
            tilt = (0, 0, 0) if c == 0 else (rnd.uniform(-1.2, 1.2), rnd.uniform(-1.5, 1.5), 0)
            box(
                f"block_{c}_{i}",
                (bw * rnd.uniform(0.95, 1.0), T * rnd.uniform(0.93, 1.0), bh * rnd.uniform(0.86, 1.0)),
                (cx, rnd.uniform(-0.012, 0.012), z + GAP / 2 + bh / 2 if c else bh / 2 + 0.001),
                old if rnd.random() < 0.35 else stone,
                rot=(tilt[0], tilt[1], rnd.uniform(-2.5, 2.5) if not end else 0),
                bevel=0.024,
            )
            x += w
        z += h

    # Capstones: flat slabs overhanging both faces a little.
    cw = L / CAPS
    for i in range(CAPS):
        box(
            f"cap_{i}",
            (cw - 0.012, CAP_D * rnd.uniform(0.96, 1.0), CAP_H * rnd.uniform(0.9, 1.0)),
            (-L / 2 + cw * (i + 0.5), rnd.uniform(-0.01, 0.01), body_h + CAP_H / 2),
            cap,
            rot=(0, 0, rnd.uniform(-2, 2)),
            bevel=0.018,
        )


def _pier(top):
    """A pier of dressed quoins flush with the +x end, `top` metres high with its capstone."""
    rnd = random.Random(29)
    stone = material("wall_stone_straight_block", STONE, vary=0.22, scale=8, crevice=0.3)
    old = material("wall_stone_straight_block_old", STONE_OLD, vary=0.25, scale=11, crevice=0.3)
    cap = material("wall_stone_straight_cap", CAP, vary=0.22, scale=9, crevice=0.3)
    body = top - PIER_CAP
    n = max(3, round(body / 0.32))
    h = body / n
    for c in range(n):
        w = PIER_LONG if c % 2 == 0 else PIER_SHORT
        box(
            f"pier_{c}",
            (w - GAP / 2, PIER_D * rnd.uniform(0.97, 1.0), h - GAP),
            (L / 2 - w / 2, rnd.uniform(-0.008, 0.008), c * h + h / 2),
            old if rnd.random() < 0.3 else stone,
            rot=(0, 0, rnd.uniform(-1.0, 1.0)),
            bevel=0.026,
        )
    box(
        "pier_cap",
        (PIER_LONG + 0.04, PIER_D + 0.06, PIER_CAP),
        (L / 2 - (PIER_LONG + 0.04) / 2, 0, body + PIER_CAP / 2),
        cap,
        rot=(0, 0, rnd.uniform(-1.5, 1.5)),
        bevel=0.02,
    )


@prop
def wall_stone_straight():
    _wall(H)


@prop
def wall_stone_straight_low():
    _wall(LOW_H)


@prop
def wall_stone_straight_end():
    _wall(H)
    _pier(H)


@prop
def wall_stone_straight_low_end():
    _wall(LOW_H)
    _pier(LOW_H + PIER_RISE)
