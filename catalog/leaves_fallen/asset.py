"""A few fallen leaves lying flat on the ground, slightly curled: brown, ochre and dull red, each about 8 cm long
(generated by npm run new). Variants: five or six scattered leaves, a small drift of a dozen."""
import math
import random

from mathutils import Euler, Matrix, Vector

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box

# The leaves stay under 0.15 m high and well inside 0.6 m across.
LEAF_L = 0.08  # metres, leaf length tip to stalk
LEAF_W = 0.042  # metres, leaf width at its widest
LEAF_T = 0.006  # metres, leaf thickness
CUP = 0.006  # metres, how far the leaf edges curl up
TIP_CURL = 0.012  # metres, how far the tip curls up
STEM_L = 0.022  # metres, leaf stalk length
STEM_T = 0.003  # metres, leaf stalk thickness
SCATTER_R = 0.2  # metres, radius within which the scattered leaves lie
DRIFT_R = 0.13  # metres, radius of the small drift
LAYER = 0.0035  # metres, how much higher each leaf of the drift lies than the one under it

BROWN = (0.2, 0.11, 0.05)  # linear RGB
DARK = (0.12, 0.068, 0.035)  # old, damp brown
OCHRE = (0.42, 0.27, 0.075)
RED = (0.3, 0.085, 0.04)  # dull red
STEM = (0.16, 0.1, 0.05)


def _mats():
    return {
        "brown": material("leaves_fallen_brown", BROWN, rough=0.85, vary=0.3, scale=60, crevice=0.5),
        "dark": material("leaves_fallen_dark", DARK, rough=0.9, vary=0.3, scale=60, crevice=0.5),
        "ochre": material("leaves_fallen_ochre", OCHRE, rough=0.8, vary=0.3, scale=60, crevice=0.5),
        "red": material("leaves_fallen_red", RED, rough=0.8, vary=0.3, scale=60, crevice=0.5),
        "stem": material("leaves_fallen_stem", STEM, rough=0.9, vary=0.2, scale=40, crevice=0.4),
    }


def _leaf(name, xy, z_low, yaw, tilt, mat, stem_mat, seed):
    """One curled leaf along local +x (stalk at -x), its lowest point at `z_low`."""
    r = LEAF_L / 2
    obj = blob(name, r, (0, 0, 0), mat, squash=(1, LEAF_W / LEAF_L, LEAF_T / LEAF_L), subdiv=1, seed=seed, jitter=0.05)
    for v in obj.data.vertices:
        x, y, z = v.co
        u = x / r  # -1 at the stalk, +1 at the tip
        y *= 1 - 0.55 * max(0.0, u) ** 1.5  # taper to a point
        z += CUP * (y / (LEAF_W / 2)) ** 2 + TIP_CURL * max(0.0, u) ** 2
        v.co = (x, y, z)
    rot = Euler((math.radians(tilt[0]), math.radians(tilt[1]), math.radians(yaw)))
    m = rot.to_matrix()
    low = min((m @ v.co).z for v in obj.data.vertices)
    at = Vector((xy[0], xy[1], z_low - low))
    obj.rotation_euler = rot
    obj.location = at
    # The stalk sticks out of the leaf's base, curving slightly up.
    stem_at = at + m @ Vector((-r - STEM_L / 2 + 0.004, 0, LEAF_T * 0.2 + 0.002))
    box(f"{name}_stem", (STEM_L, STEM_T, STEM_T), tuple(stem_at), stem_mat,
        rot=(tilt[0], tilt[1] - 8, yaw), bevel=0)


def _pick(rnd, mats, weights):
    return mats[rnd.choices(list(weights), weights=list(weights.values()))[0]]


@prop
def leaves_fallen():
    rnd = random.Random(5)
    mats = _mats()
    order = ["ochre", "brown", "red", "ochre", "dark", "red"]
    for i, key in enumerate(order):
        a = 2 * math.pi * i / len(order) + rnd.uniform(-0.4, 0.4)
        d = SCATTER_R * rnd.uniform(0.35, 1.0)
        _leaf(f"leaves_fallen_{i}", (d * math.cos(a), d * math.sin(a)), 0.0, rnd.uniform(0, 360),
              (rnd.uniform(-6, 6), rnd.uniform(-5, 5)), mats[key], mats["stem"], seed=10 + i)


@prop
def leaves_fallen_drift():
    rnd = random.Random(23)
    mats = _mats()
    for i in range(12):
        a = rnd.uniform(0, 2 * math.pi)
        d = DRIFT_R * math.sqrt(rnd.random())
        # Leaves near the middle pile a little higher; each lies a touch above the earlier ones.
        z = LAYER * i * (1 - 0.6 * d / DRIFT_R)
        _leaf(f"leaves_fallen_drift_{i}", (d * math.cos(a), d * math.sin(a)), z, rnd.uniform(0, 360),
              (rnd.uniform(-10, 10), rnd.uniform(-8, 8)), _pick(rnd, mats, {"brown": 3, "ochre": 3, "red": 2, "dark": 2}),
              mats["stem"], seed=40 + i)
