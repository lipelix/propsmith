"""A village street lamp: a dark timber post on a small stone foot, an iron bracket arm at the top and a small
four-sided iron lantern with warm glass panes hanging from it (generated by npm run new)."""
import math
import random

from propsmith import anchor, prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

# The post top is at 2.6 m, the cap about 2.68 m.
FOOT_W, FOOT_TOP_W, FOOT_H = 0.5, 0.4, 0.3  # stone foot: square, tapering
POST = 0.16  # post section
POST_TOP = 2.6
CAP_H = 0.08
ARM_Z = 2.42  # top of the bracket arm
ARM_LEN = 0.6  # from the post centre along +x
BRACE_Z = 2.1  # where the diagonal brace meets the post
LX = 0.5  # lantern axis, along the arm
LANTERN_W = 0.18  # glass body width
LANTERN_BOTTOM, LANTERN_H = 1.85, 0.28  # glass body, bottom and height
ROOF_H = 0.1

STONE = (0.3, 0.27, 0.23)
WOOD = (0.13, 0.08, 0.05)
IRON = (0.045, 0.045, 0.045)
GLASS = (0.48, 0.3, 0.1)


@prop
def lamp_post():
    rnd = random.Random(3)
    stone = material("lamp_post_stone", STONE, vary=0.25, scale=9, crevice=0.6)
    wood = material("lamp_post_wood", WOOD, vary=0.3, scale=16)
    iron = material("lamp_post_iron", IRON, rough=0.55, vary=0.2, scale=20, metal=0.6)
    glass = material("lamp_post_glass", GLASS, rough=0.3, vary=0.15, scale=12, crevice=0.2)

    # Stone foot: a squat tapered block.
    r_bot, r_top = FOOT_W / math.sqrt(2), FOOT_TOP_W / math.sqrt(2)
    cylinder("foot", r_bot, FOOT_H, (0, 0, 0), stone, r_top=r_top, segments=4, rot=(0, 0, 45 + rnd.uniform(-3, 3)),
             bevel=0.02)

    # Timber post with a pyramid cap.
    post_h = POST_TOP - FOOT_H + 0.02
    box("post", (POST, POST, post_h), (0, 0, FOOT_H - 0.02 + post_h / 2), wood,
        rot=(rnd.uniform(-0.5, 0.5), rnd.uniform(-0.5, 0.5), rnd.uniform(-2, 2)), bevel=0.02)
    cylinder("cap", POST * 0.85, CAP_H, (0, 0, POST_TOP - 0.005), wood, r_top=0.02, segments=4, rot=(0, 0, 45),
             bevel=0.008)

    # Iron collars where the bracket is fixed.
    for name, z in (("collar_top", ARM_Z - 0.02), ("collar_low", BRACE_Z)):
        box(name, (POST + 0.025, POST + 0.025, 0.05), (0, 0, z), iron, bevel=0.006)

    # Bracket arm along +x, a diagonal brace and a small scroll in the corner.
    arm_x0 = POST / 2
    box("arm", (ARM_LEN - arm_x0, 0.04, 0.045), ((arm_x0 + ARM_LEN) / 2, 0, ARM_Z - 0.0225), iron, bevel=0.008)
    box("arm_tip", (0.03, 0.05, 0.07), (ARM_LEN - 0.015, 0, ARM_Z - 0.035), iron, bevel=0.006)
    bx0, bz0 = arm_x0, BRACE_Z
    bx1, bz1 = LX - 0.14, ARM_Z - 0.04
    length = math.hypot(bx1 - bx0, bz1 - bz0)
    angle = math.degrees(math.atan2(bz1 - bz0, bx1 - bx0))
    box("brace", (length, 0.03, 0.03), ((bx0 + bx1) / 2, 0, (bz0 + bz1) / 2), iron, rot=(0, -angle, 0), bevel=0.006)
    torus("scroll", 0.075, 0.012, (arm_x0 + 0.1, 0, ARM_Z - 0.13), iron, rot=(90, 0, 0), major=16, minor=6)

    # Hanging hook and ring.
    hook_z = ARM_Z - 0.045
    cylinder("hook", 0.01, 0.05, (LX, 0, hook_z - 0.05), iron, segments=8, bevel=0)
    roof_top = LANTERN_BOTTOM + LANTERN_H + 0.03 + ROOF_H
    ring_z = (hook_z - 0.05 + roof_top) / 2 + 0.01
    torus("ring", 0.035, 0.009, (LX, 0, ring_z), iron, rot=(90, 0, 0), major=12, minor=6)

    # Lantern: base plate, four corner bars, warm glass, top plate, pyramid roof and finial.
    lw = LANTERN_W
    box("lantern_base", (lw + 0.04, lw + 0.04, 0.03), (LX, 0, LANTERN_BOTTOM - 0.015), iron, bevel=0.006)
    cylinder("lantern_drip", 0.035, 0.05, (LX, 0, LANTERN_BOTTOM - 0.075), iron, r_top=0.055, segments=8, bevel=0.004)
    box("lantern_glass", (lw - 0.01, lw - 0.01, LANTERN_H), (LX, 0, LANTERN_BOTTOM + LANTERN_H / 2), glass, bevel=0.004)
    for sx in (-1, 1):
        for sy in (-1, 1):
            box(f"lantern_bar_{sx}_{sy}", (0.025, 0.025, LANTERN_H),
                (LX + sx * lw / 2, sy * lw / 2, LANTERN_BOTTOM + LANTERN_H / 2), iron, bevel=0.005)
    # Mid cross-bars on the two visible faces split the panes.
    box("lantern_mullion_x", (0.014, 0.014, LANTERN_H), (LX + lw / 2 - 0.004, 0, LANTERN_BOTTOM + LANTERN_H / 2), iron,
        bevel=0.003)
    box("lantern_mullion_y", (0.014, 0.014, LANTERN_H), (LX, -lw / 2 + 0.004, LANTERN_BOTTOM + LANTERN_H / 2), iron,
        bevel=0.003)
    top = LANTERN_BOTTOM + LANTERN_H
    box("lantern_top", (lw + 0.05, lw + 0.05, 0.03), (LX, 0, top + 0.015), iron, bevel=0.006)
    cylinder("lantern_roof", (lw + 0.06) / math.sqrt(2), ROOF_H, (LX, 0, top + 0.03), iron, r_top=0.02, segments=4,
             rot=(0, 0, 45), bevel=0.006)

    centre = (LX, 0, LANTERN_BOTTOM + LANTERN_H * 0.45)
    anchor("light:lantern", centre)
    anchor("fire:lantern", (LX, 0, LANTERN_BOTTOM + LANTERN_H * 0.3), size=(0.03, 0.03, 0.1))
