"""A straight half-timbered wall section: fieldstone plinth, oak sill, corner posts, top plate, one diagonal brace and
warm lime plaster infill (generated by npm run new). Panel variants (by hand) so a run of
wall is not one repeated panel: a small lattice window, plain plaster, a high stone plinth and a heavy corner post with
the brace the other way; each in full height and `_low`."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box

MODULE = 1.5  # metres: the length wall and fence sections join at
# Overall dimensions: the wall runs along x through the origin, one module long and 2.4 m high.
L = MODULE  # wall length, one module so sections join end to end
T = 0.3  # wall thickness
H = 1.6 * MODULE - 0.005  # top of the top plate, 2.4 m less a hair so it stays under 2.4 m
# The `_low` variant: a cutaway wall for buildings shown without a roof.
LOW_H = 1.38
PLINTH_H = 0.3  # fieldstone plinth
PLINTH_D = 0.32  # plinth a little proud of the timbers
SILL_H, SILL_D = 0.18, 0.27  # sill beam
POST_W, POST_D = 0.2, 0.25  # corner posts
PLATE_H, PLATE_D = 0.18, 0.27  # top plate
BRACE_W, BRACE_D = 0.15, 0.23  # diagonal brace
PLASTER_D = 0.19  # infill, recessed behind the timber faces
STONE_PLINTH_H = 0.72  # the `_stone` panel: a high fieldstone base, four courses
WIN_W = 0.52  # window opening, between its jambs
WIN_H = 0.42  # window opening height; its head is the top plate on a low wall, 0.5 m under it on a tall one
WIN_FRAME = 0.07  # jambs, head and sill board
WIN_D = 0.24  # frame depth (proud of the plaster on both faces)
MULLION = 0.035  # lattice bars
HEAVY_POST_W, HEAVY_POST_D = 0.27, 0.29  # the `_post` panel's corner post, proud of the frame

STONE = (0.30, 0.265, 0.215)
STONE_OLD = (0.24, 0.215, 0.18)
MORTAR = (0.15, 0.14, 0.12)
OAK = (0.11, 0.072, 0.045)
OAK_OLD = (0.14, 0.10, 0.07)
PLASTER = (0.56, 0.49, 0.37)
GLASS = (0.035, 0.04, 0.045)  # dark leaded panes


def _wall(top, panel="brace"):
    """The wall with the top of its plate at `top` metres; a lower wall keeps the plinth and sill and shortens the posts.
    `panel`: `brace` (one diagonal brace), `window`, `plain`, `stone` (a high plinth) or `post` (a heavy corner post at
    -x and the brace the other way)."""
    rnd = random.Random(11)
    plinth_h = STONE_PLINTH_H if panel == "stone" else PLINTH_H
    stone = material("wall_timber_stone", STONE, vary=0.28, scale=9)
    stone_old = material("wall_timber_stone_old", STONE_OLD, vary=0.3, scale=9)
    mortar = material("wall_timber_mortar", MORTAR, vary=0.15, scale=12)
    oak = material("wall_timber_oak", OAK, vary=0.3, scale=16)
    oak_old = material("wall_timber_oak_old", OAK_OLD, vary=0.3, scale=16)
    plaster = material("wall_timber_plaster", PLASTER, vary=0.14, scale=3, crevice=0.3)

    # Plinth: a mortar core with two staggered courses of rough fieldstone blocks.
    box("plinth_core", (L - 0.02, PLINTH_D - 0.04, plinth_h), (0, 0, plinth_h / 2), mortar, bevel=0)
    courses = (4, 5, 4, 5) if panel == "stone" else (4, 5)
    course_h = plinth_h / len(courses)
    for c, n in enumerate(courses):
        edges = [-L / 2 + L * i / n + (rnd.uniform(-0.04, 0.04) if 0 < i < n else 0) for i in range(n + 1)]
        for i in range(n):
            x0, x1 = edges[i], edges[i + 1]
            h = course_h * rnd.uniform(0.86, 0.98)
            tilt = (rnd.uniform(-1.2, 1.2), rnd.uniform(-1.2, 1.2), 0) if c else (0, 0, 0)
            box(
                f"stone_{c}_{i}",
                (x1 - x0 - 0.022, PLINTH_D * rnd.uniform(0.95, 1.0), h),
                ((x0 + x1) / 2, rnd.uniform(-0.006, 0.006), c * course_h + h / 2 + (0.002 if c else 0)),
                stone_old if rnd.random() < 0.35 else stone,
                rot=(tilt[0], tilt[1], rnd.uniform(-1.5, 1.5)),
                bevel=0.022,
            )

    # Frame: sill beam, two corner posts, top plate.
    sill_z = plinth_h
    box("sill", (L, SILL_D, SILL_H), (0, 0, sill_z + SILL_H / 2), oak, bevel=0.015)
    post_z0, post_z1 = sill_z + SILL_H, top - PLATE_H
    post_h = post_z1 - post_z0
    for s in (-1, 1):
        heavy = panel == "post" and s < 0
        w, d = (HEAVY_POST_W, HEAVY_POST_D) if heavy else (POST_W, POST_D)
        z0, z1 = (sill_z, top) if heavy else (post_z0, post_z1)
        box(
            f"post_{s}",
            (w, d, z1 - z0),
            (s * (L / 2 - w / 2), 0, (z0 + z1) / 2),
            oak_old if s > 0 else oak,
            rot=(0, 0, rnd.uniform(-0.6, 0.6)),
            bevel=0.014,
        )
    box("plate", (L, PLATE_D, PLATE_H), (0, 0, top - PLATE_H / 2), oak, bevel=0.015)

    # Plaster infill between the posts, sill and plate, recessed behind the timber faces.
    in_x = L / 2 - POST_W
    box("plaster", (2 * in_x + 0.02, PLASTER_D, post_h + 0.02), (0, 0, post_z0 + post_h / 2), plaster, bevel=0.02)

    if panel in ("brace", "post"):
        # Diagonal brace from the foot of one post to the head of the other, ends buried in the frame.
        dx, dz = 2 * in_x, post_h
        angle = math.degrees(math.atan2(dz, dx)) * (1 if panel == "brace" else -1)
        length = math.hypot(dx, dz) + 0.12
        box(
            "brace",
            (length, BRACE_D, BRACE_W),
            (0, 0, post_z0 + post_h / 2),
            oak_old,
            rot=(0, -angle, 0),
            bevel=0.013,
        )
    elif panel == "window":
        _window(rnd, oak, oak_old, post_z1, top)
    elif panel == "plain" and post_h > 1.2:
        # A tall plain panel gets a mid rail, as the painting's house fronts.
        box("rail", (2 * in_x + 0.04, BRACE_D, BRACE_W * 0.9), (0, 0, post_z0 + post_h * 0.48), oak_old, bevel=0.012)


def _window(rnd, oak, oak_old, post_z1, top):
    """A small lattice window in the middle of the panel: dark panes, a frame proud of the plaster on both faces, a
    cross of bars and a sill board; its head is the top plate on a low wall."""
    glass = material("wall_timber_glass", GLASS, rough=0.25, vary=0.1, scale=6)
    head = post_z1 if top < 2 else post_z1 - 0.5
    z0, z1 = head - WIN_H, head
    zc = (z0 + z1) / 2
    box("window_pane", (WIN_W, PLASTER_D + 0.02, WIN_H), (0, 0, zc), glass, bevel=0.004)
    for s in (-1, 1):
        box(
            f"window_jamb_{s}",
            (WIN_FRAME, WIN_D, WIN_H + WIN_FRAME),
            (s * (WIN_W + WIN_FRAME) / 2, 0, zc - WIN_FRAME / 2 + (0 if top < 2 else WIN_FRAME / 2)),
            oak,
            rot=(0, 0, rnd.uniform(-0.8, 0.8)),
            bevel=0.01,
        )
    if top >= 2:
        box("window_head", (WIN_W + 2 * WIN_FRAME, WIN_D, WIN_FRAME), (0, 0, z1 + WIN_FRAME / 2), oak, bevel=0.01)
    box("window_sill", (WIN_W + 2 * WIN_FRAME + 0.08, WIN_D + 0.06, WIN_FRAME * 0.8), (0, 0, z0 - WIN_FRAME * 0.4), oak_old, bevel=0.01)
    # Lattice: one upright and one cross bar, a little proud of the panes on both faces.
    box("window_bar_v", (MULLION, PLASTER_D + 0.05, WIN_H), (0, 0, zc), oak_old, bevel=0.006)
    box("window_bar_h", (WIN_W, PLASTER_D + 0.05, MULLION), (0, 0, zc), oak_old, bevel=0.006)


@prop
def wall_timber_straight():
    _wall(H)


@prop
def wall_timber_straight_low():
    _wall(LOW_H)


@prop
def wall_timber_straight_window():
    _wall(H, "window")


@prop
def wall_timber_straight_low_window():
    _wall(LOW_H, "window")


@prop
def wall_timber_straight_plain():
    _wall(H, "plain")


@prop
def wall_timber_straight_low_plain():
    _wall(LOW_H, "plain")


@prop
def wall_timber_straight_stone():
    _wall(H, "stone")


@prop
def wall_timber_straight_low_stone():
    _wall(LOW_H, "stone")


@prop
def wall_timber_straight_post():
    _wall(H, "post")


@prop
def wall_timber_straight_low_post():
    _wall(LOW_H, "post")
