"""A carved stone sarcophagus: a heavy grey chest on a moulded plinth, a moulded rim, and a lid with the low relief of
a lying knight with folded hands on his sword; cracked corners and a little moss in the joints (generated by npm run
new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box

# About 2.2 m long (x), 0.9 m wide (y) and 1 m high with the effigy. The long front side faces -y; the knight's head
# is at +x.
L, W = 2.2, 0.9
PLINTH_H = 0.12  # bottom slab
STEP_L, STEP_W, STEP_H = 2.12, 0.82, 0.06  # moulded step on the plinth
BODY_L, BODY_W = 2.0, 0.72  # the chest
BODY_TOP = 0.70
RIM_L, RIM_W, RIM_H = 2.08, 0.80, 0.05  # moulded rim under the lid
LID_L, LID_W, LID_H = 2.14, 0.84, 0.10
Z_LID = BODY_TOP + RIM_H + LID_H  # top face of the lid, 0.85
PANEL_T = 0.025  # how far the carved frames stand proud of the chest

STONE = (0.34, 0.33, 0.30)
STONE_OLD = (0.29, 0.28, 0.25)
EFFIGY = (0.37, 0.355, 0.32)
CRACK = (0.06, 0.058, 0.052)
MOSS = (0.075, 0.11, 0.035)
MOSS_DEEP = (0.04, 0.06, 0.018)


@prop
def sarcophagus_stone():
    rnd = random.Random(7)
    stone = material("sarcophagus_stone", STONE, vary=0.25, scale=7)
    old = material("sarcophagus_stone_old", STONE_OLD, vary=0.3, scale=9)
    fig = material("sarcophagus_effigy", EFFIGY, vary=0.25, scale=6, crevice=0.8)
    crack = material("sarcophagus_crack", CRACK, vary=0.1, crevice=0)
    moss = material("sarcophagus_moss", MOSS, vary=0.35, scale=20)
    moss_deep = material("sarcophagus_moss_deep", MOSS_DEEP, vary=0.3, scale=20)

    # Plinth and its moulded step.
    box("plinth", (L, W, PLINTH_H), (0, 0, PLINTH_H / 2), old, rot=(0, 0, 0.3), bevel=0.025)
    box("plinth_step", (STEP_L, STEP_W, STEP_H), (0, 0, PLINTH_H + STEP_H / 2), stone, bevel=0.02)
    box("plinth_torus", (BODY_L + 0.05, BODY_W + 0.05, 0.03), (0, 0, PLINTH_H + STEP_H + 0.015), stone, bevel=0.012)

    # The chest.
    z0 = PLINTH_H + STEP_H
    body_h = BODY_TOP - z0
    box("chest", (BODY_L, BODY_W, body_h), (0, 0, z0 + body_h / 2), stone, bevel=0.015)

    # Carved frames: pilasters dividing the long sides into three panels, the ends into one, and a top and bottom band.
    ph = body_h - 0.1
    pz = z0 + body_h / 2
    for s in (-1, 1):
        y = s * (BODY_W / 2 + PANEL_T / 2 - 0.004)
        for i, x in enumerate((-0.96, -0.32, 0.32, 0.96)):
            box(f"pilaster_{s}_{i}", (0.08 * rnd.uniform(0.95, 1.05), PANEL_T, ph), (x, y, pz), stone,
                rot=(0, rnd.uniform(-0.6, 0.6), 0), bevel=0.008)
        for k, z in enumerate((z0 + 0.04, BODY_TOP - 0.04)):
            box(f"band_{s}_{k}", (BODY_L, PANEL_T, 0.035), (0, y, z), stone, bevel=0.008)
        x = s * (BODY_L / 2 + PANEL_T / 2 - 0.004)
        for i, yy in enumerate((-0.32, 0.32)):
            box(f"end_pilaster_{s}_{i}", (PANEL_T, 0.07, ph), (x, yy, pz), stone, bevel=0.008)
        for k, z in enumerate((z0 + 0.04, BODY_TOP - 0.04)):
            box(f"end_band_{s}_{k}", (PANEL_T, BODY_W, 0.035), (x, 0, z), stone, bevel=0.008)

    # A carved shield in the middle front panel and a cross on each end.
    fy = -(BODY_W / 2 + PANEL_T / 2)
    box("shield", (0.2, PANEL_T, 0.24), (0, fy, pz + 0.02), fig, bevel=0.03)
    box("shield_point", (0.12, PANEL_T, 0.12), (0, fy, pz - 0.09), fig, rot=(0, 45, 0), bevel=0.02)
    box("shield_bar_v", (0.03, PANEL_T + 0.012, 0.2), (0, fy - 0.006, pz), old, bevel=0.006)
    box("shield_bar_h", (0.15, PANEL_T + 0.012, 0.03), (0, fy - 0.006, pz + 0.06), old, bevel=0.006)
    for s in (-1, 1):
        ex = s * (BODY_L / 2 + PANEL_T / 2)
        box(f"cross_v_{s}", (PANEL_T, 0.06, 0.3), (ex, 0, pz), fig, bevel=0.008)
        box(f"cross_h_{s}", (PANEL_T, 0.22, 0.06), (ex, 0, pz + 0.05), fig, bevel=0.008)

    # Moulded rim.
    box("rim", (RIM_L, RIM_W, RIM_H), (0, 0, BODY_TOP + RIM_H / 2), old, bevel=0.015)

    # Lid: an L of two slabs and a cracked-off corner fragment at +x/-y, settled a little askew.
    zl = BODY_TOP + RIM_H + LID_H / 2
    cy, cx = -0.2, 0.85
    box("lid_back", (LID_L, LID_W / 2 - cy, LID_H), (0, (cy + LID_W / 2) / 2, zl), stone, bevel=0.025)
    box("lid_front", (cx + LID_L / 2 - 0.006, cy + LID_W / 2 - 0.006, LID_H),
        ((cx - LID_L / 2) / 2 - 0.003, (cy - LID_W / 2) / 2 - 0.003, zl), stone, bevel=0.025)
    fw, fd = LID_L / 2 - cx - 0.008, cy + LID_W / 2 - 0.008
    box("lid_fragment", (fw, fd, LID_H * 0.96), (cx + fw / 2 + 0.008, cy - fd / 2 - 0.008, zl - 0.006), old,
        rot=(1.5, -1.2, 2.5), bevel=0.02)

    # Raised border framing the relief on the lid.
    fz = Z_LID + 0.012
    box("lid_border_y0", (LID_L - 0.1, 0.05, 0.024), (0, -LID_W / 2 + 0.07, fz), stone, bevel=0.008)
    box("lid_border_y1", (LID_L - 0.1, 0.05, 0.024), (0, LID_W / 2 - 0.07, fz), stone, bevel=0.008)
    for s in (-1, 1):
        box(f"lid_border_x{s}", (0.05, LID_W - 0.14, 0.024), (s * (LID_L / 2 - 0.07), 0, fz), stone, bevel=0.008)

    # The knight in low relief, head at +x on a pillow, hands folded on the hilt of a sword laid down his body.
    z = Z_LID
    box("pillow", (0.24, 0.4, 0.05), (0.83, 0, z + 0.025), fig, rot=(0, 0, 1.5), bevel=0.02)
    blob("helm", 0.105, (0.78, 0, z + 0.08), fig, squash=(1.05, 0.85, 0.58), subdiv=2, seed=4, jitter=0.03)
    box("neck", (0.08, 0.11, 0.07), (0.67, 0, z + 0.035), fig, bevel=0.015)
    box("torso", (0.46, 0.38, 0.09), (0.42, 0, z + 0.045), fig, bevel=0.03)
    box("chest_plate", (0.3, 0.26, 0.03), (0.45, 0, z + 0.09), fig, bevel=0.012)
    box("hips", (0.28, 0.33, 0.08), (0.07, 0, z + 0.04), fig, bevel=0.025)
    for s in (-1, 1):
        box(f"leg_{s}", (0.68, 0.13, 0.07), (-0.41, s * 0.075, z + 0.035), fig,
            rot=(0, 0, s * rnd.uniform(0.3, 1.0)), bevel=0.025)
        box(f"knee_{s}", (0.08, 0.12, 0.025), (-0.28, s * 0.075, z + 0.072), fig, bevel=0.01)
        box(f"foot_{s}", (0.07, 0.1, 0.13), (-0.79, s * 0.08, z + 0.065), fig, rot=(0, -8, s * 6), bevel=0.02)
        box(f"shoulder_{s}", (0.13, 0.11, 0.07), (0.6, s * 0.2, z + 0.055), fig, bevel=0.025)
        box(f"upper_arm_{s}", (0.24, 0.085, 0.07), (0.46, s * 0.21, z + 0.055), fig, rot=(0, 0, s * -4), bevel=0.025)
        box(f"forearm_{s}", (0.2, 0.075, 0.055), (0.37, s * 0.1, z + 0.095), fig, rot=(0, 0, s * 58), bevel=0.02)
        blob(f"hand_{s}", 0.038, (0.43, s * 0.022, z + 0.112), fig, squash=(1.3, 0.6, 0.75), subdiv=1,
             seed=10 + s, jitter=0.04)
    # Sword: blade from the hands down over the legs, cross-guard and pommel.
    box("blade", (0.74, 0.055, 0.025), (-0.05, 0, z + 0.08), fig, bevel=0.008)
    box("guard", (0.04, 0.22, 0.03), (0.34, 0, z + 0.1), fig, bevel=0.01)
    blob("pommel", 0.028, (0.52, 0, z + 0.11), fig, squash=(1, 1, 0.8), subdiv=1, seed=3, jitter=0.04)

    # Cracks: thin dark seams standing a hair proud of the worn corners.
    cracks = [
        ((0.16, 0.006, 0.01), (0.9, -BODY_W / 2 - PANEL_T - 0.002, 0.55), (0, 55, 0)),
        ((0.1, 0.006, 0.01), (0.95, -BODY_W / 2 - PANEL_T - 0.002, 0.44), (0, -30, 0)),
        ((0.006, 0.14, 0.01), (-BODY_L / 2 - PANEL_T - 0.002, -0.24, 0.35), (50, 0, 0)),
        ((0.18, 0.006, 0.01), (-0.98, -W / 2 - 0.002, 0.07), (0, 35, 0)),
        ((0.006, 0.12, 0.01), (L / 2 + 0.002, 0.3, 0.06), (-40, 0, 0)),
        ((0.12, 0.006, 0.01), (-0.9, -LID_W / 2 - 0.002, zl), (0, 20, 0)),
    ]
    for i, (sz, at, rot) in enumerate(cracks):
        box(f"crack_{i}", sz, at, crack, rot=rot, bevel=0)

    # Moss in the joints: plinth to chest, chest to rim, and round the cracked lid corner.
    patches = [
        (-0.85, -BODY_W / 2 - 0.03, z0 + 0.02, 0.07), (-0.2, -BODY_W / 2 - 0.03, z0 + 0.02, 0.05),
        (0.7, -BODY_W / 2 - 0.03, z0 + 0.02, 0.06), (BODY_L / 2 + 0.03, 0.2, z0 + 0.02, 0.07),
        (BODY_L / 2 + 0.03, -0.3, z0 + 0.02, 0.05), (-BODY_L / 2 - 0.03, -0.1, z0 + 0.02, 0.06),
        (-0.55, -RIM_W / 2 + 0.01, BODY_TOP + 0.01, 0.045), (1.0, -0.33, Z_LID - 0.005, 0.05),
        (-1.0, -W / 2 + 0.04, PLINTH_H, 0.06), (1.03, W / 2 - 0.04, PLINTH_H, 0.05),
    ]
    for i, (x, y, zz, r) in enumerate(patches):
        blob(f"moss_{i}", r, (x, y, zz), moss if i % 3 else moss_deep, squash=(1.6, 0.9, 0.45), subdiv=1,
             seed=20 + i, jitter=0.2)
