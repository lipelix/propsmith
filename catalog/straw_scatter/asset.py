"""Loose straw strewn on the ground: a thin flat drift of pale golden stalks crossing each other, a few centimetres
high (generated by npm run new). Variants: a thin drift, a small trampled heap."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box

TILE = 1.5  # metres per tile
# Footprint 1x1 tile (1.5 x 1.5 m), height 0.1 tile (0.15 m). The straw stays well inside 0.6 m across.
DRIFT_R = 0.16  # metres, radius within which the stalk centres of the drift lie
DRIFT_H = 0.025  # metres, how high the crossing stalks pile up in the middle of the drift
HEAP_R = 0.15  # metres, radius of the trampled heap's core
HEAP_H = 0.085  # metres, height of the heap's core
STALK_L = (0.12, 0.22)  # metres, stalk lengths
STALK_W = 0.011  # metres, stalk width (flattened)
STALK_T = 0.005  # metres, stalk thickness

PALE = (0.48, 0.38, 0.17)  # linear RGB, pale golden straw
GOLD = (0.4, 0.29, 0.11)
OLD = (0.3, 0.22, 0.1)  # older, greyer straw
DAMP = (0.2, 0.15, 0.07)  # trodden, damp underlayer


def _mats():
    return {
        "pale": material("straw_scatter_pale", PALE, rough=0.9, vary=0.25, scale=40, crevice=0.4),
        "gold": material("straw_scatter_gold", GOLD, rough=0.9, vary=0.25, scale=40, crevice=0.4),
        "old": material("straw_scatter_old", OLD, rough=0.95, vary=0.3, scale=40, crevice=0.5),
        "damp": material("straw_scatter_damp", DAMP, rough=0.95, vary=0.3, scale=30, crevice=0.6),
    }


def _stalk(name, at_xy, z_low, length, yaw, pitch, mat, roll=0.0):
    """A flat stalk lying along local x, tipped by `pitch` degrees, its lowest point at `z_low`."""
    p = math.radians(abs(pitch))
    cz = z_low + length / 2 * math.sin(p) + STALK_T / 2 * math.cos(p) + STALK_W / 2 * math.sin(math.radians(abs(roll)))
    box(name, (length, STALK_W, STALK_T), (at_xy[0], at_xy[1], cz), mat, rot=(roll, pitch, yaw), bevel=0)


def _pick(rnd, mats, weights):
    return mats[rnd.choices(list(weights), weights=list(weights.values()))[0]]


def _drift(rnd, mats, n, radius, height, prefix, weights):
    for i in range(n):
        a = rnd.uniform(0, 2 * math.pi)
        r = radius * math.sqrt(rnd.random())
        x, y = r * math.cos(a), r * math.sin(a)
        falloff = max(0.0, 1 - (r / radius) ** 2)
        z_low = height * falloff * rnd.uniform(0.2, 1.0)
        length = rnd.uniform(*STALK_L) * (1 - 0.3 * r / radius)
        _stalk(f"{prefix}_{i}", (x, y), z_low, length, rnd.uniform(0, 180), rnd.uniform(-4, 4),
               _pick(rnd, mats, weights), roll=rnd.uniform(-10, 10))


@prop
def straw_scatter():
    rnd = random.Random(7)
    mats = _mats()
    # A trodden underlayer first, then the pale stalks crossing on top.
    _drift(rnd, mats, 20, DRIFT_R * 0.8, DRIFT_H * 0.3, "straw_scatter_under", {"damp": 2, "old": 3})
    _drift(rnd, mats, 56, DRIFT_R, DRIFT_H, "straw_scatter_stalk", {"pale": 5, "gold": 3, "old": 1})


@prop
def straw_scatter_heap():
    rnd = random.Random(19)
    mats = _mats()
    jitter = 0.06
    sz = HEAP_H / 2 / HEAP_R
    blob("straw_scatter_core", HEAP_R, (0, 0, HEAP_H / 2 * (1 + jitter)), mats["gold"], squash=(1, 0.85, sz),
         subdiv=2, seed=4, jitter=jitter)
    # Stalks lying on the dome, tipped along its slope.
    for i in range(46):
        a = rnd.uniform(0, 2 * math.pi)
        r = HEAP_R * math.sqrt(rnd.random()) * 0.9
        x, y = r * math.cos(a), r * math.sin(a) * 0.85
        top = HEAP_H * (1 + jitter)
        z_surf = top * max(0.0, 1 - (r / HEAP_R) ** 2) - 0.012
        slope = math.degrees(math.atan(2 * top * r / HEAP_R ** 2))
        yaw = math.degrees(a) + rnd.uniform(-45, 45)
        pitch = slope * math.cos(math.radians(yaw) - a) * 0.8
        length = rnd.uniform(*STALK_L) * 0.8
        p = math.radians(abs(pitch))
        _stalk(f"straw_scatter_heap_{i}", (x, y), max(0.0, z_surf - length / 2 * math.sin(p)), length, yaw, pitch,
               _pick(rnd, mats, {"pale": 5, "gold": 2, "old": 1}), roll=rnd.uniform(-15, 15))
    # Trampled skirt of loose stalks spread around the heap.
    _drift(rnd, mats, 26, HEAP_R * 1.35, 0.008, "straw_scatter_skirt", {"pale": 3, "old": 2, "damp": 1})
