"""A low oak plank chest with a slightly domed lid, dark iron corner bands and straps, side ring handles and an iron
hasp with a padlock on the front (-y) (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, torus

TILE = 1.5  # metres per tile
# Overall dimensions (real-world chest, well inside the 1x1 tile = 1.5 x 1.5 m footprint).
W, D, H = 0.9, 0.54, 0.6  # lid width (x), lid depth (y), total height (z)
BW, BD = W - 0.02, D - 0.02  # body, inset under the lid band
BODY_H = 0.40  # top of the box body
BODY_PLANKS = 4
BAND_H = 0.08  # straight lid band below the dome
RIM_Z = BODY_H + BAND_H  # where the dome starts
SAG = H - RIM_Z  # dome rise
R = (D * D / 4 + SAG * SAG) / (2 * SAG)  # dome radius from chord D and rise SAG
CZ = H - R  # dome axis height
TH_MAX = math.asin(D / 2 / R)  # half angle of the dome
LID_PLANKS = 5
LID_T = 0.13  # radial depth of a dome plank (fills the dome solid)

IRON_T = 0.007  # strap and band thickness
CORNER_W = 0.06  # corner band leg width
STRAP_W = 0.05
STRAP_X = (-0.26, 0.26)

OAK = (0.2, 0.12, 0.062)  # linear RGB
OAK_OLD = (0.155, 0.095, 0.052)
OAK_LID = (0.185, 0.112, 0.058)
IRON = (0.04, 0.038, 0.036)
LOCK = (0.06, 0.05, 0.042)  # a slightly rusty iron


@prop
def chest_wood():
    rnd = random.Random(11)
    oak = material("chest_wood_plank", OAK, vary=0.25, scale=14)
    old = material("chest_wood_plank_old", OAK_OLD, vary=0.28, scale=14)
    lidw = material("chest_wood_lid", OAK_LID, vary=0.25, scale=14)
    iron = material("chest_wood_iron", IRON, rough=0.55, vary=0.2, scale=20, metal=0.6)
    lock = material("chest_wood_lock", LOCK, rough=0.5, vary=0.2, scale=20, metal=0.6)

    # Body: horizontal plank courses, each a closed slab, with a little jitter so the seams read.
    ph = BODY_H / BODY_PLANKS
    for i in range(BODY_PLANKS):
        box(
            f"body_plank_{i}",
            (BW - rnd.uniform(0, 0.006), BD - rnd.uniform(0, 0.006), ph),
            (rnd.uniform(-0.002, 0.002), rnd.uniform(-0.002, 0.002), ph * (i + 0.5)),
            rnd.choice((oak, oak, old)),
            bevel=0.01,
        )

    # Lid: a straight band, then a dome of planks running along x.
    box("lid_band", (W, D, BAND_H), (0, 0, BODY_H + BAND_H / 2), lidw, bevel=0.012)
    step = 2 * TH_MAX / LID_PLANKS
    pw = 2 * R * math.tan(step / 2)
    angles = [-TH_MAX + step * (i + 0.5) for i in range(LID_PLANKS)]
    for i, th in enumerate(angles):
        r = R - LID_T / 2 - rnd.uniform(0, 0.003)
        box(
            f"lid_plank_{i}",
            (W - rnd.uniform(0, 0.008), pw, LID_T),
            (0, r * math.sin(th), CZ + r * math.cos(th)),
            rnd.choice((lidw, lidw, old)),
            rot=(-math.degrees(th) + rnd.uniform(-0.4, 0.4), 0, 0),
            bevel=0.01,
        )

    # Iron corner bands: an L of two legs on every vertical corner, on the body and on the lid band.
    for sx in (-1, 1):
        for sy in (-1, 1):
            for part, (w, d, z0, z1) in (("body", (BW, BD, 0, BODY_H)), ("band", (W, D, BODY_H, RIM_Z))):
                h, zc = z1 - z0, (z0 + z1) / 2
                box(f"corner_{part}_{sx}_{sy}_y", (CORNER_W, IRON_T, h),
                    (sx * (w / 2 - CORNER_W / 2 + 0.002), sy * (d / 2 + IRON_T / 2), zc), iron, bevel=0.003)
                box(f"corner_{part}_{sx}_{sy}_x", (IRON_T, CORNER_W, h),
                    (sx * (w / 2 + IRON_T / 2), sy * (d / 2 - CORNER_W / 2 + 0.002), zc), iron, bevel=0.003)

    # Two straps running up the front, over the dome and down the back.
    for k, x in enumerate(STRAP_X):
        for sy in (-1, 1):
            box(f"strap_body_{k}_{sy}", (STRAP_W, IRON_T, BODY_H - 0.02),
                (x, sy * (BD / 2 + IRON_T / 2), BODY_H / 2 + 0.01), iron, bevel=0.003)
            box(f"strap_band_{k}_{sy}", (STRAP_W, IRON_T, BAND_H),
                (x, sy * (D / 2 + IRON_T / 2), BODY_H + BAND_H / 2), iron, bevel=0.003)
        for i, th in enumerate(angles):
            r = R + IRON_T / 2 - 0.001
            box(f"strap_lid_{k}_{i}", (STRAP_W, pw + 0.004, IRON_T),
                (x, r * math.sin(th), CZ + r * math.cos(th)), iron, rot=(-math.degrees(th), 0, 0), bevel=0.003)

    # Side ring handles on the x ends.
    for sx in (-1, 1):
        box(f"handle_plate_{sx}", (0.01, 0.08, 0.05), (sx * (BW / 2 + 0.005), 0, 0.3), iron, bevel=0.003)
        torus(f"handle_ring_{sx}", 0.045, 0.008, (sx * (BW / 2 + 0.014), 0, 0.3 - 0.04), iron,
              rot=(90, 0, 90), major=16, minor=6)

    # Front: a hasp hanging from the lid band over the body, a staple and a padlock.
    fy = -D / 2 - IRON_T
    box("hasp", (0.065, 0.008, 0.13), (0, fy - 0.002, RIM_Z - 0.06), iron, bevel=0.003)
    torus("hasp_staple", 0.018, 0.005, (0, fy - 0.01, RIM_Z - 0.12), iron, rot=(0, 90, 0), major=12, minor=6)
    torus("padlock_shackle", 0.022, 0.006, (0, fy - 0.022, RIM_Z - 0.135), iron, rot=(90, 0, 0), major=14, minor=6)
    box("padlock_body", (0.07, 0.028, 0.06), (0, fy - 0.022, RIM_Z - 0.175), lock, bevel=0.006)
