"""A plain six-sided wooden coffin of dark weathered planks, iron nails and two iron bar handles on each long side, its
lid slid a little askew (generated by npm run new). Head at +x, foot at -x."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder

# Overall dimensions (metres), from the description.
L = 1.95  # body length along x (the lid makes it about 2 m)
HEAD_X, HEAD_W = L / 2, 0.19  # head end: x and half width
SHOULDER_X, SHOULDER_W = L / 2 - 0.45, 0.30  # shoulders: 0.6 m wide
FOOT_X, FOOT_W = -L / 2, 0.15  # foot end
H = 0.45  # total height, lid on
LID_T = 0.035
BODY_H = H - LID_T - 0.004  # top of the walls (nail heads make up the rest)
FLOOR_T = 0.03
WALL_T = 0.025
WALL_PLANKS = 3

LID_OVER = 0.012  # lid overhang past the walls
LID_SHIFT = (-0.06, 0.0)  # askew: slid toward the foot ...
LID_TURN = 4.0  # ... and turned (degrees about z)
LID_CUTS = (-0.1, 0.1)  # lid plank seams (y)
LID_GAP = 0.004

HANDLE_Z = 0.25
HANDLE_T = (0.2, 0.65)  # along the shoulder-to-foot side
HANDLE_OUT = 0.04
NAIL_R, NAIL_H = 0.007, 0.004

WOOD = (0.15, 0.108, 0.078)  # dark weathered planks, linear RGB
WOOD_OLD = (0.13, 0.098, 0.076)
WOOD_GREY = (0.16, 0.135, 0.11)
INNER = (0.07, 0.05, 0.04)
IRON = (0.06, 0.056, 0.052)

# The outline, counter-clockwise from the head's +y corner.
OUTLINE = [
    (HEAD_X, HEAD_W), (SHOULDER_X, SHOULDER_W), (FOOT_X, FOOT_W),
    (FOOT_X, -FOOT_W), (SHOULDER_X, -SHOULDER_W), (HEAD_X, -HEAD_W),
]


def offset(poly, d):
    """The convex CCW polygon `poly` with every edge moved outward by `d`."""
    n = len(poly)
    lines = []
    for i in range(n):
        (x0, y0), (x1, y1) = poly[i], poly[(i + 1) % n]
        ln = math.hypot(x1 - x0, y1 - y0)
        nx, ny = (y1 - y0) / ln, -(x1 - x0) / ln
        lines.append((nx, ny, nx * x0 + ny * y0 + d))
    out = []
    for i in range(n):
        a1, b1, c1 = lines[i - 1]
        a2, b2, c2 = lines[i]
        det = a1 * b2 - a2 * b1
        out.append(((c1 * b2 - c2 * b1) / det, (a1 * c2 - a2 * c1) / det))
    return out


def clip(poly, f):
    """Sutherland-Hodgman: the part of `poly` where f(p) >= 0 (f linear)."""
    out = []
    for i in range(len(poly)):
        p, q = poly[i - 1], poly[i]
        fp, fq = f(p), f(q)
        if fq >= 0:
            if fp < 0:
                t = fp / (fp - fq)
                out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
            out.append(q)
        elif fp >= 0:
            t = fp / (fp - fq)
            out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    return out


def prism(name, poly, h, at, mat, turn=0.0, bevel=0.008):
    """A closed vertical prism over the convex CCW polygon `poly`: a capped cylinder of as many segments, its ring
    vertices moved onto the polygon (same faces, so it stays closed)."""
    obj = cylinder(name, 1.0, h, at, mat, segments=len(poly), rot=(0, 0, turn), bevel=bevel)
    mesh = obj.data
    ring = sorted({(round(v.co.x, 5), round(v.co.y, 5)) for v in mesh.vertices}, key=lambda p: math.atan2(p[1], p[0]))
    start = min(range(len(poly)), key=lambda i: math.atan2(poly[i][1], poly[i][0]))
    target = {k: poly[(start + i) % len(poly)] for i, k in enumerate(ring)}
    for v in mesh.vertices:
        x, y = target[(round(v.co.x, 5), round(v.co.y, 5))]
        v.co.x, v.co.y = x, y
    mesh.update()
    mesh.set_sharp_from_angle(angle=math.radians(10))
    return obj


def edges(poly):
    """(start, unit direction, length, angle in degrees) of each edge; the inside is to the left."""
    for i in range(len(poly)):
        (x0, y0), (x1, y1) = poly[i], poly[(i + 1) % len(poly)]
        ln = math.hypot(x1 - x0, y1 - y0)
        yield (x0, y0), ((x1 - x0) / ln, (y1 - y0) / ln), ln, math.degrees(math.atan2(y1 - y0, x1 - x0))


@prop
def coffin_wood():
    rnd = random.Random(7)
    woods = [
        material("coffin_wood_plank", WOOD, vary=0.3, scale=14),
        material("coffin_wood_plank_old", WOOD_OLD, vary=0.3, scale=14),
        material("coffin_wood_plank_grey", WOOD_GREY, vary=0.28, scale=14),
    ]
    inner = material("coffin_wood_inner", INNER, vary=0.25, scale=10)
    iron = material("coffin_wood_iron", IRON, rough=0.55, vary=0.2, scale=20, metal=0.6)

    # Floor board under the walls.
    prism("floor", OUTLINE, FLOOR_T, (0, 0, 0), inner, bevel=0.006)

    # Walls: three horizontal planks per side, outer face on the outline, a little longer to close the corners.
    ph = (BODY_H - FLOOR_T) / WALL_PLANKS
    for i, ((x0, y0), (dx, dy), ln, deg) in enumerate(edges(OUTLINE)):
        nx, ny = -dy, dx  # inward
        for k in range(WALL_PLANKS):
            t = WALL_T - rnd.uniform(0, 0.003)
            s = ln / 2 + rnd.uniform(-0.004, 0.004)
            box(
                f"wall_{i}_{k}",
                (ln + WALL_T * 0.9, t, ph - 0.003),
                (x0 + dx * s + nx * t / 2, y0 + dy * s + ny * t / 2, FLOOR_T + ph * (k + 0.5)),
                rnd.choice(woods),
                rot=(0, 0, deg + rnd.uniform(-0.25, 0.25)),
                bevel=0.008,
            )
            # Nails near both corners of every plank.
            for u in (0.016, ln - 0.016):
                cylinder(
                    f"wall_nail_{i}_{k}_{int(u * 1000)}", NAIL_R, NAIL_H,
                    (x0 + dx * u, y0 + dy * u, FLOOR_T + ph * (k + 0.5) + rnd.uniform(-0.01, 0.01)),
                    iron, segments=6, rot=(90, 0, deg), bevel=0,
                )

    # Lid: three long planks over the outline plus overhang, slid and turned askew.
    lid = offset(OUTLINE, LID_OVER)
    bounds = (-1.0, LID_CUTS[0], LID_CUTS[1], 1.0)
    turn = math.radians(LID_TURN)

    def place(p):
        x, y = p
        return (LID_SHIFT[0] + x * math.cos(turn) - y * math.sin(turn),
                LID_SHIFT[1] + x * math.sin(turn) + y * math.cos(turn))

    for j in range(3):
        lo, hi = bounds[j] + LID_GAP / 2, bounds[j + 1] - LID_GAP / 2
        strip = clip(clip(lid, lambda p, lo=lo: p[1] - lo), lambda p, hi=hi: hi - p[1])
        prism(f"lid_plank_{j}", strip, LID_T - rnd.uniform(0, 0.003), (*LID_SHIFT, BODY_H), rnd.choice(woods),
              turn=LID_TURN + rnd.uniform(-0.2, 0.2), bevel=0.008)

    # Lid nails: a row along every edge, over where the walls were.
    for i, ((x0, y0), (dx, dy), ln, _) in enumerate(edges(offset(OUTLINE, -WALL_T / 2))):
        n = max(2, round(ln / 0.3))
        for k in range(n):
            u = 0.03 + (ln - 0.06) * k / n
            x, y = place((x0 + dx * u, y0 + dy * u))
            cylinder(f"lid_nail_{i}_{k}", NAIL_R, NAIL_H, (x, y, BODY_H + LID_T - 0.001), iron, segments=6, bevel=0)

    # Handles: two iron bar handles on each long (shoulder-to-foot) side.
    for i, ((x0, y0), (dx, dy), ln, deg) in enumerate(edges(OUTLINE)):
        if i not in (1, 4):
            continue
        ox, oy = dy, -dx  # outward
        for k, t in enumerate(HANDLE_T):
            px, py = x0 + dx * ln * t, y0 + dy * ln * t
            box(f"handle_plate_{i}_{k}", (0.2, 0.008, 0.05), (px + ox * 0.004, py + oy * 0.004, HANDLE_Z), iron,
                rot=(0, 0, deg), bevel=0.003)
            for s in (-1, 1):
                ax, ay = px + dx * s * 0.075, py + dy * s * 0.075
                box(f"handle_arm_{i}_{k}_{s}", (0.016, HANDLE_OUT, 0.016),
                    (ax + ox * HANDLE_OUT / 2, ay + oy * HANDLE_OUT / 2, HANDLE_Z), iron, rot=(0, 0, deg), bevel=0.003)
            gx, gy = px - dx * 0.085 + ox * HANDLE_OUT, py - dy * 0.085 + oy * HANDLE_OUT
            cylinder(f"handle_grip_{i}_{k}", 0.014, 0.17, (gx, gy, HANDLE_Z), iron, segments=8,
                     rot=(0, 90, deg), bevel=0.002)
