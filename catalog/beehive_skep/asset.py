"""A traditional straw beehive skep: a dome of coiled straw rope with a small dark entrance at the base (front, -y),
sitting on a round wooden board on a short stake stand (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder, torus

# Overall dimensions (metres), from the description: the skep about 0.5 m wide and 0.55 m high.
SKEP_R = 0.25  # outer radius of the skep at its base
SKEP_H = 0.55  # height of the skep above the board
COIL_T = 0.024  # tube radius of the straw rope
COIL_PITCH = 0.042  # vertical spacing of the coils
COILS = 12
PROFILE_P = 2.0 # dome profile exponent: higher is straighter-sided

BOARD_R = 0.29  # round board under the skep
BOARD_T = 0.035
STAND_H = 0.32  # top of the stake below the board
STAKE_R = 0.05
BATTEN = (0.5, 0.06, 0.04)  # cleats under the board
BRACE_L = 0.2  # short braces at the stake's foot

DOOR_W = 0.14 # entrance width at the base (gap in the bottom coil)

STRAW = (0.42, 0.29, 0.1)  # linear RGB, golden-brown
STRAW_LIGHT = (0.47, 0.34, 0.13)
STRAW_OLD = (0.32, 0.23, 0.1)
STRAW_CORE = (0.12, 0.08, 0.035)  # shadowed straw seen between the coils
DARK = (0.045, 0.035, 0.025)  # the entrance hole
WOOD = (0.2, 0.115, 0.058)
WOOD_OLD = (0.16, 0.11, 0.075)


def outer_r(h):
    """Outer skep radius at height h above the board."""
    t = min(max(h / SKEP_H, 0.0), 1.0)
    return SKEP_R * (1 - t**PROFILE_P) ** 0.5


@prop
def beehive_skep():
    rnd = random.Random(7)
    straws = [
        material("beehive_skep_straw", STRAW, vary=0.3, scale=40),
        material("beehive_skep_straw_light", STRAW_LIGHT, vary=0.3, scale=40),
        material("beehive_skep_straw_old", STRAW_OLD, vary=0.3, scale=35),
    ]
    core = material("beehive_skep_core", STRAW_CORE, vary=0.2, scale=10)
    dark = material("beehive_skep_entrance", DARK, vary=0.1, scale=10, crevice=0.8)
    wood = material("beehive_skep_board", WOOD, vary=0.25, scale=12)
    wood_old = material("beehive_skep_stake", WOOD_OLD, vary=0.3, scale=10)

    # The stand: a stout stake with three short braces at its foot.
    cylinder("stake", STAKE_R, STAND_H - BATTEN[2], (0, 0, 0), wood_old, r_top=STAKE_R * 0.9, segments=10, bevel=0.008)
    for i in range(3):
        a = math.radians(30 + 120 * i + rnd.uniform(-8, 8))
        tilt = 55
        d = STAKE_R + BRACE_L * 0.5 * math.sin(math.radians(tilt)) - 0.01
        zc = BRACE_L * 0.5 * math.cos(math.radians(tilt)) + 0.012
        box(
            f"brace_{i}", (0.035, 0.035, BRACE_L), (d * math.cos(a), d * math.sin(a), zc), wood_old,
            rot=(0, tilt, math.degrees(a) + 180), bevel=0.006,
        )

    # Two crossed cleats and the round board.
    zb = STAND_H - BATTEN[2] / 2
    box("cleat_0", BATTEN, (0, 0, zb), wood_old, rot=(0, 0, 45 + rnd.uniform(-3, 3)), bevel=0.006)
    box("cleat_1", BATTEN, (0, 0, zb - 0.001), wood_old, rot=(0, 0, -45 + rnd.uniform(-3, 3)), bevel=0.006)
    cylinder("board", BOARD_R, BOARD_T, (0, 0, STAND_H), wood, segments=28, bevel=0.008)

    z0 = STAND_H + BOARD_T  # the skep stands here

    # A closed dark core behind the coils, so the grooves between them read shadowed.
    for i in range(COILS):
        h = COIL_T + i * COIL_PITCH
        r = outer_r(h + COIL_PITCH / 2) - COIL_T * 1.3
        cylinder(f"core_{i}", max(r, 0.03), COIL_PITCH + 0.004, (0, 0, z0 + i * COIL_PITCH), core, segments=16, bevel=0)

    # The bottom coil: rope pieces around the ring, leaving a gap at the front for the entrance.
    rc = outer_r(COIL_T) - COIL_T
    zc = z0 + COIL_T
    pieces = 24
    da = 2 * math.pi / pieces
    seg_len = 2 * rc * math.sin(da / 2) * 1.12
    for k in range(pieces):
        a = -math.pi / 2 + da * (k + 0.5)
        mid = da * (k + 0.5)
        if min(mid, 2 * math.pi - mid) * rc < DOOR_W / 2:
            continue
        tx, ty = -math.sin(a), math.cos(a)
        cx, cy = rc * math.cos(a), rc * math.sin(a)
        cylinder(
            f"coil_0_{k}", COIL_T, seg_len, (cx - tx * seg_len / 2, cy - ty * seg_len / 2, zc - 0.0005),
            straws[rnd.choice((0, 0, 1, 2))], segments=8, rot=(90, 0, math.degrees(a) + 180), bevel=0,
        )
    # The dark entrance in the gap.
    box("entrance", (DOOR_W + 0.01, 0.06, COIL_T * 1.9), (0, -rc + 0.012, z0 + COIL_T * 0.95), dark, bevel=0.004)

    # The coiled rope dome, one ring per coil, each slightly tilted like a spiral.
    for i in range(1, COILS):
        h = COIL_T + i * COIL_PITCH
        R = outer_r(h) - COIL_T
        torus(
            f"coil_{i}", R * rnd.uniform(0.99, 1.01), COIL_T, (0, 0, z0 + h), straws[rnd.choice((0, 0, 1, 2))],
            rot=(rnd.uniform(-1.2, 1.2), rnd.uniform(-1.2, 1.2), rnd.uniform(0, 360)), major=24, minor=7,
        )

    # The crown: a small knot of straw closing the top.
    top_h = COIL_T + (COILS - 1) * COIL_PITCH
    cap_r = outer_r(top_h) - COIL_T * 0.5
    blob("crown", cap_r, (0, 0, z0 + top_h + 0.005), straws[0], squash=(1, 1, 0.45), subdiv=2, seed=3, jitter=0.06)
