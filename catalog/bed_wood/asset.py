"""A simple village bed: a low plank frame on four square posts, a tall plank headboard at -x and a lower footboard at
+x, a straw mattress under an off-white linen sheet, a pillow and a blue-grey wool blanket folded back over the lower
half (generated by npm run new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder

TILE = 1.5  # metres per tile
# Overall size: 2.0 m long along x, 1.0 m wide (footprint 2x1 tiles = 3.0 x 1.5 m, height 0.6 tile = 0.9 m).
L = 2.0  # frame length (x)
W = 1.0  # frame width (y)
POST = 0.08  # square corner posts (the four short legs run up into them)
HEAD_H = 0.88  # headboard post top (~0.9 m)
FOOT_H = 0.58  # footboard post top
CAP_H = 0.03  # caps on the post tops
RAIL_Z0, RAIL_H, RAIL_T = 0.2, 0.15, 0.05  # side and end rails: bottom, height, thickness
DECK_T = 0.03  # boards across the rails that carry the mattress
HEAD_PLANKS, FOOT_PLANKS = 3, 2
BOARD_Z0 = RAIL_Z0 + RAIL_H + 0.02  # bottom of the head/foot board planks
BOARD_T = 0.035
PLANK_GAP = 0.01
# Bedding.
MAT_H = 0.15  # straw mattress
SHEET_H = 0.1  # linen sheet: the top part of the mattress
SHEET_OVER = 0.012  # sheet hangs a touch past the mattress
BLANKET_X0 = 0.0  # blanket covers x from here to the foot
BLANKET_T = 0.035  # how far the blanket stands proud of the sheet
ROLL_R = 0.045  # folded-back edge of the blanket
PILLOW = (0.34, 0.62, 0.11)  # a stuffed linen pillow (x, y, z)

OAK = (0.2, 0.12, 0.062)  # linear RGB
OAK_OLD = (0.16, 0.098, 0.052)
STRAW = (0.42, 0.32, 0.14)
LINEN = (0.5, 0.47, 0.4)
LINEN_PILLOW = (0.46, 0.43, 0.36)
WOOL = (0.1, 0.13, 0.19)


@prop
def bed_wood():
    rnd = random.Random(11)
    oak = material("bed_frame", OAK, vary=0.25, scale=14)
    old = material("bed_frame_old", OAK_OLD, vary=0.3, scale=11)
    straw = material("bed_straw", STRAW, vary=0.35, scale=40)
    linen = material("bed_linen", LINEN, vary=0.08, scale=8, crevice=0.7)
    pillow = material("bed_pillow", LINEN_PILLOW, vary=0.1, scale=10, crevice=0.7)
    wool = material("bed_wool", WOOL, vary=0.15, scale=30, crevice=0.7)

    hx, hy = L / 2 - POST / 2, W / 2 - POST / 2  # post centres
    inner_x = L / 2 - POST  # inner faces of the posts
    inner_y = W / 2 - POST

    # Four corner posts: tall ones at the head (-x), lower ones at the foot (+x), each with a cap.
    for sx, top in ((-1, HEAD_H), (1, FOOT_H)):
        for sy in (-1, 1):
            h = top - CAP_H
            mat = old if rnd.random() < 0.35 else oak
            box(f"post_{sx}_{sy}", (POST, POST, h), (sx * hx, sy * hy, h / 2), mat,
                rot=(0, 0, rnd.uniform(-1.5, 1.5)), bevel=0.012)
            box(f"cap_{sx}_{sy}", (POST + 0.02, POST + 0.02, CAP_H), (sx * hx, sy * hy, top - CAP_H / 2), oak,
                bevel=0.008)

    # Side rails along x and end rails across y, between the posts.
    rz = RAIL_Z0 + RAIL_H / 2
    for i, sy in enumerate((-1, 1)):
        box(f"side_rail_{i}", (2 * inner_x + 0.01, RAIL_T, RAIL_H), (0, sy * (W / 2 - RAIL_T / 2 - 0.012), rz),
            oak if i else old, bevel=0.01)
    for i, sx in enumerate((-1, 1)):
        box(f"end_rail_{i}", (RAIL_T, 2 * inner_y + 0.01, RAIL_H), (sx * (L / 2 - RAIL_T / 2 - 0.012), 0, rz),
            oak, bevel=0.01)
    deck_top = RAIL_Z0 + RAIL_H - 0.02
    box("deck", (2 * inner_x - 0.02, 2 * inner_y - 0.02, DECK_T), (0, 0, deck_top - DECK_T / 2), old, bevel=0.006)

    # Headboard and footboard: horizontal planks between the posts, each a little uneven.
    def boards(tag, sx, n, top):
        span = top - CAP_H - 0.03 - BOARD_Z0
        ph = (span - PLANK_GAP * (n - 1)) / n
        for i in range(n):
            z = BOARD_Z0 + ph / 2 + i * (ph + PLANK_GAP)
            mat = old if (i + n) % 3 == 0 else oak
            box(f"{tag}_plank_{i}", (BOARD_T, 2 * inner_y + 0.01, ph - rnd.uniform(0, 0.008)),
                (sx * hx + rnd.uniform(-0.004, 0.004), 0, z), mat, rot=(rnd.uniform(-0.6, 0.6), 0, 0), bevel=0.009)

    boards("head", -1, HEAD_PLANKS, HEAD_H)
    boards("foot", 1, FOOT_PLANKS, FOOT_H)

    # The straw mattress, its top wrapped in the linen sheet.
    mx = 2 * inner_x - 0.03  # mattress length and width, inside the boards
    my = 2 * inner_y + 0.04
    m_top = deck_top + MAT_H
    box("mattress", (mx, my, MAT_H), (0, 0, deck_top + MAT_H / 2), straw, bevel=0.035)
    sx_len, sy_len = mx + 2 * SHEET_OVER - 0.02, my + 2 * SHEET_OVER
    box("sheet", (sx_len, sy_len, SHEET_H), (-0.01, 0, m_top + 0.006 - SHEET_H / 2), linen, bevel=0.03)
    s_top = m_top + 0.006

    # The pillow at the head.
    px, py, pz = PILLOW
    box("pillow", PILLOW, (-inner_x + 0.04 + px / 2, rnd.uniform(-0.03, 0.03), s_top + pz / 2 - 0.01), pillow,
        rot=(0, rnd.uniform(-4, -2), rnd.uniform(-4, 4)), bevel=0.045)

    # The wool blanket over the lower half, its edge folded back into a roll.
    b_len = mx / 2 + SHEET_OVER + 0.01 - BLANKET_X0
    b_end = BLANKET_X0 + b_len
    box("blanket", (b_len, sy_len + 0.02, SHEET_H + 0.03), (BLANKET_X0 + b_len / 2 - 0.005, 0,
        s_top + BLANKET_T - (SHEET_H + 0.03) / 2), wool, bevel=0.03)
    cylinder("blanket_fold", ROLL_R, sy_len + 0.015, (BLANKET_X0, -(sy_len + 0.015) / 2, s_top + BLANKET_T - ROLL_R + 0.012),
             wool, segments=12, rot=(-90, 0, 0), bevel=0.01)
    assert b_end < L / 2
