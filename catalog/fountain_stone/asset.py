"""The village square's stone fountain: an octagonal dressed-stone basin of still water around a central pillar that
carries a smaller upper bowl (generated by npm run new)."""
import math
import random

from propsmith import anchor, prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder, torus

TILE = 1.5  # metres per tile
# Footprint 2x2 tiles = 3 x 3 m, height 1.4 tiles = 2.1 m.
BASIN_R = 1.3  # corner radius of the octagonal rim: 2.6 m across
PLINTH_R = 1.4  # corner radius of the low step the rim stands on
PLINTH_H = 0.1
RIM_H = 0.6  # top of the coping stones
RIM_T = 0.26  # wall thickness
CAP_H = 0.1
WATER_Z = 0.47  # still water surface in the basin
PILLAR_R = 0.15
PILLAR_TOP = 1.32
BOWL_Z = 1.6  # rim of the upper bowl
BOWL_R = 0.55
SPOUT_TOP = 1.92

STONE = (0.30, 0.265, 0.215)
STONE_OLD = (0.235, 0.215, 0.18)
WATER = (0.03, 0.065, 0.07)
MOSS = (0.10, 0.13, 0.045)

SIDE = math.tan(math.radians(22.5))  # half side length per unit apothem


@prop
def fountain_stone():
    rnd = random.Random(11)
    stone = material("fountain_stone", STONE, vary=0.28, scale=9)
    old = material("fountain_stone_old", STONE_OLD, vary=0.3, scale=11)
    water = material("fountain_water", WATER, rough=0.05, vary=0.08, crevice=0)
    moss = material("fountain_moss", MOSS, vary=0.35, scale=18)

    # Low octagonal step under everything (flats facing the axes).
    cylinder("plinth", PLINTH_R, PLINTH_H, (0, 0, 0), old, segments=8, rot=(0, 0, 22.5), bevel=0.02)

    # Rim: per side two dressed blocks and a coping stone, mitred by overlap at the corners.
    apo = BASIN_R * math.cos(math.radians(22.5))
    mid = apo - RIM_T / 2
    wall_h = RIM_H - PLINTH_H - CAP_H
    side_len = 2 * apo * SIDE
    for k in range(8):
        a = math.radians(45 * k)
        c, s = math.cos(a), math.sin(a)
        tx, ty = -s, c  # along the side
        for b in (-1, 1):
            length = side_len / 2 - 0.012
            off = b * side_len / 4 + rnd.uniform(-0.01, 0.01)
            box(
                f"rim_block_{k}_{b}",
                (RIM_T * rnd.uniform(0.96, 1.0), length * rnd.uniform(0.97, 1.0), wall_h * rnd.uniform(0.97, 1.0)),
                (mid * c + off * tx, mid * s + off * ty, PLINTH_H + wall_h / 2),
                old if rnd.random() < 0.3 else stone,
                rot=(0, 0, 45 * k + rnd.uniform(-1.2, 1.2)),
                bevel=0.02,
            )
        box(
            f"coping_{k}",
            (RIM_T + 0.06, side_len + 0.03, CAP_H),
            (mid * c, mid * s, RIM_H - CAP_H / 2),
            stone if k % 3 else old,
            rot=(rnd.uniform(-0.6, 0.6), rnd.uniform(-0.6, 0.6), 45 * k),
            bevel=0.022,
        )

    # Still water filling the basin up to just under the coping.
    inner = (apo - RIM_T + 0.03) / math.cos(math.radians(22.5))
    cylinder("water", inner, WATER_Z - PLINTH_H, (0, 0, PLINTH_H), water, segments=8, rot=(0, 0, 22.5), bevel=0)

    # Central pillar: an octagonal pedestal out of the water, a shaft, a capital and the upper bowl.
    cylinder("pedestal", 0.3, 0.26, (0, 0, WATER_Z - 0.06), old, r_top=0.24, segments=8, rot=(0, 0, 22.5), bevel=0.015)
    cylinder("shaft", PILLAR_R, PILLAR_TOP - WATER_Z, (0, 0, WATER_Z), stone, r_top=PILLAR_R * 0.85, segments=12, bevel=0.01)
    torus("shaft_ring", PILLAR_R + 0.005, 0.03, (0, 0, 0.92), stone, major=12, minor=6)
    cylinder("capital", 0.17, 0.08, (0, 0, PILLAR_TOP - 0.02), stone, r_top=0.25, segments=12, bevel=0.01)
    bowl_h = BOWL_Z - PILLAR_TOP - 0.11  # the bowl's solid top sits under its water
    cylinder("bowl", 0.25, bowl_h, (0, 0, PILLAR_TOP + 0.06), stone, r_top=BOWL_R, segments=16, bevel=0.012)
    torus("bowl_lip", BOWL_R - 0.01, 0.035, (0, 0, BOWL_Z - 0.005), stone, major=24, minor=8)
    cylinder("bowl_water", BOWL_R - 0.02, 0.04, (0, 0, BOWL_Z - 0.06), water, segments=16, bevel=0)
    # Small spout column and knob in the middle of the bowl.
    cylinder("spout", 0.07, SPOUT_TOP - BOWL_Z - 0.06, (0, 0, BOWL_Z - 0.02), old, r_top=0.055, segments=8, bevel=0.008)
    blob("spout_knob", 0.08, (0, 0, SPOUT_TOP - 0.07), stone, squash=(1, 1, 0.85), subdiv=1, seed=3, jitter=0.06)

    # A little moss at the foot of the rim and around the step.
    for i in range(14):
        a = math.radians(rnd.uniform(0, 360))
        on_step = i % 2 == 0
        r = (apo + 0.05) if on_step else (PLINTH_R * math.cos(math.radians(22.5)) + 0.02)
        z = PLINTH_H + 0.03 if on_step else 0.055
        blob(
            f"moss_{i}",
            rnd.uniform(0.06, 0.1),
            (r * math.cos(a), r * math.sin(a), z),
            moss,
            squash=(1.4, 1.2, 0.5),
            subdiv=1,
            seed=20 + i,
            jitter=0.15,
        )

    # The still water inside the rim, and the upper bowl's lip it spills over (the bake falls streams between them).
    inner = apo - RIM_T
    anchor("water:basin", (0, 0, WATER_Z), size=(inner, inner, inner))
    anchor("water:spout", (0, 0, BOWL_Z), size=(BOWL_R, BOWL_R, BOWL_R))
