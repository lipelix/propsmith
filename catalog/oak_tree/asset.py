"""A broad old oak tree about 7 m high and 6 m across: a thick gnarled trunk with deep bark splitting into a few heavy
crooked limbs, and a wide rounded crown of clumped dark-green leaf masses with gaps between them (generated by
npm run new). The limbs are two crooked tapered segments each, reaching into a lower ring of leaf masses; an upper ring
and a top mass close the dome, each mass a dark core lump with a smaller lit lump on its upper side."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, cylinder

# Overall dimensions (metres), from the description.
H = 7.0  # total height, top of the crown
SPREAD = 6.0  # crown width
TRUNK_R = 0.5  # trunk radius at the ground
TRUNK_TOP_R = 0.36  # trunk radius where the limbs split off
TRUNK_H = 2.3  # height of the split
ROOT_N = 6  # buttress roots at the foot
ROOT_L = 0.75
ROOT_R = 0.24
LIMBS = 5  # heavy limbs from the split
LIMB_R = 0.22  # limb radius where it leaves the trunk
LIMB_END_R = 0.08

# Crown: rings of leaf masses on a squashed dome.
LOW_N, LOW_DIST, LOW_Z, LOW_R = 7, 1.95, 4.15, 1.0  # count, distance from axis, centre height, mass radius
HIGH_N, HIGH_DIST, HIGH_Z, HIGH_R = 5, 1.15, 5.45, 0.95
TOP_Z, TOP_R = 6.25, 0.8
SQUASH_Z = 0.78  # leaf masses are flatter than tall

BARK = (0.11, 0.075, 0.05)  # linear RGB, grey-brown old bark
BARK_DARK = (0.075, 0.052, 0.036)
LEAF_DARK = (0.028, 0.05, 0.022)  # shadowed core of a mass
LEAF = (0.045, 0.078, 0.03)  # dark oak green
LEAF_LIT = (0.075, 0.11, 0.04)  # sunlit tops


def _mats():
    return {
        "bark": material("oak_tree_bark", BARK, rough=0.95, vary=0.45, scale=9, crevice=0.85),
        "bark_dark": material("oak_tree_bark_dark", BARK_DARK, rough=0.95, vary=0.4, scale=12, crevice=0.85),
        "core": material("oak_tree_leaves_core", LEAF_DARK, rough=0.9, vary=0.3, scale=5, crevice=0.75),
        "leaf": material("oak_tree_leaves", LEAF, rough=0.85, vary=0.35, scale=7, crevice=0.6),
        "lit": material("oak_tree_leaves_lit", LEAF_LIT, rough=0.8, vary=0.3, scale=7, crevice=0.5),
    }


def _roughen(obj, rnd, amount, ridges=0):
    """Seeded radial jitter of the vertices; with `ridges`, alternate vertices pushed in: deep bark furrows."""
    for i, v in enumerate(obj.data.vertices):
        r = math.hypot(v.co.x, v.co.y)
        if r > 1e-4:
            k = 1 + rnd.uniform(-amount, amount) - (ridges if i % 2 else 0)
            v.co.x *= k
            v.co.y *= k


def _branch(name, a, b, r0, r1, mat, rnd, segments=8):
    """A tapered cylinder from point `a` to point `b`."""
    d = [b[i] - a[i] for i in range(3)]
    length = math.sqrt(sum(c * c for c in d))
    pitch = math.degrees(math.acos(max(-1.0, min(1.0, d[2] / length))))
    yaw = math.degrees(math.atan2(d[1], d[0]))
    c = cylinder(name, r0, length, a, mat, r_top=r1, segments=segments, rot=(0, pitch, yaw), bevel=0)
    _roughen(c, rnd, 0.08)
    return c


def _trunk(mats, rnd):
    t = cylinder("oak_tree_trunk", TRUNK_R, TRUNK_H + 0.3, (0, 0, 0), mats["bark"], r_top=TRUNK_TOP_R,
                 segments=16, bevel=0)
    # Gnarl: furrows, plus a lean that wanders with height.
    _roughen(t, rnd, 0.06, ridges=0.1)
    lean = (rnd.uniform(-0.12, 0.12), rnd.uniform(-0.12, 0.12))
    for v in t.data.vertices:
        u = v.co.z / (TRUNK_H + 0.3)
        v.co.x += lean[0] * math.sin(u * math.pi)
        v.co.y += lean[1] * math.sin(u * math.pi * 1.3)
    # Burls on the trunk.
    for i in range(3):
        a = rnd.uniform(0, 2 * math.pi)
        z = rnd.uniform(0.7, 1.9)
        r = TRUNK_R * 0.9
        blob(f"oak_tree_burl_{i}", 0.17, (r * math.cos(a), r * math.sin(a), z), mats["bark_dark"],
             squash=(1, 1, 1.4), subdiv=1, seed=40 + i)
    # Buttress roots sloping down to the ground.
    for i in range(ROOT_N):
        yaw = 360 * i / ROOT_N + rnd.uniform(-18, 18)
        tilt = rnd.uniform(100, 108)
        length = ROOT_L * rnd.uniform(0.8, 1.15)
        r, r_top = ROOT_R * rnd.uniform(0.85, 1.1), 0.06
        dz = math.cos(math.radians(tilt))
        flat = math.sqrt(1 - dz * dz)
        z0 = max(0.003 + 1.1 * r_top * flat - length * dz, 0.003 + 1.1 * r * flat)
        root = cylinder(f"oak_tree_root_{i}", r, length, (0, 0, z0), mats["bark_dark" if i % 2 else "bark"],
                        r_top=r_top, segments=8, rot=(tilt, 0, yaw), bevel=0)
        _roughen(root, rnd, 0.1)


def _limbs(mats, rnd, targets):
    """Heavy crooked limbs: two segments each, from the split to the underside of a low leaf mass."""
    top = (0.0, 0.0, TRUNK_H)
    for i, (tx, ty, tz) in enumerate(targets):
        start = (top[0] + 0.12 * tx / LOW_DIST, top[1] + 0.12 * ty / LOW_DIST, top[2] - 0.15)
        # Elbow: partway out, kinked sideways and up.
        side = rnd.uniform(-0.35, 0.35)
        nx, ny = -ty / LOW_DIST, tx / LOW_DIST
        f = rnd.uniform(0.45, 0.6)
        elbow = (tx * f + side * nx, ty * f + side * ny, TRUNK_H + rnd.uniform(0.45, 0.75))
        end = (tx * 0.85, ty * 0.85, tz - 0.35)
        r0 = LIMB_R * rnd.uniform(0.85, 1.1)
        rm = r0 * 0.7
        _branch(f"oak_tree_limb_{i}_a", start, elbow, r0, rm, mats["bark"], rnd, segments=10)
        _branch(f"oak_tree_limb_{i}_b", elbow, end, rm * 0.95, LIMB_END_R, mats["bark"], rnd)
        blob(f"oak_tree_elbow_{i}", rm * 1.05, elbow, mats["bark"], subdiv=1, seed=60 + i, jitter=0.08)
    # A central leader up to the high ring.
    _branch("oak_tree_leader_a", (0, 0, TRUNK_H - 0.2), (0.15, -0.1, 3.9), 0.2, 0.13, mats["bark"], rnd, segments=10)
    _branch("oak_tree_leader_b", (0.15, -0.1, 3.9), (-0.1, 0.05, 5.1), 0.13, 0.06, mats["bark"], rnd)


def _mass(name, at, r, mats, rnd, seed):
    """One leaf mass: a dark lumpy core with a lit lump on its upper outer side and a mid-green lump beside it."""
    x, y, z = at
    blob(f"{name}_core", r, at, mats["core"], squash=(1, 1, SQUASH_Z), subdiv=2, seed=seed, jitter=0.14)
    d = math.hypot(x, y) or 1.0
    ox, oy = x / d, y / d
    a = rnd.uniform(-0.6, 0.6)
    cx = ox * math.cos(a) - oy * math.sin(a)
    cy = ox * math.sin(a) + oy * math.cos(a)
    blob(f"{name}_lit", r * 0.62, (x + cx * r * 0.3, y + cy * r * 0.3, z + r * 0.38), mats["lit"],
         squash=(1, 1, 0.75), subdiv=1, seed=seed + 1, jitter=0.15)
    blob(f"{name}_leaf", r * 0.58, (x - cy * r * 0.45, y + cx * r * 0.45, z + r * 0.05), mats["leaf"],
         squash=(1, 1, 0.8), subdiv=1, seed=seed + 2, jitter=0.15)


@prop
def oak_tree():
    rnd = random.Random(11)
    mats = _mats()
    _trunk(mats, rnd)

    turn = rnd.uniform(0, 360)
    low = []
    for i in range(LOW_N):
        a = math.radians(turn + 360 * i / LOW_N + rnd.uniform(-10, 10))
        d = LOW_DIST * rnd.uniform(0.92, 1.03)
        low.append((d * math.cos(a), d * math.sin(a), LOW_Z + rnd.uniform(-0.25, 0.2)))
    for i, p in enumerate(low):
        _mass(f"oak_tree_low_{i}", p, LOW_R * rnd.uniform(0.88, 1.0), mats, rnd, 100 + 5 * i)
    _limbs(mats, rnd, low[::2][:LIMBS - 1] + [low[-2]])

    for i in range(HIGH_N):
        a = math.radians(turn + 30 + 360 * i / HIGH_N + rnd.uniform(-12, 12))
        d = HIGH_DIST * rnd.uniform(0.9, 1.05)
        p = (d * math.cos(a), d * math.sin(a), HIGH_Z + rnd.uniform(-0.2, 0.15))
        _mass(f"oak_tree_high_{i}", p, HIGH_R * rnd.uniform(0.88, 1.0), mats, rnd, 200 + 5 * i)
    _mass("oak_tree_top", (0.1, 0.0, TOP_Z), TOP_R, mats, rnd, 300)
