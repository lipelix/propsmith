"""A cluster of three large weathered shore boulders, the biggest about 1.2 m high, rounded grey-brown stone with
darker bases and a few small pebbles around them (generated by npm run new).

Each boulder is a lumpy icosphere cut flat where it rests on the ground; the faces of its lower part take a darker,
damp-looking stone material, so the base reads darker than the sun-bleached top."""
import math
import random

import bpy
from mathutils import Vector

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob

# Overall dimensions (metres), from the description.
BIG_R, BIG_H = 0.62, 1.2  # the biggest boulder: half-width and height
MID_R, MID_H = 0.45, 0.78  # the second boulder, beside it
LOW_R, LOW_H = 0.34, 0.48  # the smallest, in front
LUMPS = 5  # broad smooth waves shaping each boulder
FLAT = 0.12 # share of a boulder's height cut flat where it rests on the ground
DARK_BAND = 0.3  # share of a boulder's height (from the ground) that takes the darker base stone
PEBBLE_R = (0.045, 0.085)  # metres, half-width range of a pebble
PEBBLE_FLAT = (0.45, 0.65)  # height / width of a pebble
PEBBLES = 9

STONE = (0.3, 0.28, 0.24)  # linear RGB, weathered grey-brown
STONE_PALE = (0.36, 0.34, 0.3)
STONE_DARK = (0.15, 0.135, 0.11)  # damp, darker base
PEBBLE_COLOURS = [(0.3, 0.27, 0.22), (0.22, 0.2, 0.17), (0.38, 0.35, 0.3)]


def _boulder(name, r, h, xy, mat, dark, seed, stretch=1.0, yaw=0.0, tilt=(0.0, 0.0)):
    """A rounded boulder `r` half-wide and `h` high: a lumpy blob, base cut flat, turned and leant, standing on z = 0,
    its lower `DARK_BAND` of faces in the `dark` material."""
    rz = h / (2 * (1 - FLAT / 2))
    obj = blob(name, r, (xy[0], xy[1], 0), mat, squash=(stretch, 1 / stretch, rz / r), subdiv=4, seed=seed,
               jitter=0.015)
    verts = obj.data.vertices
    # Broad weathered lumps: a few smooth waves over the surface direction, not per-vertex noise.
    lrnd = random.Random(seed + 200)
    waves = []
    for _ in range(LUMPS):
        d = Vector((lrnd.gauss(0, 1), lrnd.gauss(0, 1), lrnd.gauss(0, 1))).normalized()
        waves.append((d, lrnd.uniform(1.6, 3.2), lrnd.uniform(0, 2 * math.pi), lrnd.uniform(0.03, 0.06)))
    for v in verts:
        u = Vector((v.co.x / stretch, v.co.y * stretch, v.co.z * r / rz)).normalized()
        v.co *= 1 + sum(a * math.sin(f * d.dot(u) * math.pi + ph) for d, f, ph, a in waves)
    low = min(v.co.z for v in verts)
    cut = low + FLAT * (max(v.co.z for v in verts) - low)
    for v in verts:
        v.co.z = max(v.co.z, cut)
    obj.rotation_euler = (math.radians(tilt[0]), math.radians(tilt[1]), math.radians(yaw))
    bpy.context.view_layer.update()
    world = [obj.matrix_world @ v.co for v in verts]
    lowest = min(w.z for w in world)
    obj.location.z -= lowest
    top = max(w.z for w in world) - lowest
    obj.data.materials.append(dark)
    rnd = random.Random(seed + 100)
    for p in obj.data.polygons:
        z = sum(world[i].z for i in p.vertices) / len(p.vertices) - lowest
        if z < top * DARK_BAND * rnd.uniform(0.8, 1.2):
            p.material_index = 1
    bpy.context.view_layer.update()
    return obj


@prop
def boulders_shore():
    rnd = random.Random(7)
    stone = material("boulders_shore_stone", STONE, rough=0.9, vary=0.3, scale=5, crevice=0.75)
    pale = material("boulders_shore_stone_pale", STONE_PALE, rough=0.9, vary=0.3, scale=5, crevice=0.75)
    dark = material("boulders_shore_stone_dark", STONE_DARK, rough=0.75, vary=0.3, scale=7, crevice=0.7)

    rocks = [
        (BIG_R, -0.28, 0.12, 1.1),
        (MID_R, 0.5, 0.2, 1.0),
        (LOW_R, 0.32, -0.42, 1.0),
    ]
    _boulder("boulders_shore_big", BIG_R, BIG_H, (-0.28, 0.12), stone, dark, 11, stretch=1.1, yaw=15, tilt=(3, -4))
    _boulder("boulders_shore_mid", MID_R, MID_H, (0.5, 0.2), pale, dark, 23, stretch=1.12, yaw=-30, tilt=(-4, 8))
    _boulder("boulders_shore_low", LOW_R, LOW_H, (0.32, -0.42), stone, dark, 37, stretch=1.2, yaw=40, tilt=(5, 3))

    pmats = [material(f"boulders_shore_pebble_{i}", c, rough=0.85, vary=0.3, scale=40, crevice=0.6)
             for i, c in enumerate(PEBBLE_COLOURS)]
    placed = [(x, y, r * s * 1.05) for r, x, y, s in rocks]
    for i in range(PEBBLES):
        r = rnd.uniform(*PEBBLE_R)
        for _ in range(200):
            x, y = rnd.uniform(-0.92, 0.92), rnd.uniform(-0.68, 0.68)
            near = min(math.hypot(x - px, y - py) - pr for px, py, pr in placed[:3])
            if near < 0.22 and all(math.hypot(x - px, y - py) > r + pr + 0.02 for px, py, pr in placed):
                break
        placed.append((x, y, r))
        h = r * rnd.uniform(*PEBBLE_FLAT)
        stretch = rnd.uniform(1.0, 1.3)
        blob(f"boulders_shore_pebble_{i}", r, (x, y, h), rnd.choice(pmats), squash=(stretch, 1 / stretch, h / r),
             subdiv=2, seed=50 + i, jitter=0.1)
