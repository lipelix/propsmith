"""A sturdy inn trestle table: thick oak planks with slight gaps on four square legs with stretchers, one pewter mug on
top (generated by npm run new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

TILE = 1.5  # metres per tile
# Overall size: 1.35 m long along x, 0.8 m wide, top at 0.75 m (footprint 1x1 tile, height 0.6 tile = 0.9 m).
L = 1.35  # top length (x)
D = 0.8  # top width (y)
H = 0.75  # top surface height
TOP_T = 0.06  # thick oak planks
PLANKS = 4
GAP = 0.008  # gap between planks
LEG = 0.085  # square leg section
LEG_X = L / 2 - 0.11  # leg centres
LEG_Y = D / 2 - 0.09
APRON_H, APRON_T = 0.09, 0.04  # rails under the top, between the legs
RAIL_Z, RAIL_H, RAIL_T = 0.14, 0.06, 0.05  # low end stretchers across y
STR_Z, STR_H, STR_T = 0.2, 0.06, 0.055  # long middle stretcher along x
CLEAT_H, CLEAT_W = 0.04, 0.07  # battens under the planks at each end
# The pewter mug.
MUG_AT = (0.3, -0.14)
MUG_R, MUG_H = 0.05, 0.12  # a tankard
HANDLE_R, HANDLE_T = 0.036, 0.01

OAK = (0.22, 0.135, 0.07)  # linear RGB
OAK_OLD = (0.17, 0.105, 0.058)
OAK_TOP = (0.25, 0.16, 0.085)
PEWTER = (0.36, 0.36, 0.37)
ALE = (0.12, 0.06, 0.02)


@prop
def table_wood():
    rnd = random.Random(7)
    top = material("table_top", OAK_TOP, vary=0.28, scale=12)
    top_old = material("table_top_old", OAK_OLD, vary=0.3, scale=10)
    oak = material("table_frame", OAK, vary=0.25, scale=14)
    old = material("table_frame_old", OAK_OLD, vary=0.3, scale=11)
    pewter = material("table_pewter", PEWTER, rough=0.5, vary=0.12, scale=30, metal=0.4)
    ale = material("table_ale", ALE, rough=0.3, vary=0.1, scale=20)

    # The top: planks along x with slight gaps, each a touch uneven.
    pw = (D - GAP * (PLANKS - 1)) / PLANKS
    for i in range(PLANKS):
        y = -D / 2 + pw / 2 + i * (pw + GAP)
        mat = top_old if i == 1 else top
        box(f"plank_{i}", (L - rnd.uniform(0, 0.02), pw - 0.002, TOP_T - rnd.uniform(0, 0.004)),
            (rnd.uniform(-0.006, 0.006), y, H - TOP_T / 2), mat,
            rot=(0, 0, rnd.uniform(-0.25, 0.25)), bevel=0.012)
    under = H - TOP_T
    # Battens across the planks near each end.
    for i, s in enumerate((-1, 1)):
        box(f"cleat_{i}", (CLEAT_W, D - 0.06, CLEAT_H), (s * (LEG_X + 0.0), 0, under - CLEAT_H / 2), old,
            bevel=0.008)

    # Four square legs.
    leg_h = under - CLEAT_H
    for sx in (-1, 1):
        for sy in (-1, 1):
            mat = old if rnd.random() < 0.35 else oak
            box(f"leg_{sx}_{sy}", (LEG, LEG, leg_h), (sx * LEG_X, sy * LEG_Y, leg_h / 2), mat,
                rot=(0, 0, rnd.uniform(-2, 2)), bevel=0.012)

    # Aprons along x under the top, between the legs.
    for i, sy in enumerate((-1, 1)):
        box(f"apron_{i}", (2 * LEG_X - LEG, APRON_T, APRON_H), (0, sy * LEG_Y, under - CLEAT_H - APRON_H / 2 + 0.01),
            oak, bevel=0.008)

    # Low stretchers across y at each end, a long one along x between them.
    for i, sx in enumerate((-1, 1)):
        box(f"rail_{i}", (RAIL_T, 2 * LEG_Y - LEG + 0.004, RAIL_H), (sx * LEG_X, 0, RAIL_Z), oak, bevel=0.008)
    box("stretcher", (2 * LEG_X - RAIL_T + 0.004, STR_T, STR_H), (0, rnd.uniform(-0.004, 0.004), STR_Z), old,
        rot=(rnd.uniform(-0.6, 0.6), 0, 0), bevel=0.01)

    # A pewter mug of ale with a rim and a loop handle.
    mx, my = MUG_AT
    cylinder("mug", MUG_R, MUG_H, (mx, my, H), pewter, r_top=MUG_R * 0.92, segments=16, bevel=0.004)
    torus("mug_rim", MUG_R * 0.92 - 0.004, 0.005, (mx, my, H + MUG_H), pewter, major=16, minor=6)
    torus("mug_base", MUG_R - 0.002, 0.005, (mx, my, H + 0.005), pewter, major=16, minor=6)
    cylinder("mug_ale", MUG_R * 0.92 - 0.006, 0.003, (mx, my, H + MUG_H), ale, segments=16, bevel=0)
    torus("mug_handle", HANDLE_R, HANDLE_T, (mx + MUG_R + 0.008, my, H + MUG_H * 0.52), pewter,
          rot=(90, 0, 0), major=12, minor=6)
