"""A small cluster of three weathered terracotta herb pots of different sizes: basil-like broad leaves, a fine
thyme-like shrub and one with a few small pale lilac flowers (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, cylinder, torus

TILE = 1.5  # metres per tile
# Footprint 1x1 tile (1.5 x 1.5 m), height 0.4 tile (0.6 m). The cluster itself stays inside about 0.6 m across.
# Pots: (name, x, y, bottom radius, top radius, height). The largest is 0.3 m high.
BIG = ("big", -0.11, 0.08, 0.11, 0.145, 0.30)
MID = ("mid", 0.17, 0.11, 0.085, 0.11, 0.22)
SMALL = ("small", 0.04, -0.17, 0.07, 0.09, 0.16)
RIM_R = 0.018  # metres, rim roll thickness
SOIL_DROP = 0.025  # metres, soil level below the rim

CLAY = (0.36, 0.19, 0.115)  # desaturated terracotta, linear RGB
CLAY_OLD = (0.37, 0.26, 0.2)  # paler, lime-bloomed weathered clay
SOIL = (0.05, 0.032, 0.02)
BASIL = (0.07, 0.16, 0.035)
BASIL_DARK = (0.045, 0.11, 0.025)
THYME = (0.075, 0.1, 0.05)  # grey-green
THYME_DARK = (0.05, 0.07, 0.035)
LEAF = (0.06, 0.12, 0.04)
LILAC = (0.42, 0.34, 0.5)  # pale lilac
STEM = (0.08, 0.11, 0.04)


def _pot(spec, clay, soil):
    """A tapered clay pot with a rolled rim and soil; returns (x, y, soil height, inner radius)."""
    name, x, y, r0, r1, h = spec
    cylinder(f"pot_{name}", r0, h - RIM_R, (x, y, 0), clay, r_top=r1, segments=20, bevel=0.01)
    torus(f"rim_{name}", r1, RIM_R, (x, y, h - RIM_R), clay, major=20, minor=8)
    top = h - SOIL_DROP
    cylinder(f"soil_{name}", r1 - 0.01, 0.01, (x, y, top - 0.01), soil, segments=16, bevel=0)
    return x, y, top, r1 - 0.01


@prop
def herb_pots():
    rnd = random.Random(7)
    clay = material("herb_pots_clay", CLAY, vary=0.25, scale=9, rough=0.92)
    clay_old = material("herb_pots_clay_old", CLAY_OLD, vary=0.3, scale=12, rough=0.95)
    soil = material("herb_pots_soil", SOIL)

    # Basil: a bushy mound of broad, flattened leaf clumps in the big pot, spilling a little over the rim.
    x, y, top, r = _pot(BIG, clay, soil)
    basil = (material("herb_pots_basil", BASIL, vary=0.3, scale=20, rough=0.6),
             material("herb_pots_basil_dark", BASIL_DARK, vary=0.3, scale=20, rough=0.65))
    for i in range(15):
        a = 4 * math.pi * i / 15 + rnd.uniform(-0.3, 0.3)
        if i == 0:
            d, z = 0, top + 0.19
        elif i < 5:
            d, z = rnd.uniform(0.02, 0.06), top + rnd.uniform(0.12, 0.16)
        else:
            d, z = rnd.uniform(0.08, r * 1.15), top + rnd.uniform(0.04, 0.09)
        blob(f"basil_{i}", rnd.uniform(0.055, 0.07), (x + d * math.cos(a), y + d * math.sin(a), z),
             basil[i % 3 == 0], squash=(1.2, 0.9, 0.55), seed=100 + i, subdiv=1, jitter=0.18)

    # Thyme: a dense dome of many tiny grey-green tufts in the middle pot.
    x, y, top, r = _pot(MID, clay_old, soil)
    thyme = (material("herb_pots_thyme", THYME, vary=0.35, scale=40, rough=0.85),
             material("herb_pots_thyme_dark", THYME_DARK, vary=0.35, scale=40, rough=0.85))
    for i in range(34):
        a = rnd.uniform(0, 2 * math.pi)
        d = r * 1.2 * math.sqrt(rnd.uniform(0, 1))
        z = top + 0.03 + 0.12 * (1 - (d / (r * 1.25)) ** 2) + rnd.uniform(-0.01, 0.015)
        blob(f"thyme_{i}", rnd.uniform(0.026, 0.036), (x + d * math.cos(a), y + d * math.sin(a), z),
             thyme[i % 3 == 0], seed=200 + i, subdiv=1, jitter=0.25)

    # Flowering herb: a leafy tuft with a few thin stems ending in small pale lilac flower heads.
    x, y, top, r = _pot(SMALL, clay, soil)
    leaf = material("herb_pots_leaf", LEAF, vary=0.3, scale=25, rough=0.7)
    stem = material("herb_pots_stem", STEM)
    lilac = material("herb_pots_lilac", LILAC, vary=0.15, scale=30, rough=0.6, crevice=0.3)
    for i in range(8):
        a = 2 * math.pi * i / 8 + rnd.uniform(-0.3, 0.3)
        d = rnd.uniform(0.01, r)
        blob(f"tuft_{i}", rnd.uniform(0.038, 0.048),
             (x + d * math.cos(a), y + d * math.sin(a), top + rnd.uniform(0.03, 0.07)),
             leaf, squash=(1, 1, 0.75), seed=300 + i, subdiv=1)
    for i in range(7):
        yaw = 360 / 7 * i + rnd.uniform(-20, 20)
        tilt = rnd.uniform(6, 24)
        length = rnd.uniform(0.15, 0.21)
        base = (x + 0.015 * math.cos(math.radians(yaw)), y + 0.015 * math.sin(math.radians(yaw)), top)
        cylinder(f"stem_{i}", 0.004, length, base, stem, r_top=0.003, segments=5, rot=(tilt, 0, yaw), bevel=0)
        t, w = math.radians(tilt), math.radians(yaw)
        tip = (base[0] + math.sin(t) * math.sin(w) * length, base[1] - math.sin(t) * math.cos(w) * length,
               base[2] + math.cos(t) * length)
        blob(f"flower_{i}", 0.028, tip, lilac, squash=(1, 1, 1.4), seed=400 + i, subdiv=1, jitter=0.2)
