"""A small patch of wildflowers among a few grass blades: thin stems about 0.2 m high with tiny flat blossoms
(generated by npm run new). Variants: white and yellow blossoms, pale violet and white blossoms."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, cylinder

# The patch stays under 0.3 m high and well inside 0.6 m across.
PATCH_R = 0.14  # metres, radius of the circle the stems root in
STEM_H = 0.2  # metres, typical stem height
STEM_R = 0.0035  # metres, stem radius at the base
BLOSSOM_R = 0.026  # metres, radius of a flat blossom
BLOSSOM_T = 0.005  # metres, blossom thickness
EYE_R = 0.008  # metres, radius of the blossom's centre
BLADE_H = 0.17  # metres, grass blade length
BLADE_R = 0.009  # metres, half-width of a blade at its base
N_STEMS = 11
N_BLADES = 12

STEM = (0.12, 0.15, 0.05)  # linear RGB
OLIVE = (0.1, 0.13, 0.035)
OLIVE_DARK = (0.06, 0.08, 0.025)
TIP = (0.33, 0.26, 0.08)
WHITE = (0.5, 0.48, 0.4)  # creamy, never pure white
YELLOW = (0.5, 0.36, 0.06)
VIOLET = (0.3, 0.22, 0.4)
EYE = (0.42, 0.27, 0.04)
ROOT = (0.13, 0.1, 0.05)


def _dir(tilt, yaw):
    """Unit vector of local +z after rot=(tilt, 0, yaw) degrees (XYZ Euler)."""
    t, y = math.radians(tilt), math.radians(yaw)
    return (math.sin(t) * math.sin(y), -math.sin(t) * math.cos(y), math.cos(t))


def _add(p, d, s):
    return (p[0] + d[0] * s, p[1] + d[1] * s, p[2] + d[2] * s)


def _blade(name, base, length, tilt, yaw, low, tip):
    """One tapering grass blade: a green lower segment and a bent dry tip."""
    l1 = length * 0.6
    cylinder(f"{name}_a", BLADE_R, l1, base, low, r_top=BLADE_R * 0.6, segments=4, rot=(tilt, 0, yaw), bevel=0)
    mid = _add(base, _dir(tilt, yaw), l1)
    cylinder(f"{name}_b", BLADE_R * 0.6, length - l1, mid, tip, r_top=0.0008, segments=4,
             rot=(min(tilt + 16, 95), 0, yaw), bevel=0)


def _flower(name, base, height, tilt, yaw, stem, petals, eye, size):
    """A thin stem with a flat blossom facing up (tilted a little with the stem) and a raised centre."""
    cylinder(f"{name}_stem", STEM_R, height, base, stem, r_top=STEM_R * 0.6, segments=4, rot=(tilt, 0, yaw), bevel=0)
    d = _dir(tilt, yaw)
    top = _add(base, d, height)
    face = (tilt * 0.5, 0, yaw)
    cylinder(f"{name}_petals", BLOSSOM_R * size, BLOSSOM_T, top, petals, segments=6, rot=face, bevel=0.002)
    cylinder(f"{name}_eye", EYE_R * size, BLOSSOM_T, _add(top, _dir(*face[::2]), BLOSSOM_T * 0.6), eye,
             r_top=EYE_R * size * 0.6, segments=6, rot=face, bevel=0)


def _patch(seed, colours):
    rnd = random.Random(seed)
    olive = material("wildflowers_olive", OLIVE, rough=0.85, vary=0.3, scale=30, crevice=0.6)
    dark = material("wildflowers_olive_dark", OLIVE_DARK, rough=0.85, vary=0.3, scale=30, crevice=0.6)
    tip = material("wildflowers_tip", TIP, rough=0.9, vary=0.25, scale=30, crevice=0.4)
    stem = material("wildflowers_stem", STEM, rough=0.85, vary=0.25, scale=30, crevice=0.5)
    eye = material("wildflowers_eye", EYE, rough=0.8, vary=0.2, scale=40, crevice=0.3)
    root = material("wildflowers_root", ROOT, vary=0.2, scale=20)

    blob("wildflowers_root", 0.05, (0, 0, 0.012), root, squash=(1.6, 1.3, 0.3), subdiv=1, seed=seed, jitter=0.2)

    for i in range(N_BLADES):
        yaw = 360 * i / N_BLADES + rnd.uniform(-20, 20)
        r = rnd.uniform(0.0, 0.06)
        base = (r * math.sin(math.radians(yaw)), -r * math.cos(math.radians(yaw)), 0.002)
        tilt = rnd.uniform(15, 50)
        _blade(f"wildflowers_blade_{i}", base, BLADE_H * rnd.uniform(0.6, 1.0), tilt, yaw,
               rnd.choice([olive, olive, dark]), rnd.choice([tip, olive]))

    for i in range(N_STEMS):
        a = 2 * math.pi * (i + rnd.uniform(-0.3, 0.3)) / N_STEMS
        r = PATCH_R * math.sqrt(rnd.uniform(0.05, 1.0))
        base = (r * math.cos(a), r * math.sin(a), 0.002)
        # Lean outwards a little, so the blossoms spread into a loose dome.
        yaw = math.degrees(a) + 90 + rnd.uniform(-25, 25)
        tilt = rnd.uniform(3, 14)
        height = STEM_H * rnd.uniform(0.7, 1.08)
        petals = colours[i % len(colours)]
        _flower(f"wildflowers_{i}", base, height, tilt, yaw, stem, petals, eye, rnd.uniform(0.85, 1.15))


@prop
def wildflowers():
    white = material("wildflowers_white", WHITE, rough=0.75, vary=0.15, scale=40, crevice=0.3)
    yellow = material("wildflowers_yellow", YELLOW, rough=0.75, vary=0.2, scale=40, crevice=0.3)
    _patch(4, [white, yellow, white, yellow, yellow])


@prop
def wildflowers_violet():
    white = material("wildflowers_white", WHITE, rough=0.75, vary=0.15, scale=40, crevice=0.3)
    violet = material("wildflowers_violet", VIOLET, rough=0.75, vary=0.2, scale=40, crevice=0.3)
    _patch(11, [violet, white, violet, violet, white])
