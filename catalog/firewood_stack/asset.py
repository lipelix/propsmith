"""A neat stack of split firewood against a house wall: rows of round and quartered logs lying front to back, pale
end grain and split faces with dark bark, on two squared sleeper beams (generated by npm run new)."""
import math
import random

from mathutils import Matrix

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder

# Overall dimensions: the stack is 1.2 m long (x), 0.5 m deep (y), 0.8 m high.
STACK_W = 1.2  # length of the stack along x
LOG_L = (0.42, 0.5)  # log length range along y (the stack's depth, about 0.5 m)
LOG_R = 0.066  # radius of a round log
PITCH = 0.135  # x spacing of logs in a row
ROW_H = 0.117  # vertical spacing of rows (staggered packing)
ROWS = 6
SPLIT = 0.118  # side of a quartered split piece
BARK_T = 0.022  # bark slab thickness on a split piece
BEAM_W, BEAM_H = 0.1, 0.08  # squared sleeper beam section
BEAM_L = 1.26  # sleeper length along x
BEAM_Y = 0.15  # sleepers sit at y = +-BEAM_Y

BARK = (0.085, 0.052, 0.03)  # dark brown bark
BARK_OLD = (0.1, 0.075, 0.05)  # greyer, older bark
PALE = (0.5, 0.37, 0.21)  # fresh split wood, pale and warm
PALE_OLD = (0.42, 0.32, 0.19)  # older, weathered split faces
BEAM = (0.17, 0.125, 0.08)  # weathered sleeper


def _place(obj, m):
    obj.location = m.to_translation()
    obj.rotation_euler = m.to_euler()
    return obj


def _rot(axis, deg):
    return Matrix.Rotation(math.radians(deg), 4, axis)


def _round_log(name, frame, length, r, mats, rnd):
    """Bark cylinder with a slightly longer pale core whose ends show the end grain."""
    spin = rnd.uniform(0, 360)
    base = frame @ _rot("X", -90) @ _rot("Z", spin)
    bark = cylinder(f"{name}_bark", r, length - 0.016, (0, 0, 0), mats["bark"], segments=8, bevel=0)
    _place(bark, base @ Matrix.Translation((0, 0, -(length - 0.016) / 2)))
    core = cylinder(f"{name}_core", r * 0.9, length, (0, 0, 0), mats["pale"], segments=8, bevel=0.006)
    core.modifiers["bevel"].segments = 1
    _place(core, base @ Matrix.Translation((0, 0, -length / 2)))


def _split_log(name, frame, length, s, mats, rnd):
    """A quartered piece: a pale square-ish block with a bark slab on one face."""
    spin = rnd.choice((0, 90, 180, 270)) + rnd.uniform(-12, 12)
    base = frame @ _rot("Y", spin)
    sx = s * rnd.uniform(0.85, 1.1)
    piece = box(f"{name}_wood", (sx, length, s), (0, 0, 0), mats["pale"], bevel=0.01)
    piece.modifiers["bevel"].segments = 1
    _place(piece, base)
    slab = box(f"{name}_bark", (sx * 0.92, length - 0.02, BARK_T), (0, 0, 0), mats["bark"], bevel=0.006)
    slab.modifiers["bevel"].segments = 1
    _place(slab, base @ Matrix.Translation((0, 0, s / 2)))


@prop
def firewood_stack():
    rnd = random.Random(11)
    beam = material("firewood_stack_beam", BEAM, vary=0.3, scale=12)
    fresh = {
        "bark": material("firewood_stack_bark", BARK, rough=0.95, vary=0.3, scale=25, crevice=0.5),
        "pale": material("firewood_stack_split", PALE, rough=0.85, vary=0.22, scale=18, crevice=0.3),
    }
    old = {
        "bark": material("firewood_stack_bark_old", BARK_OLD, rough=0.95, vary=0.3, scale=25, crevice=0.5),
        "pale": material("firewood_stack_split_old", PALE_OLD, rough=0.9, vary=0.25, scale=18, crevice=0.3),
    }

    # Two squared sleepers running along the stack, keeping the logs off the ground.
    for i, y in enumerate((-BEAM_Y, BEAM_Y)):
        box(f"firewood_stack_beam{i}", (BEAM_L, BEAM_W, BEAM_H), (rnd.uniform(-0.02, 0.02), y, BEAM_H / 2), beam,
            rot=(0, 0, rnd.uniform(-1.5, 1.5)), bevel=0.012)

    # Staggered rows of logs lying front to back (along y), end grain facing the front (-y).
    z0 = BEAM_H + LOG_R
    for row in range(ROWS):
        n = 9 if row % 2 == 0 else 8
        x0 = -(n - 1) * PITCH / 2
        for k in range(n):
            name = f"firewood_stack_log{row}_{k}"
            length = rnd.uniform(*LOG_L)
            x = x0 + k * PITCH + rnd.uniform(-0.008, 0.008)
            y = rnd.uniform(-0.02, 0.02)
            z = z0 + row * ROW_H + rnd.uniform(-0.006, 0.006)
            frame = (Matrix.Translation((x, y, z)) @ _rot("Z", rnd.uniform(-4, 4))
                     @ _rot("X", rnd.uniform(-3, 3)))
            mats = old if rnd.random() < 0.3 else fresh
            if rnd.random() < 0.55:
                _split_log(name, frame, length, SPLIT * rnd.uniform(0.92, 1.05), mats, rnd)
            else:
                _round_log(name, frame, length, LOG_R * rnd.uniform(0.88, 1.04), mats, rnd)
