"""A pitchfork and a wooden rake, heads on the ground, leaning together against a short X-legged trestle
(generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder

TILE = 1.5  # metres per tile
# Overall dimensions: the footprint is 1x1 tile (1.5 x 1.5 m), handle tops at 1.6 m (height 1.1 tile = 1.65 m).
TOP_Z = 1.6  # handle tops, metres
# Trestle: an X of two legs at each end, the bar lying in the upper V; it runs along x, centred on y = 0.
BAR_Z, BAR_R, BAR_HALF = 0.70, 0.045, 0.56
LEG_X, LEG_CROSS_Z, LEG_SPREAD, LEG_TOP_Z, LEG_T = 0.45, 0.55, 0.24, 0.80, 0.055
# Tools: hafts of ash, the heads on the ground in front (-y).
HAFT_R = 0.018
TOOL_BASE_Y = -0.55

ASH = (0.27, 0.22, 0.155)  # weathered ash, linear RGB
ASH_OLD = (0.23, 0.2, 0.16)
WOOD = (0.2, 0.115, 0.058)
WOOD_HEAD = (0.22, 0.135, 0.07)
IRON = (0.045, 0.045, 0.045)


def _norm(v):
    n = math.sqrt(sum(c * c for c in v))
    return tuple(c / n for c in v)


def _rot(d):
    """Euler XYZ (degrees) turning local +z onto unit direction d."""
    a = math.degrees(math.acos(max(-1.0, min(1.0, d[2]))))
    c = math.degrees(math.atan2(d[0], -d[1]))
    return (a, 0, c)


def _rod(name, p, q, r, mat, segments=8, bevel=0.004):
    """A capped cylinder from point p to point q."""
    d = tuple(b - a for a, b in zip(p, q))
    length = math.sqrt(sum(c * c for c in d))
    return cylinder(name, r, length, p, mat, segments=segments, rot=_rot(_norm(d)), bevel=bevel)


def _beam(name, p, q, t, mat, bevel=0.008):
    """A square beam of thickness t from p to q."""
    d = tuple(b - a for a, b in zip(p, q))
    length = math.sqrt(sum(c * c for c in d))
    mid = tuple((a + b) / 2 for a, b in zip(p, q))
    return box(name, (t, t, length), mid, mat, rot=_rot(_norm(d)), bevel=bevel)


def _lean(base, x_top):
    """The haft line from `base` (x, y, z) that rests on the trestle bar's front, to its top at TOP_Z."""
    py, pz = 0.0 - base[1], BAR_Z - base[2]
    dist = math.hypot(py, pz)
    theta = math.atan2(pz, py) + math.asin((BAR_R + HAFT_R) / dist)
    t = (TOP_Z - base[2]) / math.sin(theta)
    return (x_top, base[1] + t * math.cos(theta), TOP_Z)


def _along(p, d, s):
    return tuple(a + b * s for a, b in zip(p, d))


@prop
def farm_tools():
    rnd = random.Random(7)
    ash = material("farm_tools_ash", ASH, vary=0.22, scale=18)
    ash_old = material("farm_tools_ash_old", ASH_OLD, vary=0.25, scale=16)
    wood = material("farm_tools_trestle", WOOD, vary=0.25, scale=14)
    head = material("farm_tools_rake_head", WOOD_HEAD, vary=0.25, scale=16)
    iron = material("farm_tools_iron", IRON, rough=0.5, metal=0.8)

    # Trestle: at each end two legs crossing in an X (side by side, pinned), the bar in the upper V.
    k = LEG_SPREAD / LEG_CROSS_Z
    for s in (-1, 1):
        x = s * LEG_X
        for e in (-1, 1):
            j = rnd.uniform(-0.01, 0.01)
            foot = (x + e * 0.03, e * LEG_SPREAD + j, 0.014)
            top = (x + e * 0.03, -e * k * (LEG_TOP_Z - LEG_CROSS_Z) + j, LEG_TOP_Z)
            _beam(f"leg_{s}_{e}", foot, top, LEG_T, wood)
        cylinder(f"pin_{s}", 0.014, 0.16, (x - 0.08, 0, LEG_CROSS_Z), iron, segments=8, rot=(0, 90, 0), bevel=0.003)
    cylinder("bar", BAR_R, 2 * BAR_HALF, (-BAR_HALF, 0, BAR_Z), wood, segments=12, rot=(0, 90, 2), bevel=0.008)

    # Pitchfork: four iron tines on the ground, a bridge and ferrule, the ash haft up over the bar.
    fork_base = (-0.24, TOOL_BASE_Y, 0.012)
    fork_top = _lean(fork_base, -0.06)
    d = _norm(tuple(b - a for a, b in zip(fork_base, fork_top)))
    tine_len = 0.3
    for i in range(4):
        dx = (i - 1.5) * 0.045
        tip = (fork_base[0] + dx, fork_base[1], fork_base[2])
        root = _along((fork_base[0] + dx * 0.6, fork_base[1], fork_base[2]), d, tine_len)
        _rod(f"tine_{i}", tip, root, 0.008, iron, segments=6, bevel=0)
    bridge = _along(fork_base, d, tine_len)
    _beam("fork_bridge", _along(bridge, (1, 0, 0), -0.065), _along(bridge, (1, 0, 0), 0.065), 0.026, iron, bevel=0.004)
    _rod("fork_ferrule", bridge, _along(bridge, d, 0.12), 0.022, iron, segments=10)
    _rod("fork_haft", _along(bridge, d, 0.1), fork_top, HAFT_R, ash, segments=10)

    # Rake: a wooden head lying on the ground with its pegs pointing forward, the haft over the bar.
    rake_base = (0.28, TOOL_BASE_Y + 0.06, 0.045)
    rake_top = _lean(rake_base, 0.1)
    d = _norm(tuple(b - a for a, b in zip(rake_base, rake_top)))
    rot = _rot(d)
    box("rake_head", (0.5, 0.05, 0.05), rake_base, head, rot=rot, bevel=0.008)
    u = (math.cos(math.radians(rot[2])), math.sin(math.radians(rot[2])), 0.0)
    n = _norm((u[1] * d[2] - u[2] * d[1], u[2] * d[0] - u[0] * d[2], u[0] * d[1] - u[1] * d[0]))
    if n[1] > 0:
        n = tuple(-c for c in n)
    for i in range(9):
        p = _along(rake_base, u, (i - 4) * 0.055)
        _rod(f"peg_{i}", _along(p, n, 0.02), _along(p, n, 0.1 + rnd.uniform(-0.01, 0.01)), 0.008, ash_old, segments=6, bevel=0)
    _rod("rake_haft", _along(rake_base, d, 0.02), rake_top, HAFT_R, ash_old, segments=10)
    for s in (-1, 1):
        _rod(f"rake_brace_{s}", _along(_along(rake_base, u, s * 0.15), d, 0.02), _along(rake_base, d, 0.25), 0.009, ash_old, segments=6, bevel=0)
