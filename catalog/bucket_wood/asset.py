"""A small wooden water bucket: tapered staves, two dark iron hoops and an iron bail handle, dark water inside.
Variant `bucket_wood_tipped`: the same bucket lying on its side, empty (generated by npm run new)."""
import math
import random

from mathutils import Matrix

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box, cylinder, torus

# Overall dimensions (metres), from the description: about 0.35 m high and 0.3 m across.
H = 0.35  # stave height
R_TOP = 0.15  # outer radius at the rim
R_FOOT = 0.13  # outer radius at the foot (buckets flare upward)
STAVES = 12
STAVE_T = 0.018
FLOOR = 0.03  # top of the bucket floor
WATER_Z = 0.27  # water surface
HOOP_Z = (0.06, 0.285)
HOOP_TUBE = 0.008
EAR_Z = 0.3  # bail pivot height
BAIL_R = R_TOP + 0.014  # bail arc radius
BAIL_TUBE = 0.0065
BAIL_SEG = 9
TAPER = math.degrees(math.atan((R_TOP - R_FOOT) / H))

WOOD = (0.2, 0.12, 0.062)  # linear RGB
WOOD_LIGHT = (0.24, 0.15, 0.08)
WOOD_OLD = (0.15, 0.105, 0.072)
WOOD_INNER = (0.1, 0.06, 0.033)
IRON = (0.045, 0.045, 0.045)
WATER = (0.015, 0.035, 0.04)


def outer_r(z):
    return R_FOOT + (R_TOP - R_FOOT) * z / H


def build_bucket(seed, water, bail_swing):
    """Adds the standing bucket's parts and returns them. `bail_swing` tips the bail (degrees) about its pivots
    toward -y; `water` fills it."""
    rnd = random.Random(seed)
    woods = [
        material("bucket_staves", WOOD, vary=0.25, scale=16),
        material("bucket_staves_light", WOOD_LIGHT, vary=0.25, scale=14),
        material("bucket_staves_old", WOOD_OLD, vary=0.3, scale=12),
    ]
    inner = material("bucket_inner", WOOD_INNER, vary=0.2, scale=10)
    iron = material("bucket_iron", IRON, rough=0.5, metal=0.8, vary=0.3, scale=24)
    parts = []

    # A closed core inside the staves: the floor (and, when full, the dark water column).
    top = WATER_Z if water else FLOOR
    parts.append(
        cylinder("core", outer_r(0.005) - STAVE_T + 0.003, top - 0.005, (0, 0, 0.005), inner,
                 r_top=outer_r(top) - STAVE_T + 0.003, segments=16, bevel=0)
    )
    if water:
        wet = material("bucket_water", WATER, rough=0.05, vary=0.05, crevice=0)
        parts.append(cylinder("water", outer_r(top) - STAVE_T + 0.004, 0.006, (0, 0, top - 0.003), wet, segments=16, bevel=0))

    # Staves: one tapered-leaning box each, edge to edge.
    for i in range(STAVES):
        a = 360 * i / STAVES + rnd.uniform(-1.5, 1.5)
        ar = math.radians(a)
        stave_h = H - rnd.uniform(0.0, 0.008)
        rc = outer_r(stave_h / 2) - STAVE_T / 2
        w = 2 * rc * math.tan(math.pi / STAVES) * rnd.uniform(1.0, 1.04)
        parts.append(
            box(f"stave_{i}", (STAVE_T, w, stave_h / math.cos(math.radians(TAPER))),
                (rc * math.cos(ar), rc * math.sin(ar), stave_h / 2 + 0.001),
                woods[rnd.choice((0, 0, 1, 1, 2))], rot=(0, TAPER, a), bevel=0.005)
        )

    # Two dark iron hoops.
    for j, z in enumerate(HOOP_Z):
        parts.append(torus(f"hoop_{j}", outer_r(z) + HOOP_TUBE * 0.5, HOOP_TUBE, (0, 0, z), iron, major=24, minor=6))

    # Ears on the +x and -x staves and the bail arc between them.
    for s in (-1, 1):
        parts.append(box(f"ear_{s}", (0.018, 0.04, 0.06), (s * (outer_r(EAR_Z) + 0.006), 0, EAR_Z), iron, bevel=0.004))
    sw = math.radians(bail_swing)
    pts = []
    for k in range(BAIL_SEG + 1):
        t = math.pi * k / BAIL_SEG
        up = BAIL_R * math.sin(t) * 0.92
        pts.append((BAIL_R * math.cos(t), -up * math.sin(sw), EAR_Z + up * math.cos(sw)))
    for k in range(BAIL_SEG):
        (x0, y0, z0), (x1, y1, z1) = pts[k], pts[k + 1]
        dx, dy, dz = x1 - x0, y1 - y0, z1 - z0
        length = math.sqrt(dx * dx + dy * dy + dz * dz)
        # Orient the cylinder's +z along the segment: tilt about x, then turn about z.
        tilt = math.degrees(math.acos(max(-1.0, min(1.0, dz / length))))
        turn = math.degrees(math.atan2(dy, dx)) - 90
        parts.append(
            cylinder(f"bail_{k}", BAIL_TUBE, length + 0.004, (x0, y0, z0), iron, segments=8,
                     rot=(tilt, 0, turn + 180), bevel=0)
        )
    return parts


@prop
def bucket_wood():
    build_bucket(3, water=True, bail_swing=0)


@prop
def bucket_wood_tipped():
    # The bail has fallen against the downward side of the staves.
    parts = build_bucket(5, water=False, bail_swing=85)
    # Lay it on its side (a stave line flat on the ground), opening turned toward the camera (+x, -y).
    m = Matrix.Rotation(math.radians(45), 4, "Z") @ Matrix.Rotation(math.radians(90 - TAPER), 4, "X")
    for obj in parts:
        obj.matrix_basis = m @ obj.matrix_basis
    pts = [obj.matrix_basis @ v.co for obj in parts for v in obj.data.vertices]
    cx = (min(p.x for p in pts) + max(p.x for p in pts)) / 2
    cy = (min(p.y for p in pts) + max(p.y for p in pts)) / 2
    lift = Matrix.Translation((-cx, -cy, -min(p.z for p in pts)))
    for obj in parts:
        obj.matrix_basis = lift @ obj.matrix_basis
