"""A rectangular straw hay bale bound with two twine bands, with loose wisps at its edges and a few strands on the
ground; a variant stacks two bales side by side with a third across them (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box

# One bale is 0.45 m high, the stack 0.9 m.
L, W, H = 0.9, 0.5, 0.45  # bale length (local x), width (y), height, metres
FLAKES = 6  # compressed slabs a bale is made of, across its length
BAND_X = 0.22  # twine bands at +-BAND_X along the bale
BAND_W = 0.022  # twine band width
BAND_T = 0.008  # how far the twine stands proud of the straw
STACK_GAP = 0.27  # y offset of each lower bale in the stack (bales 0.5 m wide, a little gap)
STALK_W = 0.012  # metres, straw stalk width
STALK_T = 0.005  # stalk thickness
WISP_L = (0.07, 0.15)  # wisp lengths poking out of the bale
GROUND_L = (0.12, 0.22)  # loose stalks lying on the ground

STRAW = (0.45, 0.32, 0.12)  # linear RGB, golden but desaturated
STRAW_PALE = (0.5, 0.39, 0.17)
STRAW_OLD = (0.36, 0.26, 0.11)
TWINE = (0.16, 0.12, 0.07)


def _mats():
    return {
        "straw": material("hay_bale_straw", STRAW, rough=0.95, vary=0.3, scale=28, crevice=0.45),
        "pale": material("hay_bale_straw_pale", STRAW_PALE, rough=0.95, vary=0.3, scale=28, crevice=0.4),
        "old": material("hay_bale_straw_old", STRAW_OLD, rough=0.95, vary=0.3, scale=24, crevice=0.45),
        "twine": material("hay_bale_twine", TWINE, rough=0.9, vary=0.2, scale=40, crevice=0.4),
    }


class _Frame:
    """A bale's placement: centre (cx, cy), bottom z0, turned 90 deg when `turn`."""

    def __init__(self, cx, cy, z0, turn):
        self.cx, self.cy, self.z0, self.turn = cx, cy, z0, turn

    def at(self, x, y, z):
        if self.turn:
            x, y = -y, x
        return (self.cx + x, self.cy + y, self.z0 + z)

    def yaw(self, a):
        return a + (90 if self.turn else 0)


def _bale(prefix, frame, mats, rnd, top_wisps=True):
    """One bale: slightly uneven flakes, two twine bands and straw wisps poking out of its edges."""
    # A solid core keeps the flakes' seams shallow: they read as compressed slabs, not separate loaves.
    box(f"{prefix}_core", (L - 0.03, W - 0.03, H - 0.02), frame.at(0, 0, (H - 0.02) / 2), mats["straw"],
        rot=(0, 0, frame.yaw(0)), bevel=0.02)
    fl = L / FLAKES
    for i in range(FLAKES):
        x = -L / 2 + fl * (i + 0.5)
        h = H * rnd.uniform(0.975, 1.0)
        w = W * rnd.uniform(0.975, 1.0)
        mat = mats["pale"] if i % 3 == 1 else (mats["old"] if rnd.random() < 0.2 else mats["straw"])
        box(f"{prefix}_flake_{i}", (fl * 1.04, w, h), frame.at(x, rnd.uniform(-0.005, 0.005), h / 2), mat,
            rot=(0, 0, frame.yaw(rnd.uniform(-1.0, 1.0))), bevel=0.012)

    for j, bx in enumerate((-BAND_X, BAND_X)):
        bx += rnd.uniform(-0.015, 0.015)
        box(f"{prefix}_band_{j}", (BAND_W, W + 2 * BAND_T, H + BAND_T), frame.at(bx, 0, (H + BAND_T) / 2),
            mats["twine"], rot=(0, 0, frame.yaw(rnd.uniform(-1.5, 1.5))), bevel=0.003)

    # Wisps from the four long top edges and the ends: a stalk starting just inside the straw, tipped outwards.
    n = 0
    edges = []
    for sy in (-1, 1):  # long top edges
        if top_wisps:
            edges += [("long", sy)] * 9
        edges += [("side", sy)] * 5  # lower on the long faces
    for sx in (-1, 1):
        edges += [("end", sx)] * 6
    for kind, s in edges:
        length = rnd.uniform(*WISP_L)
        if kind == "long":
            x, y, z = rnd.uniform(-L / 2 + 0.06, L / 2 - 0.06), s * (W / 2 - 0.01), H - 0.012
            yaw, elev = s * 90 + rnd.uniform(-40, 40), rnd.uniform(5, 35)
        elif kind == "side":
            x, y, z = rnd.uniform(-L / 2 + 0.05, L / 2 - 0.05), s * (W / 2 - 0.01), rnd.uniform(0.12, H - 0.08)
            yaw, elev = s * 90 + rnd.uniform(-50, 50), rnd.uniform(-25, 20)
        else:
            x, y, z = s * (L / 2 - 0.01), rnd.uniform(-W / 2 + 0.05, W / 2 - 0.05), rnd.uniform(0.1, H - 0.03)
            yaw, elev = (0 if s > 0 else 180) + rnd.uniform(-45, 45), rnd.uniform(-20, 30)
        a, e = math.radians(yaw), math.radians(elev)
        d = (math.cos(e) * math.cos(a), math.cos(e) * math.sin(a), math.sin(e))
        half = length / 2 - 0.02  # the root sits 2 cm inside the straw
        c = (x + d[0] * half, y + d[1] * half, z + d[2] * half)
        mat = mats["pale"] if rnd.random() < 0.75 else mats["straw"]
        box(f"{prefix}_wisp_{n}", (length, STALK_W, STALK_T), frame.at(*c), mat,
            rot=(rnd.uniform(0, 180), -elev, frame.yaw(yaw)), bevel=0)
        n += 1


def _ground(prefix, mats, rnd, n, inner):
    """Loose stalks lying flat on the ground around the bales, outside the `inner` (half x, half y) box."""
    placed = 0
    while placed < n:
        x, y = rnd.uniform(-0.62, 0.62), rnd.uniform(-0.62, 0.62)
        if abs(x) < inner[0] and abs(y) < inner[1]:
            continue
        length = rnd.uniform(*GROUND_L)
        mat = mats["pale"] if placed % 2 else mats["old"]
        box(f"{prefix}_strand_{placed}", (length, STALK_W, STALK_T), (x, y, STALK_T / 2 + 0.001), mat,
            rot=(0, 0, rnd.uniform(0, 180)), bevel=0)
        placed += 1


@prop
def hay_bale():
    rnd = random.Random(3)
    mats = _mats()
    _bale("hay_bale", _Frame(0, 0, 0, False), mats, rnd)
    _ground("hay_bale", mats, rnd, 9, (L / 2 + 0.08, W / 2 + 0.08))


@prop
def hay_bale_stack():
    rnd = random.Random(5)
    mats = _mats()
    _bale("hay_bale_low_a", _Frame(0, -STACK_GAP, 0, False), mats, rnd, top_wisps=False)
    _bale("hay_bale_low_b", _Frame(0, STACK_GAP, 0, False), mats, rnd, top_wisps=False)
    _bale("hay_bale_top", _Frame(rnd.uniform(-0.03, 0.03), 0, H - 0.008, True), mats, rnd)
    _ground("hay_bale_stack", mats, rnd, 8, (L / 2 + 0.06, STACK_GAP + W / 2 + 0.06))
