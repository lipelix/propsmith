"""A section of village fieldstone wall with an empty door opening framed by dressed quoins and a heavy lintel
(generated by npm run new)."""
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import box

TILE = 1.5  # metres per tile
# Overall dimensions: the wall runs along x through the tile centre, full tile long, like wall_stone_straight.
L = 1 * TILE  # wall length (x), 1.5 m
T = 0.45  # wall thickness (y)
H = 2.4  # wall height, 1.6 tiles
OPEN_W, OPEN_H = 1.0, 2.0  # clear door passage, matches door_wood
PIER = (L - OPEN_W) / 2  # each jamb pier, 0.25 m
LINTEL_H = 0.32
CAP_H = H - OPEN_H - LINTEL_H  # capstone row on top, 0.08 m
COURSES = 7  # quoin courses up each jamb
# The `_low` variant: a cutaway doorway for roofless village buildings (Phase 13 Decision 1), two quoined piers with
# no lintel, as high as the `_low` walls. Picked in Phase 13 Task 0; the location look prototype overrides it.
LOW_H = 1.38
GAP = 0.016  # mortar joint

# Shared stone palette of the village wall set (wall_stone_straight, _corner, _doorframe): keep them equal.
STONE = (0.34, 0.295, 0.235)  # rough fieldstone
STONE_OLD = (0.27, 0.235, 0.19)
QUOIN = (0.5, 0.45, 0.36)  # dressed lighter stone
LINTEL = (0.46, 0.415, 0.335)
MORTAR = (0.11, 0.10, 0.085)
CAP = (0.27, 0.255, 0.23)


@prop
def wall_stone_doorframe():
    rnd = random.Random(11)
    stone = material("wall_stone_doorframe_field", STONE, vary=0.28, scale=9)
    old = material("wall_stone_doorframe_field_old", STONE_OLD, vary=0.3, scale=9)
    quoin = material("wall_stone_doorframe_quoin", QUOIN, vary=0.16, scale=7)
    lintel = material("wall_stone_doorframe_lintel", LINTEL, vary=0.2, scale=6)
    mortar = material("wall_stone_doorframe_mortar", MORTAR, vary=0.1, scale=12)
    cap = material("wall_stone_doorframe_cap", CAP, vary=0.25, scale=7)

    x_in, x_out = OPEN_W / 2, L / 2
    course_h = OPEN_H / COURSES
    for s in (-1, 1):
        # Recessed mortar core of the pier: shows in the joints, never in front of the stones.
        box(f"core_{s}", (PIER - 0.03, T - 0.05, OPEN_H), (s * (x_in + x_out) / 2, 0, OPEN_H / 2), mortar, bevel=0)
        for c in range(COURSES):
            z0 = c * course_h
            h = course_h - GAP
            zc = z0 + course_h / 2
            # Quoins alternate long (whole pier) and short (with a fieldstone piece behind), offset per jamb.
            long_course = (c + (s > 0)) % 2 == 0
            qw = PIER - GAP if long_course else PIER * 0.5
            box(
                f"quoin_{s}_{c}",
                (qw, T * rnd.uniform(0.985, 1.0), h),
                (s * (x_in + qw / 2), rnd.uniform(-0.004, 0.004), zc),
                quoin,
                rot=(0, 0, rnd.uniform(-0.6, 0.6)),
                bevel=0.012,
            )
            if not long_course:
                fw = PIER - qw - 2 * GAP
                box(
                    f"field_{s}_{c}",
                    (fw * rnd.uniform(0.92, 1.0), T * rnd.uniform(0.95, 1.01), h * rnd.uniform(0.9, 1.0)),
                    (s * (x_out - GAP / 2 - fw / 2), rnd.uniform(-0.008, 0.008), zc),
                    rnd.choice((stone, stone, old)),
                    rot=(rnd.uniform(-1.5, 1.5), rnd.uniform(-1.5, 1.5), rnd.uniform(-2, 2)),
                    bevel=0.02,
                )

    # One heavy lintel across the opening, bearing on both piers.
    box(
        "lintel",
        (L - 2 * GAP, T + 0.01, LINTEL_H - GAP),
        (0, 0, OPEN_H + LINTEL_H / 2),
        lintel,
        rot=(0, 0.4, 0),
        bevel=0.02,
    )

    # Flat capstones on top, as on the straight wall.
    caps = 3
    cw = L / caps
    for i in range(caps):
        box(
            f"cap_{i}",
            (cw - GAP, T + 0.03 * rnd.uniform(0.8, 1.0), CAP_H - 0.006),
            (-L / 2 + cw * (i + 0.5), rnd.uniform(-0.01, 0.01), OPEN_H + LINTEL_H + CAP_H / 2),
            cap,
            rot=(rnd.uniform(-0.8, 0.8), 0, rnd.uniform(-1.5, 1.5)),
            bevel=0.018,
        )


@prop
def wall_stone_doorframe_low():
    rnd = random.Random(11)
    stone = material("wall_stone_doorframe_field", STONE, vary=0.28, scale=9)
    old = material("wall_stone_doorframe_field_old", STONE_OLD, vary=0.3, scale=9)
    quoin = material("wall_stone_doorframe_quoin", QUOIN, vary=0.16, scale=7)
    mortar = material("wall_stone_doorframe_mortar", MORTAR, vary=0.1, scale=12)
    cap = material("wall_stone_doorframe_cap", CAP, vary=0.25, scale=7)

    x_in, x_out = OPEN_W / 2, L / 2
    body_h = LOW_H - CAP_H
    courses = max(2, round(body_h / (OPEN_H / COURSES)))
    course_h = body_h / courses
    for s in (-1, 1):
        box(f"core_{s}", (PIER - 0.03, T - 0.05, body_h), (s * (x_in + x_out) / 2, 0, body_h / 2), mortar, bevel=0)
        for c in range(courses):
            h = course_h - GAP
            zc = c * course_h + course_h / 2
            long_course = (c + (s > 0)) % 2 == 0
            qw = PIER - GAP if long_course else PIER * 0.5
            box(
                f"quoin_{s}_{c}",
                (qw, T * rnd.uniform(0.985, 1.0), h),
                (s * (x_in + qw / 2), rnd.uniform(-0.004, 0.004), zc),
                quoin,
                rot=(0, 0, rnd.uniform(-0.6, 0.6)),
                bevel=0.012,
            )
            if not long_course:
                fw = PIER - qw - 2 * GAP
                box(
                    f"field_{s}_{c}",
                    (fw * rnd.uniform(0.92, 1.0), T * rnd.uniform(0.95, 1.01), h * rnd.uniform(0.9, 1.0)),
                    (s * (x_out - GAP / 2 - fw / 2), rnd.uniform(-0.008, 0.008), zc),
                    rnd.choice((stone, stone, old)),
                    rot=(rnd.uniform(-1.5, 1.5), rnd.uniform(-1.5, 1.5), rnd.uniform(-2, 2)),
                    bevel=0.02,
                )
        # One capstone per pier, flush with the wall caps beside it.
        box(
            f"cap_{s}",
            (PIER - GAP, T + 0.03 * rnd.uniform(0.8, 1.0), CAP_H - 0.006),
            (s * (x_in + x_out) / 2, rnd.uniform(-0.01, 0.01), body_h + CAP_H / 2),
            cap,
            rot=(rnd.uniform(-0.8, 0.8), 0, rnd.uniform(-1.5, 1.5)),
            bevel=0.018,
        )
