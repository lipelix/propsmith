"""A round-bellied clay funeral urn with a lidded narrow neck, two loop handles and a zigzag band, chipped at the rim,
on a square stone block (generated by npm run new)."""
import math
import random

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder, torus

# Overall dimensions (metres), from the description.
BLOCK_W, BLOCK_H = 0.28, 0.08  # square stone block
FOOT_R, FOOT_H = 0.07, 0.03  # foot ring of the pot
BELLY_R, BELLY_SQUASH = 0.12, 0.9  # round belly
NECK_R, NECK_H = 0.05, 0.06
RIM_R, RIM_T = 0.056, 0.014  # rim ring radius and lip thickness
LID_R, LID_H = 0.05, 0.02
KNOB_R = 0.017

CLAY = (0.36, 0.15, 0.075)
CLAY_FRESH = (0.46, 0.24, 0.13)  # paler clay showing at the chips
INCISED = (0.11, 0.05, 0.028)
STONE = (0.3, 0.28, 0.25)

RIM_SEGMENTS = 16
CHIPPED = {12: 0.5, 13: 0.2, 14: 0.35, 5: 0.5}  # 12-14 face the review camera (-y, +x)  # rim segment -> remaining height fraction
ZIGZAGS = 24


@prop
def urn_funeral():
    rnd = random.Random(7)
    clay = material("urn_funeral_clay", CLAY, vary=0.2, scale=9, rough=0.9)
    fresh = material("urn_funeral_chip", CLAY_FRESH, vary=0.15, scale=20, rough=0.95, crevice=0.3)
    dark = material("urn_funeral_incised", INCISED, vary=0.1, rough=0.95)
    stone = material("urn_funeral_stone", STONE, vary=0.25, scale=7, rough=0.9, crevice=0.6)

    # Square stone block, slightly off-square.
    box("block", (BLOCK_W, BLOCK_W * 0.98, BLOCK_H), (0, 0, BLOCK_H / 2), stone, rot=(0, 0, 1.5), bevel=0.014)

    # Foot, belly, shoulder and neck.
    z = BLOCK_H
    cylinder("foot", FOOT_R, FOOT_H, (0, 0, z - 0.002), clay, r_top=FOOT_R * 0.9, segments=20, bevel=0.006)
    belly_z = z + FOOT_H + BELLY_R * BELLY_SQUASH - 0.012
    blob("belly", BELLY_R, (0, 0, belly_z), clay, squash=(1, 1, BELLY_SQUASH), subdiv=3, seed=3, jitter=0.008)
    shoulder_z = belly_z + BELLY_R * BELLY_SQUASH * 0.7
    shoulder_h = BELLY_R * BELLY_SQUASH * 0.3 + 0.012
    cylinder("shoulder", 0.085, shoulder_h, (0, 0, shoulder_z), clay, r_top=NECK_R, segments=24, bevel=0.005)
    neck_z = shoulder_z + shoulder_h - 0.004
    cylinder("neck", NECK_R, NECK_H, (0, 0, neck_z), clay, r_top=NECK_R * 1.04, segments=20, bevel=0.004)

    # Rim lip of short segments; a few are chipped down and show paler clay.
    rim_z = neck_z + NECK_H - RIM_T * 0.6
    seg_len = 2 * math.pi * RIM_R / RIM_SEGMENTS * 1.08
    for i in range(RIM_SEGMENTS):
        a = 2 * math.pi * i / RIM_SEGMENTS
        h = RIM_T * CHIPPED.get(i, 1.0)
        box(
            f"rim_{i}",
            (seg_len, RIM_T * 0.9, h),
            (RIM_R * math.cos(a), RIM_R * math.sin(a), rim_z + h / 2),
            fresh if i in CHIPPED else clay,
            rot=(rnd.uniform(-2, 2), 0, math.degrees(a) + 90),
            bevel=0.003,
        )

    # Fitted lid with a knob, seated inside the rim.
    lid_z = rim_z + RIM_T * 0.4
    cylinder("lid", LID_R, LID_H, (0, 0, lid_z), clay, r_top=LID_R * 0.72, segments=20, rot=(1.5, -1, 0), bevel=0.004)
    cylinder("knob_stem", 0.008, 0.016, (0, 0, lid_z + LID_H - 0.004), clay, segments=10, bevel=0.002)
    blob("knob", KNOB_R, (0, 0, lid_z + LID_H + 0.012 + KNOB_R * 0.8), clay, squash=(1, 1, 0.8), subdiv=2, seed=5, jitter=0.03)

    # Two small loop handles on the shoulder, in the xz plane.
    for side in (-1, 1):
        torus(
            f"handle_{side}",
            0.026,
            0.0075,
            (side * 0.088, 0, shoulder_z + 0.022),
            clay,
            rot=(90, 0, 0),
            major=16,
            minor=8,
        )

    # Band of incised zigzags around the widest part of the belly, between two incised lines.
    band_z = belly_z + 0.01
    stroke = 2 * math.pi * BELLY_R / ZIGZAGS * 1.35
    for i in range(ZIGZAGS):
        a = 2 * math.pi * (i + 0.5) / ZIGZAGS
        tilt = 45 if i % 2 else -45
        r = BELLY_R - 0.0015
        box(
            f"zigzag_{i}",
            (stroke, 0.006, 0.0045),
            (r * math.cos(a), r * math.sin(a), band_z),
            dark,
            rot=(0, tilt + rnd.uniform(-4, 4), math.degrees(a) - 90),
            bevel=0,
        )
    for k, dz in enumerate((-0.03, 0.03)):
        zz = band_z + dz
        rr = BELLY_R * math.sqrt(max(0.0, 1 - (dz / (BELLY_R * BELLY_SQUASH)) ** 2)) - 0.001
        torus(f"band_line_{k}", rr, 0.0028, (0, 0, zz), dark, major=32, minor=6)
