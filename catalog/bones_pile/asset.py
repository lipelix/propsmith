"""A heap of old human bones about 0.9 m across and 0.4 m high on the floor: several yellowed skulls, long bones, ribs
and a jaw piled loosely, a few bones scattered around it (generated by npm run new).

A low lumpy mound of bone dust and fragments carries the heap; long bones lean on it from the ground and cross over
its top, ribs lie draped over it, three skulls sit on and against it, and a jaw, a rib and two bones lie apart."""
import math
import random

from mathutils import Euler, Matrix, Vector

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder

# Overall dimensions (metres), from the description.
HEAP_RX, HEAP_RY = 0.26, 0.22  # half-widths of the fragment mound under the heap
HEAP_H = 0.17  # height of the fragment mound
SKULL_R = 0.085  # half-width of a cranium (a skull is about 0.2 m long, 0.15 m high)
SHAFT_R = 0.013  # radius of a long-bone shaft
KNOB_R = 0.03  # radius of a long-bone end
RIB_R = 0.006  # radius of a rib
RIB_ARC = 0.13  # radius of a rib's curve

BONE = (0.44, 0.37, 0.23)  # linear RGB, yellowed bone
BONE_OLD = (0.34, 0.27, 0.16)  # older, browner bone
DUST = (0.24, 0.2, 0.13)  # bone dust and fragments under the heap
HOLLOW = (0.07, 0.05, 0.035)  # eye sockets and nose holes


def _group(objs, at, yaw=0.0, pitch=0.0, roll=0.0):
    """Move parts built in a local frame: roll about x, pitch (nose up) about -y, yaw about z, then to `at`."""
    g = Matrix.Translation(Vector(at)) @ Euler(
        (math.radians(roll), math.radians(-pitch), math.radians(yaw))).to_matrix().to_4x4()
    for o in objs:
        o.matrix_basis = g @ o.matrix_basis
    return objs


def _rod(name, p0, p1, r, mat, segments=8, bevel=0.0, r_top=None):
    """A cylinder from point `p0` to point `p1`."""
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    yaw = math.degrees(math.atan2(d.y, d.x))
    pitch = math.degrees(math.asin(max(-1.0, min(1.0, d.z / d.length))))
    return cylinder(name, r, d.length, p0, mat, r_top=r_top, segments=segments, rot=(0, 90 - pitch, yaw), bevel=bevel)


def _surf(x, y):
    """Height of the fragment mound's top at (x, y) (0 outside it)."""
    u = 1 - (x / HEAP_RX) ** 2 - (y / HEAP_RY) ** 2
    return HEAP_H / 2 + HEAP_H / 2 * math.sqrt(u) if u > 0 else 0.0


def _long_bone(name, p0, p1, mat, scale=1.0, seed=0):
    """A long bone (femur, shin, arm bone) between the centres of its two ends: a shaft and a knobbly end at each."""
    k = KNOB_R * scale
    p0, p1 = Vector(p0), Vector(p1)
    d = (p1 - p0).normalized()
    side = d.cross(Vector((0, 0, 1)))
    side = side.normalized() if side.length > 1e-6 else Vector((0, 1, 0))
    _rod(f"{name}_shaft", p0, p1, SHAFT_R * scale, mat, segments=8, bevel=0.003, r_top=SHAFT_R * scale * 0.9)
    yaw = math.degrees(math.atan2(d.y, d.x))
    for i, (p, sq) in enumerate(((p0, (0.8, 1.2, 0.85)), (p1, (0.75, 1.0, 0.8)))):
        o = blob(f"{name}_end{i}", k, p, mat, squash=sq, subdiv=1, seed=seed + i, jitter=0.1)
        o.rotation_euler = (0, 0, math.radians(yaw))
    # a femur-like head knob off one end
    blob(f"{name}_head", k * 0.65, p1 + side * k * 0.7 + d * k * 0.2, mat, subdiv=1, seed=seed + 5, jitter=0.08)


def _rib(name, at, yaw, mat, pitch=0.0, roll=0.0, span=110):
    """A rib: a thin arc in the local xy plane, a chain of short rods, its lowest side at local z = 0."""
    pts = []
    n = 4
    for i in range(n + 1):
        a = math.radians(-span / 2 + span * i / n)
        pts.append((RIB_ARC * math.sin(a), RIB_ARC * (1 - math.cos(a)) * 1.2, RIB_R))
    parts = []
    for i in range(n):
        p0, p1 = Vector(pts[i]), Vector(pts[i + 1])
        e = (p1 - p0).normalized() * RIB_R
        parts.append(_rod(f"{name}_{i}", p0 - e, p1 + e, RIB_R * (1.25 - 0.1 * i), mat, segments=6))
    return _group(parts, at, yaw, pitch, roll)


def _jaw(name, at, yaw, mat, pitch=0.0, roll=0.0):
    """A lower jaw: a U of bone opening to +y, a raised branch at each back end, a row of teeth on the front."""
    w, d, r = 0.045, 0.085, 0.009
    pts = [(-w, d, r), (-w * 0.85, d * 0.35, r), (-w * 0.45, 0.0, r), (w * 0.45, 0.0, r), (w * 0.85, d * 0.35, r),
           (w, d, r)]
    parts = []
    for i in range(len(pts) - 1):
        p0, p1 = Vector(pts[i]), Vector(pts[i + 1])
        e = (p1 - p0).normalized() * r * 0.6
        parts.append(_rod(f"{name}_{i}", p0 - e, p1 + e, r, mat, segments=6))
    for s, x in ((0, -w), (1, w)):
        parts.append(box(f"{name}_branch{s}", (0.01, 0.022, 0.045), (x, d + 0.004, 0.026), mat, rot=(-15, 0, 0),
                         bevel=0.003))
    parts.append(box(f"{name}_teeth", (0.045, 0.012, 0.012), (0, 0.006, r * 2), mat, bevel=0.003))
    return _group(parts, at, yaw, pitch, roll)


def _skull(name, at, yaw, mat, hollow, pitch=0.0, roll=0.0, seed=0):
    """A skull facing local -y, its lowest point near local z = 0: cranium, face, brow, sockets, nose, upper teeth."""
    r = SKULL_R
    parts = [
        blob(f"{name}_cranium", r, (0, 0.012, r * 0.98), mat, squash=(0.92, 1.2, 0.95), subdiv=2, seed=seed,
             jitter=0.035),
        blob(f"{name}_face", r * 0.55, (0, -0.06, r * 0.62), mat, squash=(1.2, 0.85, 1.0), subdiv=2, seed=seed + 1,
             jitter=0.05),
        blob(f"{name}_brow", r * 0.4, (0, -0.07, r * 1.05), mat, squash=(1.8, 0.55, 0.55), subdiv=1, seed=seed + 2,
             jitter=0.04),
    ]
    for s in (-1, 1):
        parts.append(blob(f"{name}_cheek{s}", r * 0.28, (s * 0.045, -0.055, r * 0.62), mat, squash=(0.9, 1.3, 0.8),
                          subdiv=1, seed=seed + 3 + s, jitter=0.05))
        parts.append(blob(f"{name}_eye{s}", r * 0.3, (s * 0.03, -0.094, r * 0.84), hollow, squash=(1.0, 0.5, 0.9),
                          subdiv=1, seed=seed + 6 + s, jitter=0.05))
    parts.append(blob(f"{name}_nose", r * 0.16, (0, -0.106, r * 0.6), hollow, squash=(0.8, 0.5, 1.3), subdiv=1,
                      seed=seed + 9, jitter=0.05))
    parts.append(box(f"{name}_teeth", (0.042, 0.014, 0.014), (0, -0.092, r * 0.3), mat, bevel=0.003))
    for o in parts:
        if o.name.startswith(f"{name}_") and o.type == "MESH" and "teeth" not in o.name:
            o.rotation_euler = (0, 0, 0)
    return _group(parts, at, yaw, pitch, roll)


@prop
def bones_pile():
    rnd = random.Random(3)
    bone = material("bones_pile_bone", BONE, rough=0.7, vary=0.22, scale=25, crevice=0.6)
    old = material("bones_pile_bone_old", BONE_OLD, rough=0.75, vary=0.25, scale=25, crevice=0.6)
    dust = material("bones_pile_dust", DUST, rough=0.9, vary=0.3, scale=30, crevice=0.7)
    hollow = material("bones_pile_hollow", HOLLOW, rough=0.95, vary=0.2, scale=20, crevice=0.3)

    def pick():
        return bone if rnd.random() < 0.65 else old

    # The mound of dust and fragments that carries the heap.
    m = blob("bones_pile_mound", 1.0, (0, 0, HEAP_H / 2), dust, squash=(HEAP_RX, HEAP_RY, HEAP_H / 2), subdiv=2,
             seed=31, jitter=0.1)
    m.rotation_euler = (0, 0, 0)
    for i, (x, y, r) in enumerate(((0.12, -0.1, 0.06), (-0.14, 0.08, 0.07), (0.05, 0.13, 0.05), (-0.08, -0.14, 0.05))):
        blob(f"bones_pile_lump{i}", r, (x, y, _surf(x, y) * 0.75), dust, squash=(1.3, 1.0, 0.7), subdiv=1,
             seed=40 + i, jitter=0.2)

    # Long bones leaning on the mound from the ground, round the heap.
    lean = [(200, 0.36, 0.40, 15), (250, 0.34, 0.36, -20), (310, 0.37, 0.42, 10), (20, 0.35, 0.34, -12),
            (80, 0.33, 0.38, 18), (140, 0.36, 0.32, -10)]
    for i, (a, r0, length, skew) in enumerate(lean):
        a = math.radians(a + rnd.uniform(-8, 8))
        k = KNOB_R * rnd.uniform(0.85, 1.05)
        x0, y0 = r0 * math.cos(a), r0 * math.sin(a)
        b = a + math.pi + math.radians(skew)
        x1, y1 = x0 + length * 0.95 * math.cos(b), y0 + length * 0.95 * math.sin(b)
        _long_bone(f"bones_pile_lean{i}", (x0, y0, k * 0.9), (x1, y1, _surf(x1, y1) + k * 0.6), pick(), k / KNOB_R,
                   seed=100 + 10 * i)

    # Bones crossing over the top of the heap.
    top = [((-0.17, -0.02), (0.14, 0.1)), ((-0.05, 0.16), (0.08, -0.15)), ((0.17, -0.06), (-0.12, -0.12)),
           ((-0.2, 0.12), (-0.02, -0.17)), ((0.2, 0.06), (-0.1, 0.17))]
    for i, ((x0, y0), (x1, y1)) in enumerate(top):
        z0, z1 = _surf(x0, y0) + KNOB_R * 1.4, _surf(x1, y1) + KNOB_R * 1.4
        _long_bone(f"bones_pile_top{i}", (x0, y0, z0 + 0.02 * i), (x1, y1, z1 + 0.02 * i), pick(),
                   rnd.uniform(0.85, 1.0), seed=200 + 10 * i)

    # Ribs draped over the heap.
    ribs = [((-0.2, 0.05), 100, 25), ((-0.16, 0.1), 120, 30), ((0.16, 0.08), -40, 20), ((0.0, 0.18), 10, 15),
            ((0.12, -0.17), 200, 12)]
    for i, ((x, y), yaw, tilt) in enumerate(ribs):
        _rib(f"bones_pile_rib{i}", (x, y, _surf(x, y) - 0.005), yaw + rnd.uniform(-10, 10), pick(), pitch=tilt,
             roll=rnd.uniform(-10, 10))

    # Skulls: one crowning the heap, two against its sides; faces turned toward the front and the +x side.
    _skull("bones_pile_skull0", (0.0, -0.02, _surf(0, -0.02) + 0.035), -15, bone, hollow, pitch=6, roll=-4, seed=300)
    _skull("bones_pile_skull1", (-0.25, -0.17, 0.0), 20, old, hollow, pitch=-4, roll=8, seed=310)
    _skull("bones_pile_skull3", (0.1, 0.13, _surf(0.1, 0.13) - 0.02), -35, old, hollow, pitch=8, roll=5, seed=330)
    _skull("bones_pile_skull2", (0.25, -0.08, 0.035), -75, bone, hollow, pitch=-10, roll=-6, seed=320)

    # A few bones scattered round the heap: a jaw, a rib, an arm bone and a short shin bone.
    _jaw("bones_pile_jaw", (0.05, -0.36, 0.0), 160, bone)
    _rib("bones_pile_rib_loose", (-0.4, 0.15, 0.0), 75, old)
    _long_bone("bones_pile_loose0", (0.3, 0.27, KNOB_R * 0.75), (0.42, 0.06, KNOB_R * 0.75), old, 0.8, seed=400)
    _long_bone("bones_pile_loose1", (-0.36, -0.3, KNOB_R * 0.7), (-0.12, -0.39, KNOB_R * 0.7), bone, 0.75, seed=410)
