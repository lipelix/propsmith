"""A round leafy shrub: a dense dome of clumped leaf cards around a dark core, on a few short woody stems hidden at the
base, wider than tall (generated by npm run new). Variants: a medium dome, a small dome, a large lopsided bush of three
merged lobes. The cards are shaded in three greens: deep shadow inside and underneath, olive in between, lit
yellow-green on the top and the outer rims."""
import math
import random

from mathutils import Matrix, Vector

from propsmith import prop
from propsmith.materials import material
from propsmith.shapes import blob, box, cylinder

# Overall dimensions (metres), from the description: width across, height.
MID_W, MID_H = 0.8, 0.65
SMALL_W, SMALL_H = 0.6, 0.45
LARGE_W, LARGE_H = 1.0, 0.8

CARD_T = 0.004  # metres, leaf card thickness
CARD_L = 0.085  # metres, leaf card length for the medium bush (scaled per variant)
CARD_W = 0.075  # metres, leaf card width for the medium bush
LIFT = 0.04  # metres, lowest leaf card above the ground
STEM_R = 0.018  # metres, woody stem radius at the ground
STEM_L = 0.22  # metres, woody stem length (medium bush)
TILT = 28  # degrees, seeded tilt of a card off the dome surface
BUMP = 0.14  # fraction of radius a leaf clump bulges out

SHADOW = (0.03, 0.045, 0.016)  # linear RGB, deep shadow green
OLIVE = (0.1, 0.13, 0.035)  # mid olive
LIT = (0.23, 0.26, 0.065)  # lit yellow-green
CORE = (0.022, 0.033, 0.012)  # darker core inside
STEM = (0.11, 0.07, 0.035)  # woody stems

SUN = Vector((0.35, -0.45, 0.82)).normalized()  # where the lit rims face


def _mats():
    return {
        "shadow": material("bush_round_shadow", SHADOW, rough=0.9, vary=0.3, scale=25, crevice=0.6),
        "olive": material("bush_round_olive", OLIVE, rough=0.85, vary=0.3, scale=25, crevice=0.6),
        "lit": material("bush_round_lit", LIT, rough=0.8, vary=0.25, scale=25, crevice=0.4),
        "core": material("bush_round_core", CORE, rough=0.95, vary=0.2, scale=12, crevice=0.7),
        "stem": material("bush_round_stem", STEM, rough=0.9, vary=0.25, scale=30, crevice=0.5),
    }


def _point(obj, tail=0.6):
    """Reshape a leaf card box (corners at +-x, +-y) into a pointed leaf: the tip on +x, a shorter blunt end on -x
    (`tail` of the half-length), widest in the middle. Same vertices and faces, so it stays a closed mesh."""
    for v in obj.data.vertices:
        x, y = v.co.x, v.co.y
        if x > 0 and y > 0:
            v.co.x, v.co.y = x, 0.0
        elif x < 0 < y:
            v.co.x = 0.0
        elif x < 0 and y < 0:
            v.co.x, v.co.y = x * tail, 0.0
        else:
            v.co.x = 0.0
    return obj


def _card(name, centre, normal, length, width, mat, rnd):
    """One leaf card (a thin bevel-free box) lying roughly on the dome, tilted and spun at seeded angles."""
    q =normal.to_track_quat("Z", "Y").to_matrix().to_4x4()
    m = q @ Matrix.Rotation(math.radians(rnd.uniform(-TILT, TILT)), 4, "X") \
        @ Matrix.Rotation(math.radians(rnd.uniform(-TILT, TILT) * 0.6), 4, "Y") \
        @ Matrix.Rotation(math.radians(rnd.uniform(0, 360)), 4, "Z")
    # Keep the card off the ground: lift it so its lowest corner is at LIFT * 0.5 or more.
    low = min((m.to_3x3() @ Vector((sx * length / 2, sy * width / 2, 0))).z for sx in (-1, 1) for sy in (-1, 1))
    c = Vector(centre)
    if c.z + low < LIFT * 0.5:
        c.z = LIFT * 0.5 - low
    obj = _point(box(name, (length, width, CARD_T), tuple(c), mat, bevel=0))
    obj.rotation_euler = m.to_euler()
    return obj


def _fib(n):
    """`n` roughly even unit directions over the sphere."""
    g = math.pi * (3 - math.sqrt(5))
    for i in range(n):
        z = 1 - 2 * (i + 0.5) / n
        r = math.sqrt(1 - z * z)
        yield Vector((r * math.cos(g * i), r * math.sin(g * i), z))


def _inside(p, c, ax):
    """Below 1 when `p` is inside the ellipsoid centred on `c` with semi-axes `ax`."""
    q = p - Vector(c)
    return (q.x / ax[0]) ** 2 + (q.y / ax[1]) ** 2 + (q.z / ax[2]) ** 2


def _bush(prefix, lobes, n_cards, card_scale, stem_l, seed, inner=0.18):
    """A bush of merged ellipsoid lobes, each (centre, (ax, ay, az)), shelled with leaf cards over dark cores."""
    rnd = random.Random(seed)
    mats = _mats()
    length, width = CARD_L * card_scale, CARD_W * card_scale

    # Woody stems: a few short trunks leaning out from the root, mostly hidden under the foliage.
    for i in range(4):
        yaw = 90 * i + rnd.uniform(-25, 25)
        tilt = rnd.uniform(18, 34)
        r = STEM_R * card_scale
        cylinder(f"{prefix}_stem_{i}", r, stem_l * rnd.uniform(0.8, 1.0), (0, 0, r * math.sin(math.radians(tilt))),
                 mats["stem"], r_top=r * 0.45, segments=6, rot=(tilt, 0, yaw), bevel=0)

    # Dark cores fill the gaps between the cards, so the bush reads dark inside.
    for k, (c, ax) in enumerate(lobes):
        r = min(ax) * 0.82
        blob(f"{prefix}_core_{k}", r, (c[0], c[1], c[2] + 0.02), mats["core"],
             squash=(ax[0] * 0.82 / r, ax[1] * 0.82 / r, ax[2] * 0.8 / r), subdiv=1, seed=seed + k, jitter=0.1)

    # Leaf clumps: a few bulges over the shell, so the outline is lumpy, not one smooth blob.
    total = sum(a[0] * a[1] + a[1] * a[2] + a[0] * a[2] for _, a in lobes)
    i = 0
    for k, (c, ax) in enumerate(lobes):
        share = (ax[0] * ax[1] + ax[1] * ax[2] + ax[0] * ax[2]) / total
        n = max(8, round(n_cards * share))
        clumps = [d for d in _fib(9)]
        twist = Matrix.Rotation(rnd.uniform(0, 6.28), 3, "Z")
        clumps = [twist @ d for d in clumps]
        cv = Vector(c)

        def visible(m):
            out = []
            for d in _fib(m):
                if d.z < -0.28:
                    continue  # the flat underside sits on the stems, unseen
                p = cv + Vector((d.x * ax[0], d.y * ax[1], d.z * ax[2]))
                # Points buried inside another lobe stay hidden: skip them.
                if any(_inside(p, c2, ax2) < 0.8 for j, (c2, ax2) in enumerate(lobes) if j != k):
                    continue
                out.append(d)
            return out

        m = n
        while len(visible(m)) < n:
            m += 4
        for d in visible(m):
            bump = max(math.exp(-((d - cl).length ** 2) / 0.12) for cl in clumps)
            rr = 1 + BUMP * (bump - 0.5) + rnd.uniform(-0.03, 0.03)
            p = cv + Vector((d.x * ax[0], d.y * ax[1], d.z * ax[2])) * rr
            normal = Vector((d.x / ax[0], d.y / ax[1], d.z / ax[2])).normalized()
            light = normal.dot(SUN)
            roll = rnd.random()
            if normal.z < 0.0 or light < -0.1 or roll < 0.12:
                key = "shadow"
            elif (light > 0.65 and roll > 0.3) or (normal.z > 0.8 and roll > 0.35):
                key = "lit"
            else:
                key = "olive"
            s = rnd.uniform(0.8, 1.15)
            _card(f"{prefix}_leaf_{i}", p, normal, length * s, width * s, mats[key], rnd)
            i += 1
        # An inner layer of shadow cards a little under the shell deepens the gaps.
        for d in _fib(max(4, round(n_cards * share * inner))):
            if d.z < -0.2:
                continue
            p = cv + Vector((d.x * ax[0], d.y * ax[1], d.z * ax[2])) * 0.84
            normal = Vector((d.x / ax[0], d.y / ax[1], d.z / ax[2])).normalized()
            _card(f"{prefix}_inner_{i}", p, normal, length, width, mats["shadow"], rnd)
            i += 1


def _dome(w, h, card_scale):
    """One lobe: an ellipsoid whose card shell reaches `w` across and `h` high."""
    m = CARD_L * card_scale * 0.35  # leaf cards reach past the shell by about this much
    az = (h - m) * 0.56
    return [((0, 0, h - m - az), (w / 2 - m, w / 2 * 0.94 - m, az))]


@prop
def bush_round():
    _bush("bush_round", _dome(MID_W, MID_H, 1.0), 260, 1.0, STEM_L, 11)


@prop
def bush_round_small():
    s = SMALL_W / MID_W
    _bush("bush_round", _dome(SMALL_W, SMALL_H, s), 185, s, STEM_L * s, 23)


@prop
def bush_round_large():
    w, h = LARGE_W / 2, LARGE_H
    # Three merged lobes, the biggest off-centre and tallest, so the bush leans a little.
    lobes = [
        ((0.1, 0.04, h * 0.5), (w * 0.72, w * 0.64, h * 0.45)),
        ((-0.2, -0.03, h * 0.35), (w * 0.54, w * 0.5, h * 0.31)),
        ((0.05, -0.17, h * 0.32), (w * 0.5, w * 0.44, h * 0.29)),
    ]
    _bush("bush_round", lobes, 290, 1.05, STEM_L * 1.2, 37, inner=0.08)
